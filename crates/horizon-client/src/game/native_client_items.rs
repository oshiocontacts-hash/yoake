use super::Game;

#[allow(dead_code)]
impl Game<'_> {
    /// Whether this is a block-backed item, not a Java class identity check.
    /// @API:client_item_queries@.
    pub(super) fn native_item_is_block(&self, item: &str) -> bool {
        self.items()
            .get(item)
            .is_some_and(|info| info.block.is_some())
    }

    /// Query only the current connection's server-synchronized item tags.
    /// Unknown items, unknown tags and unavailable data return false.
    /// @API:client_item_queries@.
    pub(super) fn native_client_item_in_tag(&self, tag: &str, item: &str) -> bool {
        self.remote.as_ref().is_some_and(|remote| {
            remote.reconfiguring.is_none()
                && remote.registries.item_in_tag(&remote.builtin, tag, item)
        })
    }

    /// Whether the current connection has received its requested item tags.
    /// An empty synchronized table is ready; disconnected or reconfiguring is not.
    /// @API:client_item_queries@.
    pub(super) fn native_client_item_tags_ready(&self) -> bool {
        self.remote.as_ref().is_some_and(|remote| {
            remote.reconfiguring.is_none() && remote.registries.item_tags.is_some()
        })
    }
}

/// MX3R1: the one hook whose argument 0 is the `Game` root. With the feature on, a mod's hook runs here
/// with a root handle; through generated `Game.<name>#handle` bindings it gets path handles to
/// entities (`Game.dropped[id]`, ...), valid until this call returns. Hooks on any other function
/// (`ArmorStand::tick_settle`, ...) never see the root: their caller already holds an outer `&mut`.
/// It runs on the integrated-server thread once per tick at `ServerTickStart` (`native_lifecycle.rs`, one
/// call site), before the entity ticks; it is hook id `HOOK_SERVER_TICK`, so a guest that did not
/// register it is not entered, and with no mod installed it costs one thread-local read.
#[cfg(feature = "yoake2-slice")]
impl Game<'_> {
    pub fn yoake2_server_tick(&mut self) {
        yoake_slice::runtime::dispatch_root_id(yoake_slice::runtime::HOOK_SERVER_TICK, self, &mut |_game| 0);
    }
}

/// The call site's method (`native_lifecycle.rs` may not contain a `cfg`): the Game-root hook with the
/// feature, nothing without it.
#[cfg(feature = "yoake2-slice")]
impl Game<'_> {
    pub(super) fn yoake2_tick_hook(&mut self) {
        self.yoake2_server_tick();
    }
}

#[cfg(not(feature = "yoake2-slice"))]
impl Game<'_> {
    #[inline(always)]
    pub(super) fn yoake2_tick_hook(&mut self) {}
}

/// World start (`native_lifecycle.rs` may not contain a `cfg`, so its call site is this method): with the
/// feature, an integrated-server or dedicated world loads the allowed full-access mods of `<game root>/mods`
/// and installs the `engine_call` table; without it, nothing.
#[cfg(feature = "yoake2-slice")]
impl Game<'_> {
    pub(super) fn yoake2_world_start_hook(&mut self) {
        use super::execution_role::ExecutionRole;
        let serves = self.options.dedicated.is_some() || matches!(self.options.execution_role, ExecutionRole::IntegratedServer);
        if !serves {
            return;
        }
        if let Some(root) = crate::yak_mods::game_root() {
            yoake2_install_dispatch();
            crate::yoake2_mods::load_world_mods(&root.join("mods"), crate::yoake2_mods::Control::path_from_process().as_deref());
        }
    }
}

#[cfg(not(feature = "yoake2-slice"))]
impl Game<'_> {
    #[inline(always)]
    pub(super) fn yoake2_world_start_hook(&mut self) {}
}

/// What `engine_call` dispatches through: the `Game` path-handle bindings, then the entities and items
/// modules (ids are disjoint through the one lock file).
#[cfg(feature = "yoake2-slice")]
pub(crate) fn yoake2_dispatch(handle: u64, id: u32, args: &[u8], out: &mut Vec<u8>) -> Result<(), yoake_slice::codec::CallError> {
    use yoake_slice::codec::CallError;
    match yoake_glue::call(handle, id, args, out) {
        Err(CallError::UnknownBinding(_)) => {}
        other => return other,
    }
    match horizon_client_lib::entities::yoake_glue::call(handle, id, args, out) {
        Err(CallError::UnknownBinding(_)) => {}
        other => return other,
    }
    horizon_client_lib::items::yoake_glue::call(handle, id, args, out)
}

/// Registers [`yoake2_dispatch`] as the table behind the `engine_call` import (process-wide, idempotent).
#[cfg(feature = "yoake2-slice")]
pub(crate) fn yoake2_install_dispatch() {
    yoake_slice::runtime::set_engine_dispatch(Some(yoake2_dispatch));
}

