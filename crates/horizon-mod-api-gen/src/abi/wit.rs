fn service_signature(service: &Service) -> Result<(&'static str, &'static str), String> {
    Ok(match (service.name.as_str(), service.kind.as_str()) {
        ("log", "log") => ("logging", "log: func(target: string, message: string) -> result<_, host-error>"),
        ("feedback", "feedback") => ("feedback", "feedback: func(text: string) -> result<_, host-error>"),
        ("client_world_key", "world") => ("client-world", "client-world-key: func() -> result<option<world-key>, host-error>"),
        ("text", "text") => ("hud", "text: func(text: string, at: point, rgb: u32, shadow: bool) -> result<_, host-error>"),
        ("fill", "rect") => ("hud", "fill: func(bounds: rect, argb: u32) -> result<_, host-error>"),
        ("net_send_to_server", "net") => ("network", "net-send-to-server: func(channel: string, data: list<u8>) -> result<_, send-error>"),
        ("setting", "get") => ("settings", "setting: func(key: string) -> result<option<string>, host-error>"),
        ("set_setting", "set") => ("settings", "set-setting: func(key: string, value: string) -> result<_, host-error>"),
        ("text_width", "width") => ("hud", "text-width: func(text: string) -> result<option<f32>, host-error>"),
        ("local_player_snapshot", "player") => ("player", "local-player-snapshot: func() -> result<option<player-snapshot>, host-error>"),
        ("snapshot_client_world", "snapshot") => ("client-world", "snapshot-client-world: func() -> result<world-snapshot, host-error>"),
        ("playing", "bool") => ("client-world", "playing: func() -> result<bool, host-error>"),
        ("instance_dir", "output") => ("instance", "instance-dir: func() -> result<string, host-error>"),
        ("account", "account") => ("accounts", "account: func() -> result<option<account-snapshot>, host-error>"),
        ("mod_screen_open", "screen_open") => ("screen", "mod-screen-open: func(mod-id: string) -> result<bool, host-error>"),
        ("mod_screen_close", "screen_close") => ("screen", "mod-screen-close: func(mod-id: string) -> result<_, host-error>"),
        ("mod_screen", "output") => ("screen", "mod-screen: func() -> result<option<string>, host-error>"),
        ("mod_screen_open_anywhere", "screen_open") => ("screen", "mod-screen-open-anywhere: func(mod-id: string) -> result<bool, host-error>"),
        ("batch_len", "internal_len") => ("hud", "batch-len: func() -> result<u64, host-error>"),
        ("batch_scale_since", "internal_scale") => ("hud", "batch-scale-since: func(start: u64, origin: point, scale: point) -> result<_, host-error>"),
        ("batch_clip_since", "internal_clip") => ("hud", "batch-clip-since: func(start: u64, bounds: rect) -> result<_, host-error>"),
        ("batch_tint_since", "internal_tint") => ("hud", "batch-tint-since: func(start: u64, alpha: f32) -> result<_, host-error>"),
        ("gui_texture", "texture") | ("gui_texture_create", "texture_create") | ("gui_texture_release", "internal_release") => ("hud", ""),
        _ => return Err(format!("unknown WIT service {} ({})", service.name, service.kind)),
    })
}

fn hook_signature(hook: &Hook) -> Result<(&'static str, &'static str), String> {
    let arguments = match hook.event.as_str() {
        "TickEvent" => "reserved: u32",
        "KeyEvent" => "key: string, pressed: bool",
        "HudEvent" => "",
        "NetEvent" => "channel: string, data: list<u8>",
        "FrameEvent" => "elapsed-ns: u64",
        "NetFramesListenedEvent" => "listened: bool",
        "NetFrameReceived" => "frame: received-frame",
        "NetSessionEndedEvent" => "session: u64, reason: string",
        "GuiLayerEvent" => "layer: string",
        "ScreenRenderEvent" => "screen: screen-view",
        "ScreenKeyEvent" => "screen: screen-view, key: string, repeat: bool, modifiers: u32",
        "ScreenCharEvent" => "screen: screen-view, character: u32, modifiers: u32",
        "ScreenMouseButtonEvent" => "screen: screen-view, button: s32, modifiers: u32",
        "ScreenScrollEvent" => "screen: screen-view, scroll: tuple<f64, f64>, modifiers: u32",
        "SettingsEvent" => "mod-id: string",
        "SettingsClickEvent" => "mod-id: string, button: u64",
        other => return Err(format!("unknown WIT hook event {other}")),
    };
    let result = match (hook.name.as_str(), hook.event.as_str(), hook.contract.as_str()) {
        ("net_frames_listened", "NetFramesListenedEvent", "listen") => " -> bool",
        (_, "NetFramesListenedEvent", _) | ("net_frames_listened", _, _) => {
            return Err("invalid net_frames_listened hook".into());
        }
        (_, _, "listen") => "",
        (_, _, "cancel") => " -> bool",
        (_, "SettingsEvent", "collect") => " -> list<string>",
        _ => return Err(format!("unsupported WIT hook contract {} ({})", hook.name, hook.contract)),
    };
    Ok((arguments, result))
}

pub fn generate_wit() -> Result<String, String> {
    render_wit(&subset()?)
}

fn render_wit(subset: &Subset) -> Result<String, String> {
    if subset.abi_version != 2 {
        return Err("this WIT generator implements ABI version 2 only".into());
    }
    let mut service_names = HashSet::new();
    let mut services = Vec::new();
    for service in subset.services.iter().filter(|service| service.abi) {
        if !service_names.insert(service.name.as_str()) {
            return Err(format!("duplicate ABI service name {}", service.name));
        }
        services.push(service_signature(service)?);
    }
    let textures = ["gui_texture", "gui_texture_create", "gui_texture_release"];
    let texture_count = textures.iter().filter(|name| service_names.contains(**name)).count();
    if texture_count != 0 && texture_count != textures.len() {
        return Err("GUI texture services must be emitted together".into());
    }

    let mut output = String::from(TYPES);
    let mut imports = Vec::new();
    for &(group, types) in GROUPS {
        if !services.iter().any(|(service_group, _)| *service_group == group) {
            continue;
        }
        imports.push(group);
        output.push_str(&format!("interface {group} {{\n    use types.{{{types}}};\n\n"));
        for (_, signature) in services.iter().filter(|(service_group, _)| *service_group == group) {
            if !signature.is_empty() {
                output.push_str(&format!("    {signature};\n"));
            }
        }
        if group == "hud" && texture_count != 0 {
            output.push_str(TEXTURE);
        }
        output.push_str("}\n\n");
    }

    output.push_str("interface hooks {\n    use types.{screen-view, received-frame};\n\n");
    let mut hook_names = HashSet::new();
    for hook in subset.hooks.iter().filter(|hook| hook.abi) {
        let name = hook.name.replace('_', "-");
        if !hook_names.insert(name.clone()) {
            return Err(format!("duplicate WIT hook name {name}"));
        }
        let (arguments, result) = hook_signature(hook)?;
        if hook.name == "net_frames_listened" {
            output.push_str("    /// Returns the listened result; the host ORs it with the current value.\n");
        } else if hook.contract == "cancel" {
            output.push_str("    /// Returns true to cancel the event.\n");
        }
        output.push_str(&format!("    {name}: func({arguments}){result};\n"));
    }
    output.push_str("}\n\nworld client-mod {\n    import types;\n");
    for group in imports {
        output.push_str(&format!("    import {group};\n"));
    }
    output.push_str("    export hooks;\n    /// Returns catalog hook names with underscores, such as `net_frames_listened`.\n    export init: func() -> list<string>;\n}\n");
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn generated_wit_matches_catalog_and_parses() {
        let generated = generate_wit().expect("generate WIT");
        assert_eq!(generated, generate_wit().expect("regenerate WIT"));
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../yoake-wasm/wit/yoake-mod.wit");
        let committed = std::fs::read_to_string(path).expect("read generated WIT");
        assert_eq!(generated, committed.replace("\r\n", "\n"));
        let mut resolve = wit_parser::Resolve::default();
        let package = resolve.push_str("yoake-mod.wit", &generated).expect("parse WIT");
        resolve.select_world(&[package], Some("client-mod")).expect("find world");
    }

    #[test]
    fn catalog_controls_exports_and_service_imports() {
        let mut catalog = subset().expect("read catalog");
        catalog.hooks.iter_mut().find(|hook| hook.name == "net_from_server").unwrap().abi = false;
        catalog.services.iter_mut().find(|service| service.name == "set_setting").unwrap().abi = false;
        let wit = render_wit(&catalog).expect("generate WIT");
        assert!(!wit.contains("    net-from-server: func("));
        assert!(wit.contains("    net-frame-received: func("));
        assert!(!wit.contains("    set-setting: func("));
        assert!(wit.contains("    setting: func("));
        assert!(wit.contains("    net-frames-listened: func(listened: bool) -> bool;"));
        assert!(wit.contains("    gui-layer-pre: func(layer: string) -> bool;"));
        assert!(wit.contains("    settings: func(mod-id: string) -> list<string>;"));
    }

    #[test]
    fn incomplete_texture_services_are_rejected() {
        let mut catalog = subset().expect("read catalog");
        catalog.services.retain(|service| service.name != "gui_texture_release");
        assert!(render_wit(&catalog).is_err());
    }

    #[test]
    fn unsupported_abi_version_is_rejected() {
        let mut catalog = subset().expect("read catalog");
        catalog.abi_version = 3;
        assert!(render_wit(&catalog).is_err());
    }
}
