//! REM-11 part 1: call-site hooks across the stamped crates without rewriting the committed sources.
//!
//! `callsite-patch` runs the normal call-site `apply` (THIR, the matcher, the shims: `callsite.rs`) on a scratch copy
//! of a crate, writes the ledger sites for real, and stores the difference between the copy and the original as a
//! line patch, `hook-ledger/<crate>.callsites.patch`. The stamping overlay (`overlay.rs`) applies that patch to its
//! copy of the sources **before** the function stamps, exactly where the in-place rewrite of `entities` and
//! `game::item_use` already sits, so the rest of the pipeline sees the same source. The committed tree stays
//! unstamped and a build needs no THIR.
//!
//! A hunk carries its own context lines and is searched for near its recorded line, so unrelated edits above it
//! do not matter. A hunk whose lines changed no longer applies: it is skipped with a warning (that site is then
//! simply not hooked in the build; the ledger entry stays), and the weekly `callsite-patch` run regenerates it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The patch of a crate lives next to its ledger shard; the overlay cache key hashes every file of that directory.
pub fn patch_path(ledger: &Path, crate_ident: &str) -> PathBuf {
    ledger.join(format!("{crate_ident}.callsites.patch"))
}

const CONTEXT: usize = 3;
/// The line that opens the generated shim block (`callsite.rs`, `SHIM_HEADER`).
const SHIM_HEADER_PREFIX: &str = "// Generated by yoake-hook-codemod: call-site shims";

/// The lines of `text` without terminators, whether the text ended in a newline, and whether it used `\r\n`.
struct Lines {
    lines: Vec<String>,
    final_newline: bool,
    crlf: bool,
}

fn split(text: &str) -> Lines {
    let crlf = text.contains("\r\n");
    let final_newline = text.ends_with('\n');
    let mut lines: Vec<String> = text.split('\n').map(|l| l.strip_suffix('\r').unwrap_or(l).to_string()).collect();
    if final_newline {
        lines.pop();
    }
    Lines { lines, final_newline, crlf }
}

fn join(lines: &[String], final_newline: bool, crlf: bool) -> String {
    let nl = if crlf { "\r\n" } else { "\n" };
    let mut out = lines.join(nl);
    if final_newline && !lines.is_empty() {
        out.push_str(nl);
    }
    out
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Op {
    Equal,
    Delete,
    Insert,
}

/// Myers' O(ND) diff of two line lists, as one op per line (an Equal consumes a line of both).
fn diff_ops(a: &[String], b: &[String]) -> Result<Vec<Op>, String> {
    let mut prefix = 0;
    while prefix < a.len() && prefix < b.len() && a[prefix] == b[prefix] {
        prefix += 1;
    }
    let mut suffix = 0;
    while suffix < a.len() - prefix && suffix < b.len() - prefix && a[a.len() - 1 - suffix] == b[b.len() - 1 - suffix] {
        suffix += 1;
    }
    let (a_mid, b_mid) = (&a[prefix..a.len() - suffix], &b[prefix..b.len() - suffix]);
    let mut ops = vec![Op::Equal; prefix];
    ops.extend(myers(a_mid, b_mid)?);
    ops.extend(std::iter::repeat_n(Op::Equal, suffix));
    Ok(ops)
}

fn myers(a: &[String], b: &[String]) -> Result<Vec<Op>, String> {
    let (n, m) = (a.len() as isize, b.len() as isize);
    if n == 0 {
        return Ok(vec![Op::Insert; b.len()]);
    }
    if m == 0 {
        return Ok(vec![Op::Delete; a.len()]);
    }
    let max = n + m;
    // `v[k + max]` = furthest x on diagonal k; a snapshot of the live range per d for the backtrace
    let mut v = vec![0isize; (2 * max + 2) as usize];
    let mut trace: Vec<Vec<isize>> = Vec::new();
    let mut found = None;
    'outer: for d in 0..=max {
        if d > 6000 {
            return Err(format!("the line diff needs more than {d} edits in one file region; split the change"));
        }
        trace.push((-d..=d).map(|k| v[(k + max) as usize]).collect());
        let mut k = -d;
        while k <= d {
            let idx = (k + max) as usize;
            let mut x = if k == -d || (k != d && v[idx - 1] < v[idx + 1]) { v[idx + 1] } else { v[idx - 1] + 1 };
            let mut y = x - k;
            while x < n && y < m && a[x as usize] == b[y as usize] {
                x += 1;
                y += 1;
            }
            v[idx] = x;
            if x >= n && y >= m {
                found = Some(d);
                break 'outer;
            }
            k += 2;
        }
    }
    let d_end = found.ok_or("diff did not converge")?;
    // backtrace: `trace[d]` holds the v of the step before d, on k in -d..=d
    let mut ops = Vec::new();
    let (mut x, mut y) = (n, m);
    for d in (1..=d_end).rev() {
        let prev = &trace[d as usize];
        let at = |k: isize| prev[(k + d) as usize];
        let k = x - y;
        let prev_k = if k == -d || (k != d && at(k - 1) < at(k + 1)) { k + 1 } else { k - 1 };
        let prev_x = at(prev_k);
        let prev_y = prev_x - prev_k;
        while x > prev_x && y > prev_y {
            ops.push(Op::Equal);
            x -= 1;
            y -= 1;
        }
        if x == prev_x {
            ops.push(Op::Insert);
        } else {
            ops.push(Op::Delete);
        }
        x = prev_x;
        y = prev_y;
    }
    while x > 0 && y > 0 {
        ops.push(Op::Equal);
        x -= 1;
        y -= 1;
    }
    ops.reverse();
    Ok(ops)
}

/// Splits a line list at the shim header (the generated block is appended at the end of a file).
fn split_shims(lines: &[String]) -> (&[String], &[String]) {
    match lines.iter().position(|l| l.starts_with(SHIM_HEADER_PREFIX)) {
        Some(i) => lines.split_at(i),
        None => (lines, &[]),
    }
}

/// The line patch from `old` to `new` of the file `rel` (workspace-relative, forward slashes); `None` when equal.
/// Hunks use `@@ -<old start> @@` and prefix lines with ` `, `-`, `+`; the text is LF-only whatever the files use.
pub fn make_patch(rel: &str, old: &str, new: &str) -> Result<Option<String>, String> {
    if old == new {
        return Ok(None);
    }
    let (old_l, new_l) = (split(old), split(new));
    // the call rewrites and the appended shim block are diffed apart: a crate with hundreds of sites in one file
    // would otherwise make the block of added lines a very long edit script
    let (old_body, old_shims) = split_shims(&old_l.lines);
    let (new_body, new_shims) = split_shims(&new_l.lines);
    let mut ops = diff_ops(old_body, new_body)?;
    ops.extend(diff_ops(old_shims, new_shims)?);
    let mut all_old: Vec<&str> = old_body.iter().chain(old_shims).map(String::as_str).collect();
    let mut all_new: Vec<&str> = new_body.iter().chain(new_shims).map(String::as_str).collect();
    all_old.reverse();
    all_new.reverse();

    // one entry per op with the line text, in file order
    let mut lines: Vec<(Op, &str, usize)> = Vec::new();
    let mut old_no = 0usize;
    for op in &ops {
        match op {
            Op::Equal => {
                let t = all_old.pop().ok_or("diff out of step")?;
                all_new.pop();
                old_no += 1;
                lines.push((Op::Equal, t, old_no));
            }
            Op::Delete => {
                let t = all_old.pop().ok_or("diff out of step")?;
                old_no += 1;
                lines.push((Op::Delete, t, old_no));
            }
            Op::Insert => {
                let t = all_new.pop().ok_or("diff out of step")?;
                lines.push((Op::Insert, t, old_no + 1));
            }
        }
    }
    let changed: Vec<usize> = (0..lines.len()).filter(|&i| lines[i].0 != Op::Equal).collect();
    let mut out = String::new();
    let _ = writeln!(out, "--- a/{rel}");
    let _ = writeln!(out, "+++ b/{rel}");
    let mut i = 0;
    while i < changed.len() {
        let mut j = i;
        while j + 1 < changed.len() && changed[j + 1] - changed[j] <= 2 * CONTEXT + 1 {
            j += 1;
        }
        let from = changed[i].saturating_sub(CONTEXT);
        let to = (changed[j] + CONTEXT + 1).min(lines.len());
        let start = lines[from..to].iter().find(|l| l.0 != Op::Insert).map_or(lines[from].2, |l| l.2);
        let _ = writeln!(out, "@@ -{start} @@");
        for (op, text, _) in &lines[from..to] {
            let sign = match op {
                Op::Equal => ' ',
                Op::Delete => '-',
                Op::Insert => '+',
            };
            let _ = writeln!(out, "{sign}{text}");
        }
        i = j + 1;
    }
    if !new_l.final_newline && new_l.lines.last().is_some() {
        let _ = writeln!(out, "\\ no newline at end of file");
    }
    Ok(Some(out))
}

struct Hunk {
    start: usize,
    old: Vec<String>,
    new: Vec<String>,
}

fn parse_patch(text: &str) -> Result<BTreeMap<String, (Vec<Hunk>, bool)>, String> {
    let mut files: BTreeMap<String, (Vec<Hunk>, bool)> = BTreeMap::new();
    let mut current: Option<String> = None;
    for raw in text.lines() {
        if let Some(path) = raw.strip_prefix("--- a/") {
            current = Some(path.to_string());
            files.entry(path.to_string()).or_default();
        } else if raw.starts_with("+++ b/") {
            continue;
        } else if let Some(header) = raw.strip_prefix("@@ -") {
            let start: usize = header.trim_end_matches(" @@").parse().map_err(|_| format!("bad hunk header '{raw}'"))?;
            let file = current.clone().ok_or("hunk before a file header")?;
            files.get_mut(&file).unwrap().0.push(Hunk { start, old: Vec::new(), new: Vec::new() });
        } else if raw.starts_with("\\ no newline") {
            if let Some(file) = &current {
                files.get_mut(file).unwrap().1 = true;
            }
        } else if let Some(file) = &current {
            let Some(hunk) = files.get_mut(file).unwrap().0.last_mut() else { continue };
            let (sign, rest) = raw.split_at(raw.chars().next().map_or(0, char::len_utf8));
            match sign {
                " " => {
                    hunk.old.push(rest.to_string());
                    hunk.new.push(rest.to_string());
                }
                "-" => hunk.old.push(rest.to_string()),
                "+" => hunk.new.push(rest.to_string()),
                "" => {
                    // a context line that was empty lost its leading space in an editor
                    hunk.old.push(String::new());
                    hunk.new.push(String::new());
                }
                other => return Err(format!("bad patch line '{other}{rest}'")),
            }
        }
    }
    Ok(files)
}

/// Result of applying one patch file to a tree.
#[derive(Default, Debug)]
pub struct ApplyReport {
    pub hunks: usize,
    pub applied: usize,
    pub skipped: Vec<String>,
}

fn find_hunk(lines: &[String], hunk: &Hunk, floor: usize) -> Option<usize> {
    let want = hunk.start.saturating_sub(1);
    let fits = |at: usize| at >= floor && at + hunk.old.len() <= lines.len() && lines[at..at + hunk.old.len()] == hunk.old[..];
    // nearest match to the recorded line, searching outward
    let limit = lines.len();
    for dist in 0..=limit {
        for at in [want.checked_sub(dist), want.checked_add(dist)].into_iter().flatten() {
            if fits(at) {
                return Some(at);
            }
        }
    }
    None
}

/// Applies the hunks of `patch_text` to the files under `root` (the overlay copy). A file that is missing, or a hunk
/// that no longer fits, is skipped and reported; the rest applies.
pub fn apply_patch_text(patch_text: &str, root: &Path) -> Result<ApplyReport, String> {
    let files = parse_patch(patch_text)?;
    let mut report = ApplyReport::default();
    for (rel, (hunks, _no_newline)) in files {
        report.hunks += hunks.len();
        let path = root.join(&rel);
        let Ok(text) = std::fs::read_to_string(&path) else {
            report.skipped.push(format!("{rel}: file not found ({} hunk(s))", hunks.len()));
            continue;
        };
        let src = split(&text);
        let mut lines = src.lines.clone();
        let mut floor = 0usize;
        // hunks apply in file order; each searches from the end of the previous one, so a shifted file still works
        let mut shift: isize = 0;
        let mut applied_here = 0;
        for hunk in &hunks {
            let adjusted = Hunk { start: (hunk.start as isize + shift).max(1) as usize, old: hunk.old.clone(), new: hunk.new.clone() };
            match find_hunk(&lines, &adjusted, floor) {
                Some(at) => {
                    lines.splice(at..at + hunk.old.len(), hunk.new.iter().cloned());
                    floor = at + hunk.new.len();
                    shift = at as isize + 1 - hunk.start as isize + hunk.new.len() as isize - hunk.old.len() as isize;
                    applied_here += 1;
                }
                None => report.skipped.push(format!("{rel}: hunk at line {} no longer fits", hunk.start)),
            }
        }
        report.applied += applied_here;
        if applied_here > 0 {
            std::fs::write(&path, join(&lines, src.final_newline || !lines.is_empty(), src.crlf)).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
        }
    }
    Ok(report)
}

/// The overlay step: applies `<ledger>/<crate>.callsites.patch` (if there is one) to the overlay root.
/// Returns the number of applied hunks (0 without a patch). Skipped hunks go to stderr.
pub fn apply_for_crate(ledger: &Path, crate_ident: &str, overlay_root: &Path) -> Result<usize, String> {
    let path = patch_path(ledger, crate_ident);
    let Ok(text) = std::fs::read_to_string(&path) else { return Ok(0) };
    let report = apply_patch_text(&text, overlay_root)?;
    for line in &report.skipped {
        eprintln!("yoake-stamp: {crate_ident}: call-site patch: {line} (that site is not hooked in this build; run `callsite-patch` again)");
    }
    Ok(report.applied)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("yoake-cs-patch-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn sample(n: usize) -> String {
        (0..n).map(|i| format!("fn f{i}() {{ self.g{i}(); }}\n")).collect()
    }

    #[test]
    fn a_patch_reproduces_the_new_text_and_survives_unrelated_edits_above() {
        let old = sample(60);
        let mut new = old.replace("self.g10();", "__yoake_cs_1(self);").replace("self.g40();", "__yoake_cs_2(self);");
        new.push_str("\n// Generated by yoake-hook-codemod: call-site shims (hook-ledger). Do not edit by hand.\nfn __yoake_cs_1() {}\nfn __yoake_cs_2() {}\n");
        let patch = make_patch("src/a.rs", &old, &new).unwrap().unwrap();
        assert!(patch.starts_with("--- a/src/a.rs\n+++ b/src/a.rs\n@@ -"), "{patch}");
        assert_eq!(patch.matches("\n@@ -").count(), 3, "two call rewrites and the block: {patch}");

        let dir = tmp("roundtrip");
        std::fs::create_dir_all(dir.join("src")).unwrap();
        std::fs::write(dir.join("src/a.rs"), &old).unwrap();
        let report = apply_patch_text(&patch, &dir).unwrap();
        assert_eq!((report.hunks, report.applied), (3, 3), "{report:?}");
        assert_eq!(std::fs::read_to_string(dir.join("src/a.rs")).unwrap(), new);

        // 5 lines added at the top: the hunks are found near their recorded lines
        std::fs::write(dir.join("src/a.rs"), format!("// a\n// b\n// c\n// d\n// e\n{old}")).unwrap();
        let report = apply_patch_text(&patch, &dir).unwrap();
        assert_eq!(report.applied, 3, "{report:?}");
        assert_eq!(std::fs::read_to_string(dir.join("src/a.rs")).unwrap(), format!("// a\n// b\n// c\n// d\n// e\n{new}"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_hunk_whose_lines_changed_is_skipped_and_the_others_apply() {
        let old = sample(60);
        let new = old.replace("self.g10();", "__yoake_cs_1(self);").replace("self.g40();", "__yoake_cs_2(self);");
        let patch = make_patch("src/a.rs", &old, &new).unwrap().unwrap();
        let dir = tmp("skip");
        std::fs::create_dir_all(dir.join("src")).unwrap();
        std::fs::write(dir.join("src/a.rs"), old.replace("self.g10();", "self.other();")).unwrap();
        let report = apply_patch_text(&patch, &dir).unwrap();
        assert_eq!((report.hunks, report.applied), (2, 1), "{report:?}");
        assert!(report.skipped.iter().any(|s| s.contains("no longer fits")), "{report:?}");
        let text = std::fs::read_to_string(dir.join("src/a.rs")).unwrap();
        assert!(text.contains("self.other();") && text.contains("__yoake_cs_2(self);") && !text.contains("__yoake_cs_1"), "{text}");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn crlf_files_stay_crlf_and_an_equal_pair_makes_no_patch() {
        let old = "a\nb\nc\nd\n";
        let new = "a\nB\nc\nd\n";
        assert!(make_patch("x.rs", old, old).unwrap().is_none());
        let patch = make_patch("x.rs", old, new).unwrap().unwrap();
        assert!(!patch.contains('\r'), "the patch is LF-only");
        let dir = tmp("crlf");
        std::fs::write(dir.join("x.rs"), "a\r\nb\r\nc\r\nd\r\n").unwrap();
        assert_eq!(apply_patch_text(&patch, &dir).unwrap().applied, 1);
        assert_eq!(std::fs::read_to_string(dir.join("x.rs")).unwrap(), "a\r\nB\r\nc\r\nd\r\n");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn a_missing_file_is_reported_not_fatal_and_diff_handles_inserts_and_deletes() {
        let report = apply_patch_text("--- a/nope.rs\n+++ b/nope.rs\n@@ -1 @@\n-x\n+y\n", &std::env::temp_dir()).unwrap();
        assert_eq!((report.applied, report.skipped.len()), (0, 1));
        let a: Vec<String> = ["1", "2", "3", "4", "5"].iter().map(|s| s.to_string()).collect();
        let b: Vec<String> = ["1", "3", "x", "4", "5", "6"].iter().map(|s| s.to_string()).collect();
        let ops = diff_ops(&a, &b).unwrap();
        assert_eq!(ops.iter().filter(|o| **o == Op::Equal).count(), 4);
        assert_eq!(ops.iter().filter(|o| **o == Op::Delete).count(), 1);
        assert_eq!(ops.iter().filter(|o| **o == Op::Insert).count(), 2);
    }
}

/// `callsite-patch` arguments (see [`generate`]).
pub struct GenerateArgs {
    pub workspace_root: PathBuf,
    pub ledger: PathBuf,
    pub stamp_config: PathBuf,
    pub crate_name: String,
    /// The THIR dump of the crate (`yoake-hook-thir dump`), made from the committed (unstamped) sources.
    pub thir: PathBuf,
    /// Where the scratch copy of the crate's sources goes (rewritten there, never in the tree).
    pub scratch: PathBuf,
}

/// Runs the call-site `apply` on a scratch copy of the crate named in the stamp config (the ledger gets the sites,
/// the tree is untouched) and writes `<ledger>/<crate>.callsites.patch` from the difference. Returns
/// `(files changed, hunks)`; with no change the patch file is removed.
pub fn generate(args: &GenerateArgs) -> Result<(usize, usize), String> {
    let workspace = args.workspace_root.canonicalize().map_err(|e| format!("{}: {e}", args.workspace_root.display()))?;
    let ident = crate::key::normalize_crate_name(&args.crate_name);
    let text = std::fs::read_to_string(&args.stamp_config).map_err(|e| format!("failed to read {}: {e}", args.stamp_config.display()))?;
    let crate_rel = text
        .lines()
        .map(|l| l.split('#').next().unwrap_or("").split_whitespace().collect::<Vec<_>>())
        .find(|p| p.len() >= 3 && crate::key::normalize_crate_name(p[1]) == ident)
        .map(|p| PathBuf::from(p[0]))
        .ok_or_else(|| format!("no line for crate '{}' in {}", args.crate_name, args.stamp_config.display()))?;
    let crate_root = workspace.join(&crate_rel).canonicalize().map_err(|e| format!("{}: {e}", crate_rel.display()))?;
    let (_, files) = crate::overlay::source_closure(&crate_root, &args.crate_name)?;
    let _ = std::fs::remove_dir_all(&args.scratch);
    let mut rels = Vec::new();
    for file in &files {
        let file = file.canonicalize().map_err(|e| format!("{}: {e}", file.display()))?;
        let rel = file.strip_prefix(&workspace).map_err(|_| format!("{} is outside the workspace", file.display()))?.to_path_buf();
        let dest = args.scratch.join(&rel);
        std::fs::create_dir_all(dest.parent().unwrap()).map_err(|e| format!("{}: {e}", dest.display()))?;
        std::fs::copy(&file, &dest).map_err(|e| format!("copy {}: {e}", file.display()))?;
        rels.push((file, rel));
    }
    let mut modules = Vec::new();
    let mut exclude = Vec::new();
    let (mut min_stmts, mut private_types, mut bridges) = (0usize, false, false);
    crate::apply_stamp_config(&args.stamp_config, &args.crate_name, &mut modules, &mut exclude, &mut min_stmts, &mut private_types, &mut bridges)?;
    let scratch_root = args.scratch.join(&crate_rel);
    let modules = crate::modules::expand_star_modules(&scratch_root, &args.crate_name, &modules, &exclude)?;
    let config = crate::Config {
        mode: crate::Mode::Apply,
        crate_root: scratch_root,
        crate_name: args.crate_name.clone(),
        ledger: args.ledger.clone(),
        modules,
        shallow: false,
        renames: vec![],
        tombstones: vec![],
        callsites: true,
        thir: Some(args.thir.clone()),
        accept_sites: vec![],
        rename_sites: vec![],
        tombstone_sites: vec![],
        engine_crates: None,
        retire_ineligible: false,
        rustfmt: false,
        exclude_modules: exclude,
        min_stmts,
        verify: false,
        verify_args: vec![],
        verify_dir: PathBuf::from("."),
        verify_rounds: 1,
        verify_max_withdraw: 0,
        frozen_ledger: false,
        private_types,
        overlay: false,
    };
    crate::callsite::execute(&config)?;

    let mut patch = String::new();
    let (mut changed, mut hunks) = (0, 0);
    let mut sorted = rels;
    sorted.sort_by(|a, b| a.1.cmp(&b.1));
    for (original, rel) in &sorted {
        let old = std::fs::read_to_string(original).map_err(|e| format!("{}: {e}", original.display()))?;
        let new = std::fs::read_to_string(args.scratch.join(rel)).map_err(|e| format!("{}: {e}", rel.display()))?;
        let rel_text = rel.to_string_lossy().replace('\\', "/");
        if let Some(text) = make_patch(&rel_text, &old, &new)? {
            changed += 1;
            hunks += text.matches("\n@@ -").count();
            patch.push_str(&text);
        }
    }
    let path = patch_path(&args.ledger, &ident);
    if patch.is_empty() {
        let _ = std::fs::remove_file(&path);
    } else {
        std::fs::write(&path, patch).map_err(|e| format!("cannot write {}: {e}", path.display()))?;
    }
    Ok((changed, hunks))
}
