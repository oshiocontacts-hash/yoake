#[derive(Default)]
struct CallsiteSummary {
    joined: usize,
    eligible: usize,
    rewritten: usize,
    excluded_by_reason: BTreeMap<String, usize>,
    unjoined_thir: Vec<String>,
    unjoined_syn: Vec<String>,
}

impl CallsiteSummary {
    fn exclude(&mut self, reason: &str) {
        *self
            .excluded_by_reason
            .entry(reason.to_string())
            .or_default() += 1;
    }

    fn print(&self) {
        let excluded_total: usize = self.excluded_by_reason.values().sum();
        let reasons_part = if self.excluded_by_reason.is_empty() {
            String::new()
        } else {
            let parts: Vec<String> = self
                .excluded_by_reason
                .iter()
                .map(|(r, c)| format!("{r}={c}"))
                .collect();
            format!(" ({})", parts.join(", "))
        };
        println!(
            "callsites: joined={} eligible={} rewritten={} excluded={}{} unjoined_thir={} unjoined_syn={}",
            self.joined,
            self.eligible,
            self.rewritten,
            excluded_total,
            reasons_part,
            self.unjoined_thir.len(),
            self.unjoined_syn.len()
        );
        for item in &self.unjoined_thir {
            println!("  unjoined_thir: {item}");
        }
        for item in &self.unjoined_syn {
            println!("  unjoined_syn: {item}");
        }
    }
}

fn norm_slash(path: &str) -> String {
    path.replace('\\', "/")
}

fn path_matches_suffix(candidate: &str, suffix: &str) -> bool {
    candidate == suffix || candidate.ends_with(&format!("/{suffix}"))
}

fn match_thir_file(thir_file: &str, scanned_paths: &[String]) -> Option<usize> {
    let norm = norm_slash(thir_file);
    let mut best: Option<(usize, usize)> = None;
    for (idx, sp) in scanned_paths.iter().enumerate() {
        if path_matches_suffix(sp, &norm) || path_matches_suffix(&norm, sp) {
            let score = sp.len().min(norm.len());
            if best.is_none_or(|(_, best_score)| score > best_score) {
                best = Some((idx, score));
            }
        }
    }
    best.map(|(idx, _)| idx)
}

fn span_contains(outer: SpanRange, inner: SpanRange) -> bool {
    (outer[0], outer[1]) <= (inner[0], inner[1]) && (inner[2], inner[3]) <= (outer[2], outer[3])
}

fn to_span_range(span: proc_macro2::Span) -> SpanRange {
    let start = span.start();
    let end = span.end();
    [start.line, start.column + 1, end.line, end.column + 1]
}

struct FnLedgerIndex {
    exact: BTreeMap<String, u32>,
    no_cfg: BTreeMap<String, Option<u32>>,
}

impl FnLedgerIndex {
    fn build(ledger_dir: &Path, ledger_set: &LedgerSet, crate_ident: &str) -> Result<Self, String> {
        let mut pairs = ledger_io::read_all_fn_keys(ledger_dir)?;
        if let Some(shard) = ledger_set.shard(crate_ident) {
            for entry in shard.live() {
                if entry.kind == Kind::Fn {
                    pairs.push((entry.key.clone(), entry.id));
                }
            }
        }
        let mut exact = BTreeMap::new();
        let mut no_cfg: BTreeMap<String, Option<u32>> = BTreeMap::new();
        for (k, id) in pairs {
            exact.insert(k.clone(), id);
            let stripped = strip_cfg_suffix(&k).to_string();
            no_cfg
                .entry(stripped)
                .and_modify(|existing| {
                    if *existing != Some(id) {
                        *existing = None;
                    }
                })
                .or_insert(Some(id));
        }
        Ok(Self { exact, no_cfg })
    }

    fn lookup_key(&self, k: &str) -> Option<u32> {
        if let Some(&id) = self.exact.get(k) {
            return Some(id);
        }
        self.no_cfg.get(strip_cfg_suffix(k)).copied().flatten()
    }

    fn lookup_callee(&self, call: &ThirCall, crate_ident: &str) -> Option<u32> {
        if let Some(id) = self.lookup_key(&call.callee) {
            return Some(id);
        }
        let callee_def = call.callee_def.as_deref()?;
        let impl_pos = callee_def.find("::{impl#")?;
        let def_mod = &callee_def[..impl_pos];
        let local_prefix = format!("{crate_ident}::");
        let full_mod = if call.callee.starts_with(&local_prefix) && !def_mod.starts_with(&local_prefix) {
            if def_mod.is_empty() {
                crate_ident.to_string()
            } else {
                format!("{crate_ident}::{def_mod}")
            }
        } else {
            def_mod.to_string()
        };
        let (owner_path, method_name) = call.callee.rsplit_once("::")?;
        let type_name = owner_path.rsplit("::").next()?;
        let candidate = format!("{full_mod}::{type_name}::{method_name}");
        self.lookup_key(&candidate)
    }
}

fn strip_cfg_suffix(mut key: &str) -> &str {
    while let Some(prefix) = key.strip_suffix(']') {
        let Some(pos) = prefix.rfind("[cfg(") else {
            break;
        };
        key = &prefix[..pos];
    }
    key
}

fn extract_sig_param_tys(sig: &syn::Signature) -> Vec<Type> {
    // The declared return type is appended as the last element (callers index by argument position, so the
    // extra element is only read by `callee_return_ty`, which checks `len == args + 1`).
    let ret: Type = match &sig.output {
        syn::ReturnType::Default => syn::parse_quote!(()),
        syn::ReturnType::Type(_, ty) => (**ty).clone(),
    };
    sig.inputs
        .iter()
        .map(|arg| match arg {
            syn::FnArg::Receiver(r) => {
                if let Some((_, lt)) = &r.reference {
                    let lt_str = lt
                        .as_ref()
                        .map_or_else(String::new, |l| format!("{} ", quote!(#l)));
                    let mut_str = if r.mutability.is_some() { "mut " } else { "" };
                    syn::parse_str(&format!("&{lt_str}{mut_str}Self"))
                        .unwrap_or_else(|_| syn::parse_quote!(Self))
                } else {
                    syn::parse_quote!(Self)
                }
            }
            syn::FnArg::Typed(pt) => (*pt.ty).clone(),
        })
        .chain(std::iter::once(ret))
        .collect()
}

/// True when `ty` names a lifetime other than `'static` and `'_` (`&'r T`, `Foo<'a>`).
fn type_has_named_lifetime(ty: &Type) -> bool {
    let text = quote!(#ty).to_string();
    let bytes: Vec<char> = text.chars().collect();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == '\'' {
            let mut j = i + 1;
            while j < bytes.len() && bytes[j].is_whitespace() {
                j += 1;
            }
            let start = j;
            while j < bytes.len() && (bytes[j].is_alphanumeric() || bytes[j] == '_') {
                j += 1;
            }
            let name: String = bytes[start..j].iter().collect();
            if !name.is_empty() && name != "static" && name != "_" {
                return true;
            }
            i = j.max(i + 1);
        } else {
            i += 1;
        }
    }
    false
}

/// The callee's declared return type, when the index entry carries it (`params.len() == nargs + 1`).
fn callee_return_ty(callee_params: Option<&[Type]>, nargs: usize) -> Option<&Type> {
    callee_params.filter(|v| v.len() == nargs + 1).and_then(|v| v.last())
}

fn strip_impl_generics(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let bytes = s.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'<' {
            let mut depth = 1usize;
            let mut j = i + 1;
            while j < bytes.len() && depth > 0 {
                match bytes[j] {
                    b'<' => depth += 1,
                    b'>' => depth -= 1,
                    _ => {}
                }
                j += 1;
            }
            let inner = &s[i + 1..j.saturating_sub(1)];
            if let Some((left, right)) = inner.split_once(" as ") {
                out.push('<');
                out.push_str(&strip_impl_generics(left));
                out.push_str(" as ");
                out.push_str(&strip_impl_generics(right));
                out.push('>');
            }
            i = j;
        } else {
            let ch = s[i..].chars().next().unwrap();
            out.push(ch);
            i += ch.len_utf8();
        }
    }
    out
}

fn type_path_key(tp: &syn::TypePath) -> Option<String> {
    if tp.qself.is_some() {
        return None;
    }
    let segs: Vec<String> = tp.path.segments.iter().map(|s| s.ident.to_string()).collect();
    (!segs.is_empty()).then(|| segs.join("::"))
}

fn apply_static_from_param_ty(
    raw_ty: &Type,
    param_ty: &Type,
    aliases: &BTreeMap<String, Option<Type>>,
    depth: usize,
) -> (Type, bool) {
    if depth < 5
        && let Type::Path(tp) = param_ty
        && let Some(path_str) = type_path_key(tp)
        && let Some(Some(aliased)) = aliases
            .get(&path_str)
            .or_else(|| tp.path.segments.last().and_then(|s| aliases.get(&s.ident.to_string())))
    {
        return apply_static_from_param_ty(raw_ty, aliased, aliases, depth + 1);
    }

    match (raw_ty, param_ty) {
        (Type::Reference(r_raw), Type::Reference(r_param)) => {
            let (new_elem, elem_changed) =
                apply_static_from_param_ty(&r_raw.elem, &r_param.elem, aliases, depth);
            let param_is_static = r_param
                .lifetime
                .as_ref()
                .is_some_and(|l| l.ident == "static");
            let mut out = r_raw.clone();
            let mut changed = elem_changed;
            if elem_changed {
                out.elem = Box::new(new_elem);
            }
            if param_is_static && !out.lifetime.as_ref().is_some_and(|l| l.ident == "static") {
                out.lifetime = Some(syn::Lifetime::new("'static", proc_macro2::Span::call_site()));
                changed = true;
            }
            (Type::Reference(out), changed)
        }
        (Type::Slice(s_raw), Type::Slice(s_param)) => {
            let (new_elem, changed) =
                apply_static_from_param_ty(&s_raw.elem, &s_param.elem, aliases, depth);
            if !changed {
                return (raw_ty.clone(), false);
            }
            let mut out = s_raw.clone();
            out.elem = Box::new(new_elem);
            (Type::Slice(out), true)
        }
        (Type::Array(a_raw), Type::Array(a_param)) => {
            let (new_elem, changed) =
                apply_static_from_param_ty(&a_raw.elem, &a_param.elem, aliases, depth);
            if !changed {
                return (raw_ty.clone(), false);
            }
            let mut out = a_raw.clone();
            out.elem = Box::new(new_elem);
            (Type::Array(out), true)
        }
        (Type::Tuple(t_raw), Type::Tuple(t_param)) if t_raw.elems.len() == t_param.elems.len() => {
            let mut out = t_raw.clone();
            let mut changed = false;
            for (re, pe) in out.elems.iter_mut().zip(t_param.elems.iter()) {
                let (mapped, c) = apply_static_from_param_ty(re, pe, aliases, depth);
                if c {
                    *re = mapped;
                    changed = true;
                }
            }
            (if changed { Type::Tuple(out) } else { raw_ty.clone() }, changed)
        }
        (Type::Path(p_raw), Type::Path(p_param))
            if p_raw.path.segments.last().map(|s| &s.ident)
                == p_param.path.segments.last().map(|s| &s.ident) =>
        {
            let Some(last_raw) = p_raw.path.segments.last() else {
                return (raw_ty.clone(), false);
            };
            let Some(last_param) = p_param.path.segments.last() else {
                return (raw_ty.clone(), false);
            };
            let (
                PathArguments::AngleBracketed(ab_raw),
                PathArguments::AngleBracketed(ab_param),
            ) = (&last_raw.arguments, &last_param.arguments)
            else {
                return (raw_ty.clone(), false);
            };
            let mut new_ab = ab_raw.clone();
            // `Foo<'static>` in the callee, `Foo<'_>` in THIR: keep the `'static`.
            let mut lt_changed = false;
            {
                let param_lts: Vec<&syn::Lifetime> = ab_param
                    .args
                    .iter()
                    .filter_map(|a| match a {
                        syn::GenericArgument::Lifetime(l) => Some(l),
                        _ => None,
                    })
                    .collect();
                let mut k = 0;
                for arg in new_ab.args.iter_mut() {
                    if let syn::GenericArgument::Lifetime(l) = arg {
                        if let Some(pl) = param_lts.get(k)
                            && pl.ident == "static"
                            && l.ident != "static"
                        {
                            *l = syn::Lifetime::new("'static", proc_macro2::Span::call_site());
                            lt_changed = true;
                        }
                        k += 1;
                    }
                }
            }
            let raw_ty_args: Vec<usize> = new_ab
                .args
                .iter()
                .enumerate()
                .filter_map(|(i, a)| matches!(a, syn::GenericArgument::Type(_)).then_some(i))
                .collect();
            let param_ty_args: Vec<&Type> = ab_param
                .args
                .iter()
                .filter_map(|a| match a {
                    syn::GenericArgument::Type(t) => Some(t),
                    _ => None,
                })
                .collect();
            let mut changed = lt_changed;
            if raw_ty_args.len() != param_ty_args.len() && !lt_changed {
                return (raw_ty.clone(), false);
            }
            let same_ty_arity = raw_ty_args.len() == param_ty_args.len();
            for (ri, p_arg) in raw_ty_args.into_iter().zip(param_ty_args) {
                if !same_ty_arity {
                    break;
                }
                if let syn::GenericArgument::Type(r_arg) = &mut new_ab.args[ri] {
                    let (mapped, c) = apply_static_from_param_ty(r_arg, p_arg, aliases, depth);
                    if c {
                        *r_arg = mapped;
                        changed = true;
                    }
                }
            }
            if !changed {
                return (raw_ty.clone(), false);
            }
            let mut out = p_raw.clone();
            out.path.segments.last_mut().unwrap().arguments =
                PathArguments::AngleBracketed(new_ab);
            (Type::Path(out), true)
        }
        _ => (raw_ty.clone(), false),
    }
}

struct StaticParamIndex {
    exact: BTreeMap<String, Vec<Type>>,
    no_cfg: BTreeMap<String, Option<Vec<Type>>>,
    aliases: BTreeMap<String, Option<Type>>,
    loaded_crates: BTreeSet<String>,
    crate_dirs: BTreeMap<String, (PathBuf, String)>,
    /// Full paths (`crate_ident::a::b`) of modules declared without `pub`/`pub(crate)`: a shim in another
    /// module cannot name a type through them (E0603).
    private_mods: BTreeSet<String>,
}

/// Drops the segments of private modules from every `a::b::C` path in `text`, unless the caller lives inside
/// the private module's parent (then the full path is visible). The surviving path is the module's re-export
/// path (`placement::context::Err` -> `placement::Err`); if there is no re-export the compile/exclude loop
/// removes the site.
fn publicize_paths(text: &str, caller_key: &str, crate_ident: &str, private_mods: &BTreeSet<String>) -> String {
    if private_mods.is_empty() {
        return text.to_string();
    }
    let is_ident_char = |c: char| c.is_alphanumeric() || c == '_';
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let prev_ok = i == 0 || !(is_ident_char(chars[i - 1]) || chars[i - 1] == '\'');
        if !(prev_ok && (c.is_alphabetic() || c == '_')) {
            out.push(c);
            i += 1;
            continue;
        }
        let mut segs: Vec<String> = Vec::new();
        loop {
            let start = i;
            while i < chars.len() && is_ident_char(chars[i]) {
                i += 1;
            }
            segs.push(chars[start..i].iter().collect());
            if i + 2 < chars.len() && chars[i] == ':' && chars[i + 1] == ':' && (chars[i + 2].is_alphabetic() || chars[i + 2] == '_') {
                i += 2;
            } else {
                break;
            }
        }
        let mut kept: Vec<&str> = Vec::with_capacity(segs.len());
        for idx in 0..segs.len() {
            if idx + 1 < segs.len() && idx >= 1 {
                let orig_path: Vec<&str> = segs[..=idx]
                    .iter()
                    .enumerate()
                    .map(|(n, s)| if n == 0 && s == "crate" { crate_ident } else { s.as_str() })
                    .collect();
                let full = orig_path.join("::");
                if private_mods.contains(&full) {
                    let parent = orig_path[..idx].join("::");
                    if !caller_key.starts_with(&format!("{parent}::")) {
                        continue;
                    }
                }
            }
            kept.push(&segs[idx]);
        }
        out.push_str(&kept.join("::"));
    }
    out
}

impl StaticParamIndex {
    fn find_workspace_crates(start: &Path, ledger_dir: &Path) -> BTreeMap<String, (PathBuf, String)> {
        let mut ws_root = None;
        for anchor in [start, ledger_dir] {
            let mut dir = Some(anchor);
            while let Some(d) = dir {
                if d.join("hook-ledger").join("stamp-config.txt").is_file() {
                    ws_root = Some(d.to_path_buf());
                    break;
                }
                dir = d.parent();
            }
            if ws_root.is_some() {
                break;
            }
        }
        let Some(ws) = ws_root else {
            return BTreeMap::new();
        };
        let mut out = BTreeMap::new();
        let Ok(entries) = std::fs::read_dir(ws.join("crates")) else {
            return out;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let cargo_toml = path.join("Cargo.toml");
            if let Ok(text) = std::fs::read_to_string(&cargo_toml) {
                for line in text.lines() {
                    let trimmed = line.trim();
                    if let Some(rest) = trimmed.strip_prefix("name")
                        && let Some(val) = rest.trim_start().strip_prefix('=')
                    {
                        let pkg = val.trim().trim_matches('"').to_string();
                        if !pkg.is_empty() {
                            out.insert(key::normalize_crate_name(&pkg), (path.clone(), pkg));
                        }
                        break;
                    }
                }
            }
        }
        out
    }

    fn new(
        crate_root: &Path,
        ledger_dir: &Path,
        crate_name: &str,
        crate_ident: &str,
        scanned_files: &[modules::ScannedFile],
        colliding_short_keys: &BTreeSet<String>,
    ) -> Self {
        let mut index = Self {
            exact: BTreeMap::new(),
            no_cfg: BTreeMap::new(),
            private_mods: BTreeSet::new(),
            aliases: BTreeMap::new(),
            loaded_crates: BTreeSet::new(),
            crate_dirs: Self::find_workspace_crates(crate_root, ledger_dir),
        };
        index.insert_crate_files(
            crate_root,
            crate_name,
            crate_ident,
            scanned_files,
            colliding_short_keys,
            false,
        );
        index.loaded_crates.insert(crate_ident.to_string());
        index
    }

    fn insert_alias(&mut self, key: String, ty: Type) {
        self.aliases
            .entry(key)
            .and_modify(|existing| {
                if existing.as_ref().is_some_and(|e| quote!(#e).to_string() != quote!(#ty).to_string()) {
                    *existing = None;
                }
            })
            .or_insert_with(|| Some(ty));
    }

    fn insert_one_key(&mut self, fn_key: String, params: Vec<Type>) {
        let stripped = strip_cfg_suffix(&fn_key).to_string();
        self.no_cfg
            .entry(stripped)
            .and_modify(|existing| {
                if existing.as_ref().is_some_and(|e| e.len() != params.len()) {
                    *existing = None;
                }
            })
            .or_insert_with(|| Some(params.clone()));
        self.exact.insert(fn_key, params);
    }

    fn insert(&mut self, fn_key: String, params: Vec<Type>) {
        if params.is_empty() {
            return;
        }
        let no_gen = strip_impl_generics(&fn_key);
        if no_gen != fn_key {
            self.insert_one_key(no_gen, params.clone());
        }
        self.insert_one_key(fn_key, params);
    }

    fn insert_crate_files(
        &mut self,
        crate_root: &Path,
        crate_name: &str,
        crate_ident: &str,
        scanned_files: &[modules::ScannedFile],
        colliding_short_keys: &BTreeSet<String>,
        is_foreign: bool,
    ) {
        let mut seen_paths = BTreeSet::new();
        for sf in scanned_files {
            if let Ok(c) = sf.path.canonicalize() {
                seen_paths.insert(c);
            }
            let idx = LineIndex::new(&sf.source);
            self.collect_items(
                &sf.source,
                &idx,
                crate_ident,
                colliding_short_keys,
                &sf.root_mod_path,
                &sf.root_cfg_tags,
                &sf.parsed.items,
                is_foreign,
            );
        }
        if let Ok(root_file) = modules::find_crate_root_file(crate_root, crate_name)
            && root_file.canonicalize().is_ok_and(|c| !seen_paths.contains(&c))
            && let Ok(source) = std::fs::read_to_string(&root_file)
            && let Ok(parsed) = syn::parse_file(&source)
        {
            let idx = LineIndex::new(&source);
            self.collect_items(
                &source,
                &idx,
                crate_ident,
                colliding_short_keys,
                &[],
                &[],
                &parsed.items,
                is_foreign,
            );
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn collect_items(
        &mut self,
        source: &str,
        idx: &LineIndex,
        crate_ident: &str,
        colliding_short_keys: &BTreeSet<String>,
        mod_path: &[String],
        mod_cfg_tags: &[String],
        items: &[Item],
        is_foreign: bool,
    ) {
        let prefix = key::module_prefix(crate_ident, mod_path);
        let (matched_helpers, _) = run::pair_converted_trait_helpers(
            source,
            idx,
            &prefix,
            mod_cfg_tags,
            colliding_short_keys,
            items,
        );
        for item in items {
            match item {
                Item::Mod(item_mod) if !modules::has_cfg_test(&item_mod.attrs) => {
                    let is_priv = if is_foreign {
                        !matches!(item_mod.vis, syn::Visibility::Public(_))
                    } else {
                        matches!(item_mod.vis, syn::Visibility::Inherited)
                    };
                    if is_priv {
                        self.private_mods.insert(format!("{prefix}::{}", item_mod.ident));
                    }
                    if let Some((_, inner)) = &item_mod.content {
                        let mut child_mod = mod_path.to_vec();
                        child_mod.push(item_mod.ident.to_string());
                        let mut child_tags = mod_cfg_tags.to_vec();
                        child_tags.extend(key::extract_cfg_tags(&item_mod.attrs));
                        self.collect_items(
                            source,
                            idx,
                            crate_ident,
                            colliding_short_keys,
                            &child_mod,
                            &child_tags,
                            inner,
                            is_foreign,
                        );
                    }
                }
                Item::Type(item_type) if !modules::has_cfg_test(&item_type.attrs) => {
                    if item_type.generics.params.is_empty() && !eligible::type_has_non_static_lifetime(&item_type.ty) {
                        let short = item_type.ident.to_string();
                        self.insert_alias(short.clone(), (*item_type.ty).clone());
                        self.insert_alias(format!("{prefix}::{short}"), (*item_type.ty).clone());
                    }
                }
                Item::Fn(item_fn) if !modules::has_cfg_test(&item_fn.attrs) => {
                    let mut cfgs = mod_cfg_tags.to_vec();
                    cfgs.extend(key::extract_cfg_tags(&item_fn.attrs));
                    let fn_key = key::free_fn_key(&prefix, &item_fn.sig.ident, &cfgs);
                    self.insert(fn_key, extract_sig_param_tys(&item_fn.sig));
                }
                Item::Impl(item_impl) if !modules::has_cfg_test(&item_impl.attrs) => {
                    let mut impl_cfgs = mod_cfg_tags.to_vec();
                    impl_cfgs.extend(key::extract_cfg_tags(&item_impl.attrs));
                    let trait_path = item_impl.trait_.as_ref().map(|(_, p, _)| p);
                    for impl_item in &item_impl.items {
                        let ImplItem::Fn(method) = impl_item else {
                            continue;
                        };
                        if modules::has_cfg_test(&method.attrs) {
                            continue;
                        }
                        let method_span = idx.span_range(source, method.span());
                        if trait_path.is_none() && matched_helpers.contains_key(&method_span) {
                            continue;
                        }
                        let mut fn_cfgs = impl_cfgs.clone();
                        fn_cfgs.extend(key::extract_cfg_tags(&method.attrs));
                        let fn_key = match trait_path {
                            Some(tp) => {
                                let short_key = key::trait_method_key(
                                    &prefix,
                                    &item_impl.self_ty,
                                    tp,
                                    &method.sig.ident,
                                    &fn_cfgs,
                                    false,
                                );
                                if colliding_short_keys.contains(&short_key) {
                                    key::trait_method_key(
                                        &prefix,
                                        &item_impl.self_ty,
                                        tp,
                                        &method.sig.ident,
                                        &fn_cfgs,
                                        true,
                                    )
                                } else {
                                    short_key
                                }
                            }
                            None => key::inherent_method_key(
                                &prefix,
                                &item_impl.self_ty,
                                &method.sig.ident,
                                &fn_cfgs,
                            ),
                        };
                        self.insert(fn_key, extract_sig_param_tys(&method.sig));
                    }
                }
                _ => {}
            }
        }
    }

    fn ensure_crate_loaded(&mut self, target_ident: &str) {
        if self.loaded_crates.contains(target_ident) {
            return;
        }
        self.loaded_crates.insert(target_ident.to_string());
        let Some((dir, pkg)) = self.crate_dirs.get(target_ident).cloned() else {
            return;
        };
        let Ok(mod_names) = modules::expand_star_modules(&dir, &pkg, &["*".to_string()], &[]) else {
            return;
        };
        let Ok(targets) = mod_names
            .iter()
            .map(|m| modules::normalize_module_arg(m))
            .collect::<Result<Vec<_>, _>>()
        else {
            return;
        };
        let Ok(files) = modules::collect_module_files(&dir, &pkg, &targets, false) else {
            return;
        };
        let colliding = run::collect_colliding_short_keys(target_ident, &targets, false, &files);
        self.insert_crate_files(&dir, &pkg, target_ident, &files, &colliding, true);
    }

    /// Loads any workspace dependency crate named at path root positions in `text` (so its aliases
    /// and private modules are known even when the call's callee lives in a different crate).
    fn ensure_crates_in_text(&mut self, text: &str) {
        if self.crate_dirs.is_empty() {
            return;
        }
        let bytes = text.as_bytes();
        let mut i = 0;
        let mut at_root = true;
        while i < bytes.len() {
            let b = bytes[i];
            if b == b'\'' {
                i += 1;
                while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_') {
                    i += 1;
                }
                continue;
            }
            if b.is_ascii_alphabetic() || b == b'_' {
                let start = i;
                while i < bytes.len() && (bytes[i].is_ascii_alphanumeric() || bytes[i] == b'_') {
                    i += 1;
                }
                let ident = &text[start..i];
                if at_root && bytes.get(i..i + 2) == Some(b"::") && self.crate_dirs.contains_key(ident) {
                    self.ensure_crate_loaded(ident);
                }
                at_root = matches!(ident, "mut" | "fn" | "for" | "dyn" | "impl" | "const");
                continue;
            }
            if b == b':' && bytes.get(i + 1) == Some(&b':') {
                at_root = false;
                i += 2;
                continue;
            }
            if !b.is_ascii_whitespace() {
                at_root = matches!(b, b'&' | b'<' | b'(' | b'[' | b',' | b';' | b'=' | b'|' | b'+');
            }
            i += 1;
        }
    }

    fn lookup_key(&self, k: &str) -> Option<&[Type]> {
        if let Some(v) = self.exact.get(k) {
            return Some(v.as_slice());
        }
        self.no_cfg
            .get(strip_cfg_suffix(k))
            .and_then(|opt| opt.as_deref())
    }

    fn lookup_callee(&mut self, call: &ThirCall, crate_ident: &str, callee_path: &str) -> Option<Vec<Type>> {
        if let Some(first) = callee_first_segment(callee_path) {
            self.ensure_crate_loaded(first);
        }
        if let Some(params) = self.lookup_key(callee_path) {
            return Some(params.to_vec());
        }
        let callee_def = call.callee_def.as_deref()?;
        let impl_pos = callee_def.find("::{impl#")?;
        let def_mod = &callee_def[..impl_pos];
        let local_prefix = format!("{crate_ident}::");
        let full_mod = if callee_path.starts_with(&local_prefix) && !def_mod.starts_with(&local_prefix) {
            if def_mod.is_empty() {
                crate_ident.to_string()
            } else {
                format!("{crate_ident}::{def_mod}")
            }
        } else {
            def_mod.to_string()
        };
        let (owner_path, method_name) = callee_path.rsplit_once("::")?;
        let type_name = owner_path.rsplit("::").next()?;
        let candidate = format!("{full_mod}::{type_name}::{method_name}");
        self.lookup_key(&candidate).map(|m| m.to_vec())
    }
}

