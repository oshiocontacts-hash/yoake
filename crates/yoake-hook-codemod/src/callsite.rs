#[derive(Default)]
struct CallsiteSummary {
    joined: usize,
    eligible: usize,
    rewritten: usize,
    excluded_by_reason: BTreeMap<String, usize>,
    unjoined_thir: Vec<String>,
    unjoined_syn: Vec<String>,
}

impl CallsiteSummary {
    fn exclude(&mut self, reason: &str) {
        *self
            .excluded_by_reason
            .entry(reason.to_string())
            .or_default() += 1;
    }

    fn print(&self) {
        let excluded_total: usize = self.excluded_by_reason.values().sum();
        let reasons_part = if self.excluded_by_reason.is_empty() {
            String::new()
        } else {
            let parts: Vec<String> = self
                .excluded_by_reason
                .iter()
                .map(|(r, c)| format!("{r}={c}"))
                .collect();
            format!(" ({})", parts.join(", "))
        };
        println!(
            "callsites: joined={} eligible={} rewritten={} excluded={}{} unjoined_thir={} unjoined_syn={}",
            self.joined,
            self.eligible,
            self.rewritten,
            excluded_total,
            reasons_part,
            self.unjoined_thir.len(),
            self.unjoined_syn.len()
        );
        for item in &self.unjoined_thir {
            println!("  unjoined_thir: {item}");
        }
        for item in &self.unjoined_syn {
            println!("  unjoined_syn: {item}");
        }
    }
}

fn norm_slash(path: &str) -> String {
    path.replace('\\', "/")
}

fn path_matches_suffix(candidate: &str, suffix: &str) -> bool {
    candidate == suffix || candidate.ends_with(&format!("/{suffix}"))
}

fn match_thir_file(thir_file: &str, scanned_paths: &[String]) -> Option<usize> {
    let norm = norm_slash(thir_file);
    let mut best: Option<(usize, usize)> = None;
    for (idx, sp) in scanned_paths.iter().enumerate() {
        if path_matches_suffix(sp, &norm) || path_matches_suffix(&norm, sp) {
            let score = sp.len().min(norm.len());
            if best.is_none_or(|(_, best_score)| score > best_score) {
                best = Some((idx, score));
            }
        }
    }
    best.map(|(idx, _)| idx)
}

fn span_contains(outer: SpanRange, inner: SpanRange) -> bool {
    (outer[0], outer[1]) <= (inner[0], inner[1]) && (inner[2], inner[3]) <= (outer[2], outer[3])
}

fn to_span_range(span: proc_macro2::Span) -> SpanRange {
    let start = span.start();
    let end = span.end();
    [start.line, start.column + 1, end.line, end.column + 1]
}

struct FnLedgerIndex {
    exact: BTreeMap<String, u32>,
    no_cfg: BTreeMap<String, Option<u32>>,
}

impl FnLedgerIndex {
    fn build(ledger_dir: &Path, ledger_set: &LedgerSet, crate_ident: &str) -> Result<Self, String> {
        let mut pairs = ledger_io::read_all_fn_keys(ledger_dir)?;
        if let Some(shard) = ledger_set.shard(crate_ident) {
            for entry in shard.live() {
                if entry.kind == Kind::Fn {
                    pairs.push((entry.key.clone(), entry.id));
                }
            }
        }
        let mut exact = BTreeMap::new();
        let mut no_cfg: BTreeMap<String, Option<u32>> = BTreeMap::new();
        for (k, id) in pairs {
            exact.insert(k.clone(), id);
            let stripped = strip_cfg_suffix(&k).to_string();
            no_cfg
                .entry(stripped)
                .and_modify(|existing| {
                    if *existing != Some(id) {
                        *existing = None;
                    }
                })
                .or_insert(Some(id));
        }
        Ok(Self { exact, no_cfg })
    }

    fn lookup_key(&self, k: &str) -> Option<u32> {
        if let Some(&id) = self.exact.get(k) {
            return Some(id);
        }
        self.no_cfg.get(strip_cfg_suffix(k)).copied().flatten()
    }

    fn lookup_callee(&self, call: &ThirCall, crate_ident: &str) -> Option<u32> {
        if let Some(id) = self.lookup_key(&call.callee) {
            return Some(id);
        }
        let callee_def = call.callee_def.as_deref()?;
        let impl_pos = callee_def.find("::{impl#")?;
        let def_mod = &callee_def[..impl_pos];
        let local_prefix = format!("{crate_ident}::");
        let full_mod = if call.callee.starts_with(&local_prefix) && !def_mod.starts_with(&local_prefix) {
            if def_mod.is_empty() {
                crate_ident.to_string()
            } else {
                format!("{crate_ident}::{def_mod}")
            }
        } else {
            def_mod.to_string()
        };
        let (owner_path, method_name) = call.callee.rsplit_once("::")?;
        let type_name = owner_path.rsplit("::").next()?;
        let candidate = format!("{full_mod}::{type_name}::{method_name}");
        self.lookup_key(&candidate)
    }
}

fn strip_cfg_suffix(mut key: &str) -> &str {
    while let Some(prefix) = key.strip_suffix(']') {
        let Some(pos) = prefix.rfind("[cfg(") else {
            break;
        };
        key = &prefix[..pos];
    }
    key
}

