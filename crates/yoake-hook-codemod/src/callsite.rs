struct DetailVisitor<'a> {
    source: &'a str,
    idx: &'a LineIndex,
    details: BTreeMap<SpanRange, SynCallDetail>,
    macro_spans: Vec<SpanRange>,
}

impl<'ast> Visit<'ast> for DetailVisitor<'_> {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        let span = to_span_range(node.span());
        let existing_shim_id = match &*node.func {
            Expr::Path(ep) if ep.qself.is_none() && ep.path.segments.len() == 1 => ep
                .path
                .segments[0]
                .ident
                .to_string()
                .strip_prefix("__yoake_cs_")
                .and_then(|s| s.parse::<u32>().ok()),
            _ => None,
        };
        let (call_start, call_end) = self.idx.span_range(self.source, node.span());
        self.details.insert(
            span,
            SynCallDetail {
                recv_start: call_start,
                recv_end: call_start,
                recv_needs_parens: false,
                paren_open_end: call_start,
                call_end,
                first_arg_start: None,
                method_name: None,
                turbofish_src: None,
                existing_shim_id,
            },
        );
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        let span = to_span_range(node.span());
        let (recv_start, recv_end) = self.idx.span_range(self.source, node.receiver.span());
        let (_, paren_open_end) = self
            .idx
            .span_range(self.source, node.paren_token.span.open());
        let (_, call_end) = self.idx.span_range(self.source, node.span());
        let first_arg_start = node
            .args
            .first()
            .map(|a| self.idx.span_range(self.source, a.span()).0);
        let turbofish_src = node.turbofish.as_ref().map(|t| {
            let (s, e) = self.idx.span_range(self.source, t.span());
            self.source[s..e].to_string()
        });
        let recv_needs_parens = !matches!(
            &*node.receiver,
            Expr::Path(_)
                | Expr::Field(_)
                | Expr::MethodCall(_)
                | Expr::Call(_)
                | Expr::Index(_)
                | Expr::Paren(_)
                | Expr::Lit(_)
                | Expr::Try(_)
                | Expr::Block(_)
                | Expr::Tuple(_)
                | Expr::Array(_)
                | Expr::Struct(_)
        );
        self.details.insert(
            span,
            SynCallDetail {
                recv_start,
                recv_end,
                recv_needs_parens,
                paren_open_end,
                call_end,
                first_arg_start,
                method_name: Some(node.method.to_string()),
                turbofish_src,
                existing_shim_id: None,
            },
        );
        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        self.macro_spans.push(to_span_range(node.span()));
        visit::visit_expr_macro(self, node);
    }

    fn visit_stmt_macro(&mut self, node: &'ast StmtMacro) {
        self.macro_spans.push(to_span_range(node.span()));
        visit::visit_stmt_macro(self, node);
    }

    fn visit_item_fn(&mut self, _node: &'ast ItemFn) {}
    fn visit_impl_item_fn(&mut self, _node: &'ast syn::ImplItemFn) {}
}

fn parse_existing_shim(item_fn: &ItemFn, source: &str, idx: &LineIndex) -> ExistingShim {
    let ident_str = item_fn.sig.ident.to_string();
    let ident_id = ident_str
        .strip_prefix("__yoake_cs_")
        .and_then(|s| s.parse::<u32>().ok());
    let hook_attrs = attr::find_hook_attrs(&item_fn.attrs, source, idx);
    let first_hook = hook_attrs.first();
    let attr_id = first_hook.and_then(|a| a.parsed.id);
    let attr_key = first_hook.and_then(|a| a.parsed.key.clone());
    let attr_byte_span = first_hook.map(|a| idx.span_range(source, item_fn.attrs[a.attr_index].span()));
    let kind_is_callsite = first_hook.is_some_and(|a| a.parsed.kind.as_deref() == Some("callsite"));
    let has_inline_always = item_fn.attrs.iter().any(|a| {
        a.path().is_ident("inline")
            && matches!(&a.meta, syn::Meta::List(l) if l.tokens.to_string().trim() == "always")
    });

    let full_end = idx.span_range(source, item_fn.span()).1;
    let full_start = item_fn
        .attrs
        .first()
        .map_or_else(|| idx.span_range(source, item_fn.span()).0, |a| idx.span_range(source, a.span()).0);

    let sig = &item_fn.sig;
    let mut param_names = Vec::new();
    for input in &sig.inputs {
        if let syn::FnArg::Typed(pt) = input
            && let syn::Pat::Ident(pi) = &*pt.pat
        {
            param_names.push(pi.ident.to_string());
        }
    }

    let body_method = if item_fn.block.stmts.len() == 1
        && let syn::Stmt::Expr(Expr::MethodCall(mc), None) = &item_fn.block.stmts[0]
        && matches!(&*mc.receiver, Expr::Path(ep) if ep.qself.is_none() && ep.path.is_ident("recv"))
    {
        let tf = mc.turbofish.as_ref().map(|t| quote!(#t).to_string());
        let args = mc
            .args
            .iter()
            .filter_map(|arg| match arg {
                Expr::Path(ep) if ep.qself.is_none() && ep.path.segments.len() == 1 => {
                    Some(ep.path.segments[0].ident.to_string())
                }
                _ => None,
            })
            .collect::<Vec<_>>();
        if args.len() == mc.args.len() {
            Some((mc.method.to_string(), tf, args))
        } else {
            None
        }
    } else {
        None
    };

    ExistingShim {
        ident_id,
        attr_id,
        attr_key,
        attr_byte_span,
        kind_is_callsite,
        has_inline_always,
        byte_span: (full_start, full_end),
        span: to_span_range(item_fn.span()),
        param_names,
        body_method,
    }
}

struct AstCollector<'a> {
    source: &'a str,
    idx: &'a LineIndex,
    crate_ident: &'a str,
    targets: &'a [Vec<String>],
    colliding_short_keys: &'a BTreeSet<String>,
    fn_ledger: &'a FnLedgerIndex,
    mod_path: Vec<String>,
    mod_cfg_tags: Vec<String>,
    mod_cfg_attrs: Vec<String>,
    in_target_mod: bool,
    cfg_test_spans: Vec<SpanRange>,
    existing_shims: Vec<ExistingShim>,
    callers: Vec<CollectedCaller>,
    top_macro_spans: Vec<SpanRange>,
}

impl<'a> AstCollector<'a> {
    fn collect_caller_block(
        &mut self,
        fn_key: String,
        cfg_attrs: Vec<String>,
        block: &Block,
    ) {
        let fn_id = self.fn_ledger.lookup_key(&fn_key);
        let caller_label = fn_id
            .map(|id| format!("fn:{id}"))
            .unwrap_or_else(|| fn_key.clone());
        let (extracted, snapshot) = extract_block_calls(block, &caller_label);
        let mut detail_visitor = DetailVisitor {
            source: self.source,
            idx: self.idx,
            details: BTreeMap::new(),
            macro_spans: Vec::new(),
        };
        detail_visitor.visit_block(block);

        let calls = extracted
            .into_iter()
            .filter_map(|ec| {
                let detail = detail_visitor.details.remove(&ec.span)?;
                Some(CollectedCall {
                    site: ec.site,
                    span: ec.span,
                    detail,
                })
            })
            .collect();

        self.callers.push(CollectedCaller {
            fn_key,
            fn_id,
            cfg_attrs,
            snapshot,
            calls,
            macro_spans: detail_visitor.macro_spans,
        });
    }

    fn collect_cfg_attrs(&self, attrs: &[syn::Attribute]) -> Vec<String> {
        let mut out = self.mod_cfg_attrs.clone();
        for attr in attrs {
            if attr.path().is_ident("cfg") {
                let (s, e) = self.idx.span_range(self.source, attr.span());
                out.push(self.source[s..e].to_string());
            }
        }
        out
    }

    fn visit_items(&mut self, items: &[Item]) {
        self.in_target_mod = modules::is_target_or_descendant(&self.mod_path, self.targets);
        let prefix = key::module_prefix(self.crate_ident, &self.mod_path);
        let (matched_helpers, _) = if self.in_target_mod {
            run::pair_converted_trait_helpers(
                self.source,
                self.idx,
                &prefix,
                &self.mod_cfg_tags,
                self.colliding_short_keys,
                items,
            )
        } else {
            (BTreeMap::new(), BTreeMap::new())
        };

        for item in items {
            match item {
                Item::Mod(item_mod) => {
                    if modules::has_cfg_test(&item_mod.attrs) {
                        self.cfg_test_spans.push(to_span_range(item_mod.span()));
                        continue;
                    }
                    if let Some((_, inner)) = &item_mod.content {
                        let prev_path = self.mod_path.clone();
                        let prev_tags = self.mod_cfg_tags.clone();
                        let prev_attrs = self.mod_cfg_attrs.clone();
                        let prev_in = self.in_target_mod;
                        self.mod_path.push(item_mod.ident.to_string());
                        self.mod_cfg_tags.extend(key::extract_cfg_tags(&item_mod.attrs));
                        self.mod_cfg_attrs = self.collect_cfg_attrs(&item_mod.attrs);
                        self.visit_items(inner);
                        self.mod_path = prev_path;
                        self.mod_cfg_tags = prev_tags;
                        self.mod_cfg_attrs = prev_attrs;
                        self.in_target_mod = prev_in;
                    }
                }
                Item::Fn(item_fn) => {
                    if modules::has_cfg_test(&item_fn.attrs) {
                        self.cfg_test_spans.push(to_span_range(item_fn.span()));
                        continue;
                    }
                    if !self.in_target_mod {
                        continue;
                    }
                    let is_shim = item_fn.sig.ident.to_string().starts_with("__yoake_cs_")
                        || attr::find_hook_attrs(&item_fn.attrs, self.source, self.idx)
                            .iter()
                            .any(|a| a.parsed.kind.as_deref() == Some("callsite"));
                    if is_shim {
                        self.existing_shims
                            .push(parse_existing_shim(item_fn, self.source, self.idx));
                        continue;
                    }
                    let mut fn_cfg_tags = self.mod_cfg_tags.clone();
                    fn_cfg_tags.extend(key::extract_cfg_tags(&item_fn.attrs));
                    let fn_key = key::free_fn_key(&prefix, &item_fn.sig.ident, &fn_cfg_tags);
                    let cfg_attrs = self.collect_cfg_attrs(&item_fn.attrs);
                    self.collect_caller_block(fn_key, cfg_attrs, &item_fn.block);
                }
                Item::Impl(item_impl) => {
                    if modules::has_cfg_test(&item_impl.attrs) {
                        self.cfg_test_spans.push(to_span_range(item_impl.span()));
                        continue;
                    }
                    if !self.in_target_mod {
                        continue;
                    }
                    let mut impl_cfg_tags = self.mod_cfg_tags.clone();
                    impl_cfg_tags.extend(key::extract_cfg_tags(&item_impl.attrs));
                    let impl_cfg_attrs = self.collect_cfg_attrs(&item_impl.attrs);
                    let trait_path = item_impl.trait_.as_ref().map(|(_, p, _)| p);
                    for impl_item in &item_impl.items {
                        let ImplItem::Fn(method) = impl_item else {
                            continue;
                        };
                        if modules::has_cfg_test(&method.attrs) {
                            self.cfg_test_spans.push(to_span_range(method.span()));
                            continue;
                        }
                        let method_span = self.idx.span_range(self.source, method.span());
                        let fn_key = if trait_path.is_none()
                            && let Some(trait_key) = matched_helpers.get(&method_span)
                        {
                            trait_key.clone()
                        } else {
                            let mut fn_cfg_tags = impl_cfg_tags.clone();
                            fn_cfg_tags.extend(key::extract_cfg_tags(&method.attrs));
                            match trait_path {
                                Some(tp) => {
                                    let short_key = key::trait_method_key(
                                        &prefix,
                                        &item_impl.self_ty,
                                        tp,
                                        &method.sig.ident,
                                        &fn_cfg_tags,
                                        false,
                                    );
                                    if self.colliding_short_keys.contains(&short_key) {
                                        key::trait_method_key(
                                            &prefix,
                                            &item_impl.self_ty,
                                            tp,
                                            &method.sig.ident,
                                            &fn_cfg_tags,
                                            true,
                                        )
                                    } else {
                                        short_key
                                    }
                                }
                                None => key::inherent_method_key(
                                    &prefix,
                                    &item_impl.self_ty,
                                    &method.sig.ident,
                                    &fn_cfg_tags,
                                ),
                            }
                        };
                        let mut cfg_attrs = impl_cfg_attrs.clone();
                        for attr in &method.attrs {
                            if attr.path().is_ident("cfg") {
                                let (s, e) = self.idx.span_range(self.source, attr.span());
                                cfg_attrs.push(self.source[s..e].to_string());
                            }
                        }
                        self.collect_caller_block(fn_key, cfg_attrs, &method.block);
                    }
                }
                Item::Macro(ItemMacro { .. }) if self.in_target_mod => {
                    self.top_macro_spans.push(to_span_range(item.span()));
                }
                _ => {}
            }
        }
    }
}

fn collect_file_ast(
    file: &modules::ScannedFile,
    crate_ident: &str,
    targets: &[Vec<String>],
    colliding_short_keys: &BTreeSet<String>,
    fn_ledger: &FnLedgerIndex,
) -> CollectedFile {
    let idx = LineIndex::new(&file.source);
    let style = attr::detect_file_style(&file.parsed.items, &file.source);
    let shim_header_byte_start = file.source.find(SHIM_HEADER);
    let mut collector = AstCollector {
        source: &file.source,
        idx: &idx,
        crate_ident,
        targets,
        colliding_short_keys,
        fn_ledger,
        mod_path: file.root_mod_path.clone(),
        mod_cfg_tags: file.root_cfg_tags.clone(),
        mod_cfg_attrs: Vec::new(),
        in_target_mod: false,
        cfg_test_spans: Vec::new(),
        existing_shims: Vec::new(),
        callers: Vec::new(),
        top_macro_spans: Vec::new(),
    };
    collector.visit_items(&file.parsed.items);
    CollectedFile {
        path: file.path.clone(),
        source: file.source.clone(),
        style,
        cfg_test_spans: collector.cfg_test_spans,
        existing_shims: collector.existing_shims,
        shim_header_byte_start,
        callers: collector.callers,
        top_macro_spans: collector.top_macro_spans,
    }
}

fn simplify_elided_refs(ty_str: &str) -> String {
    ty_str
        .replace("&'_ mut ", "&mut ")
        .replace("&'_ ", "&")
}

