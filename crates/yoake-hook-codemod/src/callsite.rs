fn parse_shim_ident(name: &str) -> Option<u32> {
    name.strip_prefix("__yoake_cs_")
        .and_then(|s| s.parse::<u32>().ok())
}

struct DetailVisitor<'a> {
    source: &'a str,
    idx: &'a LineIndex,
    details: BTreeMap<SpanRange, SynCallDetail>,
    macro_spans: Vec<SpanRange>,
}

impl<'ast> Visit<'ast> for DetailVisitor<'_> {
    fn visit_expr_call(&mut self, node: &'ast ExprCall) {
        let span = to_span_range(node.span());
        let existing_shim_id = match &*node.func {
            Expr::Path(ep) if ep.qself.is_none() && ep.path.segments.len() == 1 => {
                parse_shim_ident(&ep.path.segments[0].ident.to_string())
            }
            _ => None,
        };
        let (call_start, call_end) = self.idx.span_range(self.source, node.span());
        let (func_start, func_end) = self.idx.span_range(self.source, node.func.span());
        let (_, paren_open_end) = self
            .idx
            .span_range(self.source, node.paren_token.span.open());
        let turbofish_src = match &*node.func {
            Expr::Path(ep) => ep.path.segments.last().and_then(|seg| {
                matches!(seg.arguments, PathArguments::AngleBracketed(_)).then(|| {
                    let (s, e) = self.idx.span_range(self.source, seg.arguments.span());
                    self.source[s..e].to_string()
                })
            }),
            _ => None,
        };
        let first_arg_start = node
            .args
            .first()
            .map(|a| self.idx.span_range(self.source, a.span()).0);
        let arg0_span = node
            .args
            .first()
            .map(|a| self.idx.span_range(self.source, a.span()));
        let arg1_start = node
            .args
            .iter()
            .nth(1)
            .map(|a| self.idx.span_range(self.source, a.span()).0);
        self.details.insert(
            span,
            SynCallDetail {
                is_method: false,
                func_start,
                func_end,
                recv_start: call_start,
                recv_end: call_start,
                recv_needs_parens: false,
                paren_open_end,
                call_end,
                first_arg_start,
                arg0_span,
                arg1_start,
                turbofish_src,
                existing_shim_id,
            },
        );
        visit::visit_expr_call(self, node);
    }

    fn visit_expr_method_call(&mut self, node: &'ast ExprMethodCall) {
        let span = to_span_range(node.span());
        let (recv_start, recv_end) = self.idx.span_range(self.source, node.receiver.span());
        let (_, paren_open_end) = self
            .idx
            .span_range(self.source, node.paren_token.span.open());
        let (_, call_end) = self.idx.span_range(self.source, node.span());
        let first_arg_start = node
            .args
            .first()
            .map(|a| self.idx.span_range(self.source, a.span()).0);
        let turbofish_src = node.turbofish.as_ref().map(|t| {
            let (s, e) = self.idx.span_range(self.source, t.span());
            self.source[s..e].to_string()
        });
        let recv_needs_parens = !matches!(
            &*node.receiver,
            Expr::Path(_)
                | Expr::Field(_)
                | Expr::MethodCall(_)
                | Expr::Call(_)
                | Expr::Index(_)
                | Expr::Paren(_)
                | Expr::Lit(_)
                | Expr::Try(_)
                | Expr::Block(_)
                | Expr::Tuple(_)
                | Expr::Array(_)
                | Expr::Struct(_)
        );
        self.details.insert(
            span,
            SynCallDetail {
                is_method: true,
                func_start: recv_start,
                func_end: recv_end,
                recv_start,
                recv_end,
                recv_needs_parens,
                paren_open_end,
                call_end,
                first_arg_start,
                arg0_span: None,
                arg1_start: None,
                turbofish_src,
                existing_shim_id: None,
            },
        );
        visit::visit_expr_method_call(self, node);
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        self.macro_spans.push(to_span_range(node.span()));
        visit::visit_expr_macro(self, node);
    }

    fn visit_stmt_macro(&mut self, node: &'ast StmtMacro) {
        self.macro_spans.push(to_span_range(node.span()));
        visit::visit_stmt_macro(self, node);
    }

    fn visit_item_fn(&mut self, _node: &'ast ItemFn) {}
    fn visit_impl_item_fn(&mut self, _node: &'ast syn::ImplItemFn) {}
}

fn parse_existing_shim(item_fn: &ItemFn, source: &str, idx: &LineIndex) -> ExistingShim {
    let ident_str = item_fn.sig.ident.to_string();
    let ident_id = parse_shim_ident(&ident_str);
    let hook_attrs = attr::find_hook_attrs(&item_fn.attrs, source, idx);
    let first_hook = hook_attrs.first();
    let attr_id = first_hook.and_then(|a| a.parsed.id);
    let attr_key = first_hook.and_then(|a| a.parsed.key.clone());
    let attr_wrapper_cfg = first_hook.and_then(|a| a.wrapper_cfg.clone());
    let attr_path = first_hook.map(|a| a.attr_path.clone());
    let attr_byte_span = first_hook.map(|a| idx.span_range(source, item_fn.attrs[a.attr_index].span()));
    let kind_is_callsite = first_hook.is_some_and(|a| a.parsed.kind.as_deref() == Some("callsite"));
    let has_inline_always = item_fn.attrs.iter().any(|a| {
        a.path().is_ident("inline")
            && matches!(&a.meta, syn::Meta::List(l) if l.tokens.to_string().trim() == "always")
    });

    let full_end = idx.span_range(source, item_fn.span()).1;
    let full_start = item_fn
        .attrs
        .first()
        .map_or_else(|| idx.span_range(source, item_fn.span()).0, |a| idx.span_range(source, a.span()).0);

    let sig = &item_fn.sig;
    let mut param_names = Vec::new();
    let mut recv_ty = None;
    let mut recv_ty_src = None;
    for (pi_idx, input) in sig.inputs.iter().enumerate() {
        if let syn::FnArg::Typed(pt) = input {
            if pi_idx == 0 {
                recv_ty = Some((*pt.ty).clone());
                let (ts, te) = idx.span_range(source, pt.ty.span());
                let raw = source[ts..te].split_whitespace().collect::<Vec<_>>().join(" ");
                recv_ty_src = Some(
                    raw.replace("< ", "<")
                        .replace(" <", "<")
                        .replace(", >", ">")
                        .replace(" >", ">"),
                );
            }
            if let syn::Pat::Ident(pi) = &*pt.pat {
                param_names.push(pi.ident.to_string());
            }
        }
    }

    let collect_simple_args = |args: &syn::punctuated::Punctuated<Expr, syn::Token![,]>| {
        let collected: Vec<String> = args
            .iter()
            .filter_map(|arg| match arg {
                Expr::Path(ep) if ep.qself.is_none() && ep.path.segments.len() == 1 => {
                    Some(ep.path.segments[0].ident.to_string())
                }
                _ => None,
            })
            .collect();
        (collected.len() == args.len()).then_some(collected)
    };

    let mut turbofish_src = None;
    let mut body_byte_span = None;
    let body = if item_fn.block.stmts.len() == 1 {
        match &item_fn.block.stmts[0] {
            syn::Stmt::Expr(Expr::MethodCall(mc), None)
                if matches!(&*mc.receiver, Expr::Path(ep) if ep.qself.is_none() && ep.path.is_ident("recv")) =>
            {
                if let Some(args) = collect_simple_args(&mc.args) {
                    body_byte_span = Some(idx.span_range(source, mc.span()));
                    turbofish_src = mc.turbofish.as_ref().map(|t| {
                        let (s, e) = idx.span_range(source, t.span());
                        source[s..e].to_string()
                    });
                    ShimBody::Method {
                        method: mc.method.to_string(),
                        args,
                    }
                } else {
                    ShimBody::Other
                }
            }
            syn::Stmt::Expr(Expr::Call(call), None) => {
                if let Expr::Path(ep) = &*call.func
                    && let Some(args) = collect_simple_args(&call.args)
                {
                    body_byte_span = Some(idx.span_range(source, call.span()));
                    turbofish_src = ep.path.segments.last().and_then(|seg| {
                        matches!(seg.arguments, PathArguments::AngleBracketed(_)).then(|| {
                            let (s, e) = idx.span_range(source, seg.arguments.span());
                            source[s..e].to_string()
                        })
                    });
                    ShimBody::QualifiedCall {
                        func_path: ep.clone(),
                        args,
                    }
                } else {
                    ShimBody::Other
                }
            }
            _ => ShimBody::Other,
        }
    } else {
        ShimBody::Other
    };

    ExistingShim {
        ident_id,
        attr_id,
        attr_key,
        attr_wrapper_cfg,
        attr_path,
        attr_byte_span,
        kind_is_callsite,
        has_inline_always,
        byte_span: (full_start, full_end),
        span: to_span_range(item_fn.span()),
        sig_ident_span: to_span_range(item_fn.sig.ident.span()),
        param_names,
        recv_ty,
        recv_ty_src,
        turbofish_src,
        body_byte_span,
        body,
    }
}

struct ShimRefCollector<'a> {
    targets: &'a [Vec<String>],
    skip_targets: &'a [Vec<String>],
    shallow: bool,
    mod_path: Vec<String>,
    in_target_mod: bool,
    shim_ident_spans: &'a BTreeSet<SpanRange>,
    refs: Vec<ShimIdentRef>,
}

impl ShimRefCollector<'_> {
    fn scan_tokens(&mut self, tokens: proc_macro2::TokenStream) {
        if !self.in_target_mod {
            return;
        }
        for tt in tokens {
            match tt {
                TokenTree::Group(g) => self.scan_tokens(g.stream()),
                TokenTree::Ident(ident) => {
                    if let Some(id) = parse_shim_ident(&ident.to_string()) {
                        let sp = to_span_range(ident.span());
                        if !self.shim_ident_spans.contains(&sp) {
                            self.refs.push(ShimIdentRef {
                                id,
                                line: sp[0],
                                col: sp[1],
                            });
                        }
                    }
                }
                _ => {}
            }
        }
    }
}

impl<'ast> Visit<'ast> for ShimRefCollector<'_> {
    fn visit_file(&mut self, node: &'ast syn::File) {
        self.in_target_mod =
            modules::is_target_or_descendant(&self.mod_path, self.targets, self.shallow)
                && !modules::is_target_or_descendant(&self.mod_path, self.skip_targets, false);
        visit::visit_file(self, node);
    }

    fn visit_item_mod(&mut self, node: &'ast syn::ItemMod) {
        if modules::has_cfg_test(&node.attrs) {
            return;
        }
        if node.content.is_some() {
            let prev_path = self.mod_path.clone();
            let prev_in = self.in_target_mod;
            self.mod_path.push(node.ident.to_string());
            self.in_target_mod =
                modules::is_target_or_descendant(&self.mod_path, self.targets, self.shallow)
                    && !modules::is_target_or_descendant(&self.mod_path, self.skip_targets, false);
            visit::visit_item_mod(self, node);
            self.mod_path = prev_path;
            self.in_target_mod = prev_in;
        }
    }

    fn visit_item_fn(&mut self, node: &'ast ItemFn) {
        if self.in_target_mod && !modules::has_cfg_test(&node.attrs) {
            visit::visit_item_fn(self, node);
        }
    }

    fn visit_item_impl(&mut self, node: &'ast syn::ItemImpl) {
        if self.in_target_mod && !modules::has_cfg_test(&node.attrs) {
            visit::visit_item_impl(self, node);
        }
    }

    fn visit_impl_item_fn(&mut self, node: &'ast syn::ImplItemFn) {
        if self.in_target_mod && !modules::has_cfg_test(&node.attrs) {
            visit::visit_impl_item_fn(self, node);
        }
    }

    fn visit_ident(&mut self, ident: &'ast proc_macro2::Ident) {
        if self.in_target_mod
            && let Some(id) = parse_shim_ident(&ident.to_string())
        {
            let sp = to_span_range(ident.span());
            if !self.shim_ident_spans.contains(&sp) {
                self.refs.push(ShimIdentRef {
                    id,
                    line: sp[0],
                    col: sp[1],
                });
            }
        }
    }

    fn visit_expr_macro(&mut self, node: &'ast ExprMacro) {
        self.scan_tokens(node.mac.tokens.clone());
        visit::visit_expr_macro(self, node);
    }

    fn visit_stmt_macro(&mut self, node: &'ast StmtMacro) {
        self.scan_tokens(node.mac.tokens.clone());
        visit::visit_stmt_macro(self, node);
    }

    fn visit_item_macro(&mut self, node: &'ast ItemMacro) {
        self.scan_tokens(node.mac.tokens.clone());
        visit::visit_item_macro(self, node);
    }

    fn visit_impl_item_macro(&mut self, node: &'ast ImplItemMacro) {
        self.scan_tokens(node.mac.tokens.clone());
        visit::visit_impl_item_macro(self, node);
    }

    fn visit_trait_item_macro(&mut self, node: &'ast TraitItemMacro) {
        self.scan_tokens(node.mac.tokens.clone());
        visit::visit_trait_item_macro(self, node);
    }
}

struct AstCollector<'a> {
    source: &'a str,
    idx: &'a LineIndex,
    crate_ident: &'a str,
    targets: &'a [Vec<String>],
    skip_targets: &'a [Vec<String>],
    shallow: bool,
    colliding_short_keys: &'a BTreeSet<String>,
    fn_ledger: &'a FnLedgerIndex,
    mod_path: Vec<String>,
    mod_cfg_tags: Vec<String>,
    mod_cfg_attrs: Vec<String>,
    in_target_mod: bool,
    cfg_test_spans: Vec<SpanRange>,
    existing_shims: Vec<ExistingShim>,
    callers: Vec<CollectedCaller>,
    top_macro_spans: Vec<SpanRange>,
}

impl<'a> AstCollector<'a> {
    fn collect_caller_block(
        &mut self,
        fn_key: String,
        cfg_attrs: Vec<String>,
        block: &Block,
    ) {
        let fn_id = self.fn_ledger.lookup_key(&fn_key);
        let caller_label = fn_id
            .map(|id| format!("fn:{id}"))
            .unwrap_or_else(|| fn_key.clone());
        let (extracted, snapshot) = extract_block_calls(block, &caller_label);
        let mut detail_visitor = DetailVisitor {
            source: self.source,
            idx: self.idx,
            details: BTreeMap::new(),
            macro_spans: Vec::new(),
        };
        detail_visitor.visit_block(block);

        let calls = extracted
            .into_iter()
            .filter_map(|ec| {
                let detail = detail_visitor.details.remove(&ec.span)?;
                Some(CollectedCall {
                    site: ec.site,
                    span: ec.span,
                    detail,
                })
            })
            .collect();

        self.callers.push(CollectedCaller {
            fn_key,
            fn_id,
            cfg_attrs,
            snapshot,
            calls,
            macro_spans: detail_visitor.macro_spans,
        });
    }

    fn collect_cfg_attrs(&self, attrs: &[syn::Attribute]) -> Vec<String> {
        let mut out = self.mod_cfg_attrs.clone();
        for attr in attrs {
            if attr.path().is_ident("cfg") {
                let (s, e) = self.idx.span_range(self.source, attr.span());
                out.push(self.source[s..e].to_string());
            }
        }
        out
    }

    fn visit_items(&mut self, items: &[Item]) {
        self.in_target_mod =
            modules::is_target_or_descendant(&self.mod_path, self.targets, self.shallow)
                && !modules::is_target_or_descendant(&self.mod_path, self.skip_targets, false);
        let prefix = key::module_prefix(self.crate_ident, &self.mod_path);
        let (matched_helpers, _) = if self.in_target_mod {
            run::pair_converted_trait_helpers(
                self.source,
                self.idx,
                &prefix,
                &self.mod_cfg_tags,
                self.colliding_short_keys,
                items,
            )
        } else {
            (BTreeMap::new(), BTreeMap::new())
        };

        for item in items {
            match item {
                Item::Mod(item_mod) => {
                    if modules::has_cfg_test(&item_mod.attrs) {
                        self.cfg_test_spans.push(to_span_range(item_mod.span()));
                        continue;
                    }
                    if let Some((_, inner)) = &item_mod.content {
                        let prev_path = self.mod_path.clone();
                        let prev_tags = self.mod_cfg_tags.clone();
                        let prev_attrs = self.mod_cfg_attrs.clone();
                        let prev_in = self.in_target_mod;
                        self.mod_path.push(item_mod.ident.to_string());
                        self.mod_cfg_tags.extend(key::extract_cfg_tags(&item_mod.attrs));
                        self.mod_cfg_attrs = self.collect_cfg_attrs(&item_mod.attrs);
                        self.visit_items(inner);
                        self.mod_path = prev_path;
                        self.mod_cfg_tags = prev_tags;
                        self.mod_cfg_attrs = prev_attrs;
                        self.in_target_mod = prev_in;
                    }
                }
                Item::Fn(item_fn) => {
                    if modules::has_cfg_test(&item_fn.attrs) {
                        self.cfg_test_spans.push(to_span_range(item_fn.span()));
                        continue;
                    }
                    if !self.in_target_mod {
                        continue;
                    }
                    let is_shim = item_fn.sig.ident.to_string().starts_with("__yoake_cs_")
                        || attr::find_hook_attrs(&item_fn.attrs, self.source, self.idx)
                            .iter()
                            .any(|a| a.parsed.kind.as_deref() == Some("callsite"));
                    if is_shim {
                        self.existing_shims
                            .push(parse_existing_shim(item_fn, self.source, self.idx));
                        continue;
                    }
                    let mut fn_cfg_tags = self.mod_cfg_tags.clone();
                    fn_cfg_tags.extend(key::extract_cfg_tags(&item_fn.attrs));
                    let fn_key = key::free_fn_key(&prefix, &item_fn.sig.ident, &fn_cfg_tags);
                    let cfg_attrs = self.collect_cfg_attrs(&item_fn.attrs);
                    self.collect_caller_block(fn_key, cfg_attrs, &item_fn.block);
                }
                Item::Impl(item_impl) => {
                    if modules::has_cfg_test(&item_impl.attrs) {
                        self.cfg_test_spans.push(to_span_range(item_impl.span()));
                        continue;
                    }
                    if !self.in_target_mod {
                        continue;
                    }
                    let mut impl_cfg_tags = self.mod_cfg_tags.clone();
                    impl_cfg_tags.extend(key::extract_cfg_tags(&item_impl.attrs));
                    let impl_cfg_attrs = self.collect_cfg_attrs(&item_impl.attrs);
                    let trait_path = item_impl.trait_.as_ref().map(|(_, p, _)| p);
                    for impl_item in &item_impl.items {
                        let ImplItem::Fn(method) = impl_item else {
                            continue;
                        };
                        if modules::has_cfg_test(&method.attrs) {
                            self.cfg_test_spans.push(to_span_range(method.span()));
                            continue;
                        }
                        let method_span = self.idx.span_range(self.source, method.span());
                        let fn_key = if trait_path.is_none()
                            && let Some(trait_key) = matched_helpers.get(&method_span)
                        {
                            trait_key.clone()
                        } else {
                            let mut fn_cfg_tags = impl_cfg_tags.clone();
                            fn_cfg_tags.extend(key::extract_cfg_tags(&method.attrs));
                            match trait_path {
                                Some(tp) => {
                                    let short_key = key::trait_method_key(
                                        &prefix,
                                        &item_impl.self_ty,
                                        tp,
                                        &method.sig.ident,
                                        &fn_cfg_tags,
                                        false,
                                    );
                                    if self.colliding_short_keys.contains(&short_key) {
                                        key::trait_method_key(
                                            &prefix,
                                            &item_impl.self_ty,
                                            tp,
                                            &method.sig.ident,
                                            &fn_cfg_tags,
                                            true,
                                        )
                                    } else {
                                        short_key
                                    }
                                }
                                None => key::inherent_method_key(
                                    &prefix,
                                    &item_impl.self_ty,
                                    &method.sig.ident,
                                    &fn_cfg_tags,
                                ),
                            }
                        };
                        let mut cfg_attrs = impl_cfg_attrs.clone();
                        for attr in &method.attrs {
                            if attr.path().is_ident("cfg") {
                                let (s, e) = self.idx.span_range(self.source, attr.span());
                                cfg_attrs.push(self.source[s..e].to_string());
                            }
                        }
                        self.collect_caller_block(fn_key, cfg_attrs, &method.block);
                    }
                }
                Item::Macro(ItemMacro { .. }) if self.in_target_mod => {
                    self.top_macro_spans.push(to_span_range(item.span()));
                }
                _ => {}
            }
        }
    }
}

fn collect_file_ast(
    file: &modules::ScannedFile,
    crate_ident: &str,
    targets: &[Vec<String>],
    skip_targets: &[Vec<String>],
    shallow: bool,
    colliding_short_keys: &BTreeSet<String>,
    fn_ledger: &FnLedgerIndex,
) -> CollectedFile {
    let idx = LineIndex::new(&file.source);
    let style = attr::detect_file_style(&file.parsed.items, &file.source);
    let shim_header_byte_start = file.source.find(SHIM_HEADER);
    let mut collector = AstCollector {
        source: &file.source,
        idx: &idx,
        crate_ident,
        targets,
        skip_targets,
        shallow,
        colliding_short_keys,
        fn_ledger,
        mod_path: file.root_mod_path.clone(),
        mod_cfg_tags: file.root_cfg_tags.clone(),
        mod_cfg_attrs: Vec::new(),
        in_target_mod: false,
        cfg_test_spans: Vec::new(),
        existing_shims: Vec::new(),
        callers: Vec::new(),
        top_macro_spans: Vec::new(),
    };
    collector.visit_items(&file.parsed.items);
    let shim_ident_spans: BTreeSet<SpanRange> = collector
        .existing_shims
        .iter()
        .map(|s| s.sig_ident_span)
        .collect();
    let mut ref_collector = ShimRefCollector {
        targets,
        skip_targets,
        shallow,
        mod_path: file.root_mod_path.clone(),
        in_target_mod: false,
        shim_ident_spans: &shim_ident_spans,
        refs: Vec::new(),
    };
    ref_collector.visit_file(&file.parsed);
    CollectedFile {
        path: file.path.clone(),
        source: file.source.clone(),
        style,
        cfg_test_spans: collector.cfg_test_spans,
        existing_shims: collector.existing_shims,
        shim_refs: ref_collector.refs,
        shim_header_byte_start,
        callers: collector.callers,
        top_macro_spans: collector.top_macro_spans,
    }
}

fn simplify_elided_refs(ty_str: &str) -> String {
    ty_str
        .replace("&'_ mut ", "&mut ")
        .replace("&'_ ", "&")
}

struct ShimSignature {
    arg_tys: Vec<String>,
    ret_ty: Option<String>,
    sig_hash: String,
}

fn format_mapped_type(ty: &Type) -> String {
    let raw = quote!(#ty).to_string();
    let cleaned = raw
        .replace("& '", "&'")
        .replace("& mut ", "&mut ")
        .replace(" :: ", "::")
        .replace("< ", "<")
        .replace(" >", ">")
        .replace(" , ", ", ")
        .replace("[ ", "[")
        .replace(" ]", "]")
        .replace(" ; ", "; ");
    simplify_elided_refs(&cleaned)
}

fn validate_and_format_shim_sig(
    call: &ThirCall,
    callee_params: Option<&[Type]>,
    aliases: &BTreeMap<String, Option<Type>>,
    is_path_call: bool,
) -> Result<ShimSignature, &'static str> {
    if !is_path_call && call.args.is_empty() {
        return Err("missing receiver arg");
    }
    let mut parsed_args = Vec::with_capacity(call.args.len());
    let mut arg_tys = Vec::with_capacity(call.args.len());
    for (idx, arg) in call.args.iter().enumerate() {
        let Some(raw_ty) = arg.ty.as_deref() else {
            return Err("unwritable arg type");
        };
        let base_formatted = simplify_elided_refs(raw_ty.trim());
        let parsed_raw: Type = syn::parse_str(&base_formatted).map_err(|_| "unparseable arg type")?;
        if let Some(param_ty) = callee_params.and_then(|v| v.get(idx)) {
            let (mapped, changed) = apply_static_from_param_ty(&parsed_raw, param_ty, aliases, 0);
            if changed {
                arg_tys.push(format_mapped_type(&mapped));
                parsed_args.push(mapped);
                continue;
            }
        }
        parsed_args.push(parsed_raw);
        arg_tys.push(base_formatted);
    }
    let Some(raw_ret) = call.ret_ty.as_deref() else {
        return Err("unwritable return type");
    };
    let parsed_ret: Type = syn::parse_str(raw_ret).map_err(|_| "unparseable return type")?;
    // A callee declared `-> &'static T` (or `Option<&'static T>`, ...): keep the `'static` in the shim, otherwise
    // the shim narrows it to the receiver's borrow and the caller no longer compiles.
    let mut ret_static_str: Option<String> = None;
    if let Some(callee_ret) = callee_return_ty(callee_params, call.args.len())
        && type_has_named_lifetime(callee_ret)
    {
        // `-> &'r T` where `'r` belongs to the impl or the fn: the shim cannot name it, and tying the output to
        // the receiver's borrow instead breaks callers that keep the result longer.
        return Err("named lifetime in callee return");
    }
    let parsed_ret = match callee_return_ty(callee_params, call.args.len()) {
        Some(callee_ret) => {
            let (mapped, changed) = apply_static_from_param_ty(&parsed_ret, callee_ret, aliases, 0);
            if changed {
                ret_static_str = Some(format_mapped_type(&mapped));
                mapped
            } else {
                parsed_ret
            }
        }
        None => parsed_ret,
    };
    let borrowed_inputs = parsed_args
        .iter()
        .filter(|ty| eligible::type_has_non_static_lifetime(ty))
        .count();
    let borrowed_return = eligible::type_has_non_static_lifetime(&parsed_ret);
    // A borrowed return from a method on a borrowed receiver: use the method elision rule
    // (the output borrows from `&self`) by naming the receiver's outer reference `'r`. If the
    // callee actually ties the output to another argument, the shim fails to borrow-check, so a
    // wrong guess is a compile error, never a silent change.
    let receiver_borrow = !is_path_call
        && matches!(call.kind.as_str(), "method")
        && parsed_args
            .first()
            .is_some_and(eligible::type_has_non_static_lifetime)
        && arg_tys[0].trim_start().starts_with('&');
    let self_borrow = borrowed_return && receiver_borrow;
    if borrowed_return && !self_borrow {
        if borrowed_inputs == 0 {
            return Err("borrowed return with no borrowed inputs");
        }
        if borrowed_inputs > 1 {
            return Err("borrowed return with several borrowed inputs");
        }
    }

    let trimmed_ret = ret_static_str.as_deref().unwrap_or_else(|| raw_ret.trim());
    let ret_ty = if trimmed_ret == "()" {
        None
    } else if self_borrow {
        Some(name_elided_lifetimes(trimmed_ret, "'r"))
    } else {
        Some(simplify_elided_refs(trimmed_ret))
    };
    if self_borrow {
        arg_tys[0] = name_outer_reference(&arg_tys[0], "'r");
    }
    // A borrowed return with exactly one borrowed input that is not a borrowed receiver (for
    // example `Iter<'_, T>` by value -> `Enumerate<Iter<'_, T>>`): tie that input's elided
    // lifetimes and the result's to one named `'r`, which is what elision means for one input.
    let mut ret_ty = ret_ty;
    if borrowed_return && !self_borrow && borrowed_inputs == 1 {
        if let Some(index) = parsed_args
            .iter()
            .position(|ty| eligible::type_has_non_static_lifetime(ty))
        {
            let formatted_arg = arg_tys[index].clone();
            arg_tys[index] = name_elided_lifetimes(&formatted_arg, "'r");
            ret_ty = Some(name_elided_lifetimes(trimmed_ret, "'r"));
        }
    }
    let sig_hash_input = format!(
        "fn({}) -> {}",
        arg_tys.join(", "),
        ret_ty.as_deref().unwrap_or("()")
    );
    let sig_hash = Ledger::sig_hash(&sig_hash_input);
    Ok(ShimSignature {
        arg_tys,
        ret_ty,
        sig_hash,
    })
}

/// `&'_ T` / `&T` / `&'_ mut T` -> `&'r T` / `&'r mut T` for the outer reference only; inner `'_`
/// stay elided.
fn name_outer_reference(ty: &str, lifetime: &str) -> String {
    let ty = ty.trim();
    let rest = ty.strip_prefix('&').unwrap_or(ty).trim_start();
    let rest = rest.strip_prefix("'_").map_or(rest, str::trim_start);
    let inner = simplify_elided_refs(rest);
    format!("&{lifetime} {inner}")
}

/// Every elided reference (`&T`, `&'_ T`) and every `'_` in a return type become `lifetime`.
fn name_elided_lifetimes(ty: &str, lifetime: &str) -> String {
    let mut out = String::with_capacity(ty.len() + 8);
    let bytes = ty.as_bytes();
    let mut index = 0;
    while index < ty.len() {
        let rest = &ty[index..];
        if let Some(after) = rest.strip_prefix("'_") {
            if !after.starts_with(|c: char| c.is_alphanumeric() || c == '_') {
                out.push_str(lifetime);
                index += 2;
                continue;
            }
        }
        if bytes[index] == b'&' {
            out.push('&');
            index += 1;
            let tail = ty[index..].trim_start();
            if !tail.starts_with('\'') {
                out.push_str(lifetime);
                out.push(' ');
            }
            continue;
        }
        let ch = rest.chars().next().unwrap();
        out.push(ch);
        index += ch.len_utf8();
    }
    out
}

fn recv_adjust_prefix(adjust: Option<&RecvAdjust>) -> Result<String, String> {
    let Some(adj) = adjust else {
        return Ok(String::new());
    };
    let stars = "*".repeat(adj.derefs);
    match adj.borrow.as_str() {
        "none" => Ok(stars),
        "shared" => Ok(format!("&{stars}")),
        "mut" => Ok(format!("&mut {stars}")),
        other => Err(format!("unknown recv_adjust borrow kind '{other}'")),
    }
}

fn to_local_callee_path(path: &str, crate_ident: &str) -> String {
    let prefix = format!("{crate_ident}::");
    if let Some(rest) = path.strip_prefix(&prefix) {
        format!("crate::{rest}")
    } else {
        path.to_string()
    }
}

fn strip_outer_reference_str(ty: &str) -> String {
    let ty = ty.trim();
    let Some(rest) = ty.strip_prefix('&') else {
        return ty.to_string();
    };
    let mut rest = rest.trim_start();
    if rest.starts_with('\'') {
        let end = rest[1..]
            .find(|c: char| !c.is_alphanumeric() && c != '_')
            .map_or(rest.len(), |off| 1 + off);
        rest = rest[end..].trim_start();
    }
    if let Some(after_mut) = rest.strip_prefix("mut")
        && after_mut.starts_with(char::is_whitespace)
    {
        rest = after_mut.trim_start();
    }
    rest.to_string()
}

fn strip_outer_reference_ty(mut ty: &Type) -> Type {
    loop {
        match ty {
            Type::Group(g) => ty = &g.elem,
            Type::Paren(p) => ty = &p.elem,
            Type::Reference(r) => return (*r.elem).clone(),
            _ => return ty.clone(),
        }
    }
}

fn type_needs_angle_brackets_in_ufcs(mut ty: &Type) -> bool {
    loop {
        match ty {
            Type::Group(g) => ty = &g.elem,
            Type::Paren(p) => ty = &p.elem,
            _ => break,
        }
    }
    let Type::Path(tp) = ty else {
        return true;
    };
    if tp.qself.is_some() {
        return true;
    }
    tp.path.segments.iter().any(|seg| match &seg.arguments {
        PathArguments::None => false,
        PathArguments::Parenthesized(_) => true,
        PathArguments::AngleBracketed(ab) => ab
            .args
            .iter()
            .any(|arg| !matches!(arg, syn::GenericArgument::Lifetime(_))),
    })
}

fn format_qualified_callee(
    crate_ident: &str,
    callee_path: &str,
    recv_ty_str: &str,
    turbofish_src: Option<&str>,
) -> Result<String, String> {
    let tf = turbofish_src.unwrap_or("");
    let owner_str = strip_outer_reference_str(recv_ty_str);
    if let Some(rest) = callee_path.strip_prefix("<Self as ")
        && let Some((trait_path, method)) = rest.rsplit_once(">::")
    {
        let local_trait = to_local_callee_path(trait_path, crate_ident);
        return Ok(format!("<{owner_str} as {local_trait}>::{method}{tf}"));
    }
    let (_, method) = callee_path
        .rsplit_once("::")
        .ok_or_else(|| format!("malformed callee_path '{callee_path}'"))?;
    let parsed_owner: Type = syn::parse_str(&owner_str)
        .map_err(|e| format!("unparseable receiver owner type '{owner_str}': {e}"))?;
    if type_needs_angle_brackets_in_ufcs(&parsed_owner) {
        Ok(format!("<{owner_str}>::{method}{tf}"))
    } else {
        let local_callee = to_local_callee_path(callee_path, crate_ident);
        Ok(format!("{local_callee}{tf}"))
    }
}

fn strip_method_turbofish(ep: &ExprPath) -> ExprPath {
    let mut out = ep.clone();
    if let Some(last) = out.path.segments.last_mut() {
        last.arguments = PathArguments::None;
    }
    out
}

#[derive(Clone)]
struct DesiredShim {
    id: u32,
    key: String,
    cfg_attrs: Vec<String>,
    arg_tys: Vec<String>,
    ret_ty: Option<String>,
    callee_path: String,
    turbofish_src: Option<String>,
    is_path_call: bool,
}

impl DesiredShim {
    fn sig_header_string(&self) -> String {
        let mut params = Vec::with_capacity(self.arg_tys.len());
        if self.is_path_call {
            for (idx, ty) in self.arg_tys.iter().enumerate() {
                params.push(format!("a{idx}: {ty}"));
            }
        } else {
            params.push(format!("recv: {}", self.arg_tys[0]));
            for (idx, ty) in self.arg_tys.iter().enumerate().skip(1) {
                params.push(format!("a{}: {}", idx - 1, ty));
            }
        }
        let ret_part = self
            .ret_ty
            .as_deref()
            .map(|r| format!(" -> {r}"))
            .unwrap_or_default();
        let uses_r = self.arg_tys.iter().chain(self.ret_ty.iter()).any(|ty| ty.contains("'r"));
        let generics = if uses_r { "<'r>" } else { "" };
        format!("fn __yoake_cs_{}{}({}){}", self.id, generics, params.join(", "), ret_part)
    }

    fn body_call_args(&self) -> Vec<String> {
        if self.is_path_call {
            (0..self.arg_tys.len()).map(|i| format!("a{i}")).collect()
        } else {
            std::iter::once("recv".to_string())
                .chain((1..self.arg_tys.len()).map(|i| format!("a{}", i - 1)))
                .collect()
        }
    }

    fn render(&self, crate_ident: &str, style: &FileStyle, nl: &str) -> Result<String, String> {
        let mut lines = Vec::new();
        for cfg in &self.cfg_attrs {
            lines.push(cfg.clone());
        }
        let expected = ExpectedHookAttr {
            method: false,
            self_ty_src: None,
            self_ty_norm: None,
            id: self.id,
            key: &self.key,
            kind: Some("callsite"),
        };
        lines.push(attr::format_hook_attr(&expected, None, None, style));
        lines.push("#[inline(always)]".to_string());
        lines.push(format!("{} {{", self.sig_header_string()));
        let qualified_fn = if self.is_path_call
            && !self.callee_path.starts_with("<Self as ")
            && !self.callee_path.contains("{impl#")
        {
            let local_callee = to_local_callee_path(&self.callee_path, crate_ident);
            let tf = self.turbofish_src.as_deref().unwrap_or("");
            format!("{local_callee}{tf}")
        } else {
            format_qualified_callee(
                crate_ident,
                &self.callee_path,
                self.arg_tys.first().map(String::as_str).unwrap_or(""),
                self.turbofish_src.as_deref(),
            )?
        };
        let call_args = self.body_call_args().join(", ");
        lines.push(format!("    {qualified_fn}({call_args})"));
        lines.push("}".to_string());
        Ok(lines.join(nl))
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
struct ShimShapeStatus {
    body_old_method_form: bool,
    attr_needs_update: bool,
}

fn verify_shim_shape(
    shim: &ExistingShim,
    id: u32,
    expected_key: &str,
    crate_ident: &str,
    expected_callee_path: Option<&str>,
    style: &FileStyle,
    file_path: &Path,
) -> Result<ShimShapeStatus, String> {
    if shim.attr_id != Some(id)
        || shim.attr_key.as_deref() != Some(expected_key)
        || !shim.kind_is_callsite
        || !shim.has_inline_always
    {
        return Err(format!(
            "{}: shim __yoake_cs_{id} attribute does not match ledger key {:?}",
            file_path.display(),
            expected_key
        ));
    }
    let is_path_style = shim.param_names.first().map(String::as_str) != Some("recv");
    let expected_params: Vec<String> = if is_path_style {
        (0..shim.param_names.len()).map(|i| format!("a{i}")).collect()
    } else {
        std::iter::once("recv".to_string())
            .chain((1..shim.param_names.len()).map(|i| format!("a{}", i - 1)))
            .collect()
    };
    if shim.param_names != expected_params {
        return Err(format!(
            "{}: shim __yoake_cs_{id} signature or body does not match expected form",
            file_path.display()
        ));
    }
    let expected_method_args: Vec<String> = (1..shim.param_names.len())
        .map(|i| format!("a{}", i - 1))
        .collect();
    let expected_call_args: Vec<String> = if is_path_style {
        expected_params.clone()
    } else {
        std::iter::once("recv".to_string())
            .chain(expected_method_args.iter().cloned())
            .collect()
    };
    let attr_needs_update = !attr::callsite_wrapper_matches(shim.attr_wrapper_cfg.as_deref(), style);

    match &shim.body {
        ShimBody::Method { method, args } => {
            if is_path_style {
                return Err(format!(
                    "{}: shim __yoake_cs_{id} signature or body does not match expected form",
                    file_path.display()
                ));
            }
            let expected_method = expected_callee_path.and_then(|cp| cp.rsplit("::").next());
            if args == &expected_method_args && expected_method.is_none_or(|em| em == method) {
                Ok(ShimShapeStatus {
                    body_old_method_form: true,
                    attr_needs_update,
                })
            } else {
                Err(format!(
                    "{}: shim __yoake_cs_{id} signature or body does not match expected form",
                    file_path.display()
                ))
            }
        }
        ShimBody::QualifiedCall { func_path, args } => {
            if args != &expected_call_args {
                return Err(format!(
                    "{}: shim __yoake_cs_{id} signature or body does not match expected form",
                    file_path.display()
                ));
            }
            if let Some(callee_path) = expected_callee_path {
                let actual_ep = strip_method_turbofish(func_path);
                let actual_tokens = key::canonical_expr_path_tokens(&actual_ep);
                let matches_direct = if is_path_style && !callee_path.starts_with("<Self as ") {
                    let direct_callee = to_local_callee_path(callee_path, crate_ident);
                    syn::parse_str::<ExprPath>(&direct_callee).is_ok_and(|ep| {
                        key::canonical_expr_path_tokens(&ep) == actual_tokens
                    })
                } else {
                    false
                };
                if !matches_direct {
                    let Some(recv_ty) = &shim.recv_ty else {
                        if is_path_style {
                            return Err(format!(
                                "{}: shim __yoake_cs_{id} body '{}' does not match expected '{}'",
                                file_path.display(),
                                quote!(#actual_ep),
                                to_local_callee_path(callee_path, crate_ident),
                            ));
                        }
                        return Err(format!(
                            "{}: shim __yoake_cs_{id} is missing recv parameter type",
                            file_path.display()
                        ));
                    };
                    let owner_ty = strip_outer_reference_ty(recv_ty);
                    let owner_str = quote!(#owner_ty).to_string();
                    let expected_callee =
                        format_qualified_callee(crate_ident, callee_path, &owner_str, None)?;
                    let expected_ep: ExprPath = syn::parse_str(&expected_callee).map_err(|e| {
                        format!(
                            "{}: invalid expected qualified callee '{expected_callee}': {e}",
                            file_path.display()
                        )
                    })?;
                    if actual_tokens != key::canonical_expr_path_tokens(&expected_ep) {
                        return Err(format!(
                            "{}: shim __yoake_cs_{id} body '{}' does not match expected '{expected_callee}'",
                            file_path.display(),
                            quote!(#actual_ep)
                        ));
                    }
                }
            }
            Ok(ShimShapeStatus {
                body_old_method_form: false,
                attr_needs_update,
            })
        }
        ShimBody::Other => Err(format!(
            "{}: shim __yoake_cs_{id} signature or body does not match expected form",
            file_path.display()
        )),
    }
}

fn allocate_unique_key(base_key: &str, used_keys: &mut BTreeSet<String>) -> String {
    if used_keys.insert(base_key.to_string()) {
        return base_key.to_string();
    }
    let mut n = 1usize;
    loop {
        let cand = format!("{base_key}#{n}");
        if used_keys.insert(cand.clone()) {
            return cand;
        }
        n += 1;
    }
}

fn file_fnv1a_hex(bytes: &[u8]) -> String {
    yoake_callsite_match::format_hash(yoake_callsite_match::fnv1a_64(bytes))
}

fn find_thir_file_entry<'a>(
    scanned_path: &str,
    files: &'a BTreeMap<String, ThirFileSummary>,
) -> Option<(&'a String, &'a ThirFileSummary)> {
    let mut best: Option<(&String, &ThirFileSummary, usize)> = None;
    for (thir_file, summary) in files {
        let norm = norm_slash(thir_file);
        if path_matches_suffix(scanned_path, &norm) || path_matches_suffix(&norm, scanned_path) {
            let score = scanned_path.len().min(norm.len());
            if best.is_none_or(|(_, _, best_score)| score > best_score) {
                best = Some((thir_file, summary, score));
            }
        }
    }
    best.map(|(k, v, _)| (k, v))
}

fn resolve_listed_thir_file_bytes(
    thir_file: &str,
    crate_root: &Path,
    scanned_files: &[&modules::ScannedFile],
    scanned_paths: &[String],
) -> Result<Option<Vec<u8>>, String> {
    if let Some(fi) = match_thir_file(thir_file, scanned_paths) {
        return Ok(Some(scanned_files[fi].source.as_bytes().to_vec()));
    }
    let direct = Path::new(thir_file);
    if direct.is_file() {
        let bytes = std::fs::read(direct)
            .map_err(|e| format!("failed to read {}: {e}", direct.display()))?;
        return Ok(Some(bytes));
    }
    let under_crate = crate_root.join(thir_file);
    if under_crate.is_file() {
        let bytes = std::fs::read(&under_crate)
            .map_err(|e| format!("failed to read {}: {e}", under_crate.display()))?;
        return Ok(Some(bytes));
    }
    Ok(None)
}

fn verify_thir_freshness(
    crate_root: &Path,
    scanned_files: &[&modules::ScannedFile],
    thir_dump: &ThirDump,
) -> Result<(), String> {
    let scanned_paths: Vec<String> = scanned_files
        .iter()
        .map(|f| norm_slash(&f.path.to_string_lossy()))
        .collect();

    for (thir_file, summary) in &thir_dump.files {
        let maybe_bytes =
            resolve_listed_thir_file_bytes(thir_file, crate_root, scanned_files, &scanned_paths)?;
        let now_sha = maybe_bytes
            .as_deref()
            .map(file_fnv1a_hex)
            .unwrap_or_else(|| "<missing>".to_string());
        let Some(dump_sha) = summary.sha.as_deref().filter(|s| !s.is_empty()) else {
            return Err(format!(
                "THIR is stale: {thir_file} changed since the dump (dump sha <missing>, now {now_sha}); re-run yoake-hook-thir dump"
            ));
        };
        if let Some(bytes) = maybe_bytes.as_deref() {
            let len_mismatch = summary.len.is_some_and(|len| len != bytes.len() as u64);
            if now_sha != dump_sha || len_mismatch {
                return Err(format!(
                    "THIR is stale: {thir_file} changed since the dump (dump sha {dump_sha}, now {now_sha}); re-run yoake-hook-thir dump"
                ));
            }
        }
    }

    for (sf, sp) in scanned_files.iter().zip(&scanned_paths) {
        let now_sha = file_fnv1a_hex(sf.source.as_bytes());
        let Some((_, summary)) = find_thir_file_entry(sp, &thir_dump.files) else {
            let rel = display_rel_path(crate_root, &sf.path);
            return Err(format!(
                "THIR is stale: {rel} changed since the dump (dump sha <missing>, now {now_sha}); re-run yoake-hook-thir dump"
            ));
        };
        if summary.sha.as_deref().is_none_or(str::is_empty) {
            let rel = display_rel_path(crate_root, &sf.path);
            return Err(format!(
                "THIR is stale: {rel} changed since the dump (dump sha <missing>, now {now_sha}); re-run yoake-hook-thir dump"
            ));
        }
    }

    Ok(())
}

pub fn execute(config: &Config) -> Result<bool, String> {
    let crate_ident = key::normalize_crate_name(&config.crate_name);
    let targets = config
        .modules
        .iter()
        .map(|m| modules::normalize_module_arg(m))
        .collect::<Result<Vec<_>, _>>()?;

    let skip_targets = config
        .skip_callsite_modules
        .iter()
        .map(|m| modules::normalize_module_arg(m))
        .collect::<Result<Vec<_>, _>>()?;

    let scanned_files = modules::collect_module_files(
        &config.crate_root,
        &config.crate_name,
        &targets,
        config.shallow,
    )?;
    let active_scanned_files: Vec<&modules::ScannedFile> = scanned_files
        .iter()
        .filter(|sf| !modules::is_target_or_descendant(&sf.root_mod_path, &skip_targets, false))
        .collect();
    let thir_dump = match &config.thir {
        None => {
            if config.mode == Mode::Apply {
                return Err("apply --callsites requires --thir <calls.json>".to_string());
            }
            None
        }
        Some(thir_path) => {
            let thir_text = std::fs::read_to_string(thir_path)
                .map_err(|e| format!("failed to read {}: {e}", thir_path.display()))?;
            let thir_dump: ThirDump = serde_json::from_str(&thir_text)
                .map_err(|e| format!("invalid THIR JSON in {}: {e}", thir_path.display()))?;
            if let Some(dump_crate) = thir_dump.crate_name.as_deref()
                && key::normalize_crate_name(dump_crate) != crate_ident
            {
                return Err(format!(
                    "THIR dump crate '{dump_crate}' does not match --crate-name '{}'",
                    config.crate_name
                ));
            }
            verify_thir_freshness(&config.crate_root, &active_scanned_files, &thir_dump)?;
            Some(thir_dump)
        }
    };
    let colliding_short_keys = run::collect_colliding_short_keys(
        &crate_ident,
        &targets,
        config.shallow,
        &scanned_files,
    );
    let mut static_index = StaticParamIndex::new(
        &config.crate_root,
        &config.ledger,
        &config.crate_name,
        &crate_ident,
        &scanned_files,
        &colliding_short_keys,
    );

    let mut ledger_set = ledger_io::load_ledger_set(&config.ledger)?;
    let mut manual_keys = ledger_io::read_manual_exclusions(&config.ledger, &crate_ident)?;
    if let Some(shard) = ledger_set.shard(&crate_ident) {
        for ex in shard.excluded() {
            if ex.manual {
                manual_keys
                    .entry(ex.key.clone())
                    .or_insert_with(|| ex.reason.clone());
            }
        }
    }

    let existing_sites = ledger_io::read_callsite_sites(&config.ledger, &crate_ident)?;
    let tombstoned_sites = ledger_io::read_tombstoned_callsite_keys(&config.ledger, &crate_ident)?;
    let mut site_manual_keys: BTreeMap<String, (String, SiteMeta)> = BTreeMap::new();
    for (k, meta) in tombstoned_sites {
        if let Some(reason) = manual_keys.remove(&k) {
            site_manual_keys.insert(k, (reason, meta));
        }
    }
    let fn_ledger = FnLedgerIndex::build(&config.ledger, &ledger_set, &crate_ident)?;

    let collected_files: Vec<CollectedFile> = active_scanned_files
        .iter()
        .map(|sf| {
            collect_file_ast(
                sf,
                &crate_ident,
                &targets,
                &skip_targets,
                config.shallow,
                &colliding_short_keys,
                &fn_ledger,
            )
        })
        .collect();

    match thir_dump.as_ref() {
        None => execute_syn_only_check(
            config,
            &crate_ident,
            &mut ledger_set,
            &existing_sites,
            &collected_files,
        ),
        Some(thir_dump) => execute_with_thir(
            config,
            &crate_ident,
            &mut ledger_set,
            &manual_keys,
            &site_manual_keys,
            &existing_sites,
            &fn_ledger,
            &mut static_index,
            &collected_files,
            thir_dump,
        ),
    }
}

fn caller_belongs_to_scan(
    entry: &yoake_hook_ledger::Entry,
    site_meta: Option<&SiteMeta>,
    scanned_fn_ids: &BTreeSet<u32>,
    scanned_fn_keys: &BTreeSet<String>,
) -> bool {
    if let Some(meta) = site_meta {
        return scanned_fn_ids.contains(&meta.caller);
    }
    if let Some((caller_part, _)) = entry.key.split_once("@call:") {
        if let Some(id_str) = caller_part.strip_prefix("fn:")
            && let Ok(id) = id_str.parse::<u32>()
        {
            return scanned_fn_ids.contains(&id);
        }
        return scanned_fn_keys.contains(caller_part);
    }
    false
}

#[derive(Default)]
struct CallsiteAllowlist {
    exact: BTreeSet<String>,
    compact: BTreeSet<String>,
}

impl CallsiteAllowlist {
    fn load(ledger_dir: &Path) -> Result<Self, String> {
        let path = ledger_dir.join("callsite-allow.txt");
        if !path.is_file() {
            return Ok(Self::default());
        }
        let text = std::fs::read_to_string(&path)
            .map_err(|e| format!("failed to read {}: {e}", path.display()))?;
        let mut out = Self::default();
        for line in text.lines() {
            let trimmed = line.split('#').next().unwrap_or("").trim();
            if !trimmed.is_empty() {
                out.exact.insert(trimmed.to_string());
                out.compact
                    .insert(trimmed.chars().filter(|c| !c.is_whitespace()).collect());
            }
        }
        Ok(out)
    }

    fn contains(&self, candidate: &str) -> bool {
        if self.exact.contains(candidate) {
            return true;
        }
        let comp: String = candidate.chars().filter(|c| !c.is_whitespace()).collect();
        self.compact.contains(&comp)
    }
}

fn split_hot_caller_line(trimmed: &str) -> Option<(&str, &str)> {
    let mut angle_depth = 0usize;
    let mut prev = None;
    for (idx, ch) in trimmed.char_indices() {
        match ch {
            '<' => angle_depth += 1,
            '>' if prev != Some('-') => angle_depth = angle_depth.saturating_sub(1),
            _ if ch.is_whitespace() && angle_depth == 0 => {
                let key = &trimmed[..idx];
                let reason = trimmed[idx..].trim();
                if key.is_empty() || reason.is_empty() {
                    return None;
                }
                return Some((key, reason));
            }
            _ => {}
        }
        prev = Some(ch);
    }
    None
}

fn load_hot_callers_file(ledger_dir: &Path) -> Result<BTreeMap<String, String>, String> {
    let path = ledger_dir.join("callsite-hot-callers.txt");
    if !path.is_file() {
        return Ok(BTreeMap::new());
    }
    let text = std::fs::read_to_string(&path)
        .map_err(|e| format!("failed to read {}: {e}", path.display()))?;
    let mut out = BTreeMap::new();
    for (line_idx, raw_line) in text.lines().enumerate() {
        let trimmed = raw_line.split('#').next().unwrap_or("").trim();
        if trimmed.is_empty() {
            continue;
        }
        let Some((caller_key, reason)) = split_hot_caller_line(trimmed) else {
            return Err(format!(
                "{}:{}: expected '<caller fn key> <reason>', got '{trimmed}'",
                path.display(),
                line_idx + 1
            ));
        };
        out.insert(caller_key.to_string(), reason.to_string());
    }
    Ok(out)
}

fn callee_first_segment(callee_path: &str) -> Option<&str> {
    if let Some(rest) = callee_path.strip_prefix("<Self as ")
        && let Some((trait_path, _)) = rest.rsplit_once(">::")
    {
        return trait_path.split("::").next();
    }
    if callee_path.starts_with(['<', '[', '(', '*']) {
        return None;
    }
    callee_path.split("::").next()
}

fn is_engine_callee(
    callee_path: &str,
    crate_ident: &str,
    engine_crates: Option<&[String]>,
    thir_externs: &BTreeSet<String>,
) -> bool {
    let Some(first) = callee_first_segment(callee_path) else {
        return false;
    };
    if first == "crate" {
        return true;
    }
    match engine_crates {
        Some(list) => list.iter().any(|c| c == first),
        None => {
            let direct_ok = thir_externs.is_empty()
                || first == crate_ident
                || thir_externs.contains(first);
            direct_ok && (first.starts_with("horizon_") || first.starts_with("yoake_") || first == crate_ident)
        }
    }
}

fn is_allowlisted(
    callee_path: &str,
    recv_ty_str: Option<&str>,
    allowlist: &CallsiteAllowlist,
) -> bool {
    if allowlist.contains(callee_path) {
        return true;
    }
    if let Some(rest) = callee_path.strip_prefix("<Self as ")
        && let Some((trait_path, method)) = rest.rsplit_once(">::")
    {
        if allowlist.contains(&format!("{trait_path}::{method}")) {
            return true;
        }
        if let Some(short) = trait_path.rsplit("::").next()
            && allowlist.contains(&format!("{short}::{method}"))
        {
            return true;
        }
        if let Some(rt) = recv_ty_str {
            let owner = strip_outer_reference_str(rt);
            if allowlist.contains(&format!("<{owner} as {trait_path}>::{method}")) {
                return true;
            }
        }
        return false;
    }
    if let Some((owner_path, method)) = callee_path.rsplit_once("::") {
        if let Some(short) = owner_path.rsplit("::").next()
            && allowlist.contains(&format!("{short}::{method}"))
        {
            return true;
        }
        if let Some(rt) = recv_ty_str {
            let owner = strip_outer_reference_str(rt);
            if allowlist.contains(&format!("<{owner}>::{method}"))
                || allowlist.contains(&format!("{owner}::{method}"))
            {
                return true;
            }
        }
    }
    false
}

fn check_callee_policy(
    callee_path: &str,
    recv_ty_str: Option<&str>,
    crate_ident: &str,
    engine_crates: Option<&[String]>,
    thir_externs: &BTreeSet<String>,
    allowlist: &CallsiteAllowlist,
    track_caller_set: &BTreeSet<String>,
) -> Result<(), &'static str> {
    if track_caller::is_track_caller(callee_path, track_caller_set) {
        return Err("track-caller");
    }
    if !is_engine_callee(callee_path, crate_ident, engine_crates, thir_externs)
        && !is_allowlisted(callee_path, recv_ty_str, allowlist)
    {
        return Err("non-engine callee");
    }
    Ok(())
}

fn verify_s2_refs(
    crate_root: &Path,
    files: &[CollectedFile],
    shims_by_id: &BTreeMap<u32, (usize, &ExistingShim)>,
) -> Result<(), String> {
    let mut refs_by_id: BTreeMap<u32, Vec<(usize, usize, usize)>> = BTreeMap::new();
    for (fi, file) in files.iter().enumerate() {
        for r in &file.shim_refs {
            refs_by_id.entry(r.id).or_default().push((fi, r.line, r.col));
        }
    }
    let fmt_loc = |fi: usize, line: usize, col: usize| {
        format!("{}:{line}:{col}", display_rel_path(crate_root, &files[fi].path))
    };

    let mut errors = Vec::new();
    for (&id, &(shim_fi, shim)) in shims_by_id {
        match refs_by_id.get(&id) {
            None => {
                let loc = fmt_loc(shim_fi, shim.sig_ident_span[0], shim.sig_ident_span[1]);
                errors.push(format!("{loc}: shim __yoake_cs_{id} has 0 references in source"));
            }
            Some(locs) if locs.len() > 1 => {
                let joined = locs
                    .iter()
                    .map(|&(fi, l, c)| fmt_loc(fi, l, c))
                    .collect::<Vec<_>>()
                    .join(", ");
                errors.push(format!(
                    "shim __yoake_cs_{id} is referenced {} times (expected 1): {joined}",
                    locs.len()
                ));
            }
            Some(locs) => {
                let (ref_fi, l, c) = locs[0];
                if ref_fi != shim_fi {
                    errors.push(format!(
                        "{}: reference to __yoake_cs_{id} is in a different file than its shim {}",
                        fmt_loc(ref_fi, l, c),
                        display_rel_path(crate_root, &files[shim_fi].path)
                    ));
                }
            }
        }
    }
    for (&id, locs) in &refs_by_id {
        if !shims_by_id.contains_key(&id) {
            let joined = locs
                .iter()
                .map(|&(fi, l, c)| fmt_loc(fi, l, c))
                .collect::<Vec<_>>()
                .join(", ");
            errors.push(format!(
                "reference to __yoake_cs_{id} has no matching shim fn: {joined}"
            ));
        }
    }
    if errors.is_empty() {
        Ok(())
    } else {
        Err(errors.join("\n"))
    }
}

fn strip_adjust_prefix_len(arg0: &str) -> usize {
    let bytes = arg0.as_bytes();
    let mut i = 0;
    if arg0[i..].starts_with("&mut") {
        let after_mut = i + 4;
        if after_mut < bytes.len() && bytes[after_mut].is_ascii_whitespace() {
            i = after_mut;
            while i < bytes.len() && bytes[i].is_ascii_whitespace() {
                i += 1;
            }
        }
    } else if arg0[i..].starts_with('&') {
        i += 1;
        while i < bytes.len() && bytes[i].is_ascii_whitespace() {
            i += 1;
        }
    }
    while i < bytes.len() && bytes[i] == b'*' {
        i += 1;
    }
    i
}

fn execute_syn_only_check(
    config: &Config,
    crate_ident: &str,
    ledger_set: &mut LedgerSet,
    existing_sites: &BTreeMap<u32, SiteMeta>,
    files: &[CollectedFile],
) -> Result<bool, String> {
    let mut scanned_fn_ids = BTreeSet::new();
    let mut scanned_fn_keys = BTreeSet::new();
    let mut shim_calls: BTreeMap<u32, Vec<usize>> = BTreeMap::new();
    let mut shims_by_id: BTreeMap<u32, (usize, &ExistingShim)> = BTreeMap::new();
    let mut check_failures = Vec::new();

    for (fi, file) in files.iter().enumerate() {
        for caller in &file.callers {
            scanned_fn_keys.insert(caller.fn_key.clone());
            if let Some(id) = caller.fn_id {
                scanned_fn_ids.insert(id);
            }
            for call in &caller.calls {
                if let Some(id) = call.detail.existing_shim_id {
                    shim_calls.entry(id).or_default().push(fi);
                }
            }
        }
        let mut prev_id = None;
        for shim in &file.existing_shims {
            let Some(id) = shim.ident_id else {
                check_failures.push(format!("{}: malformed callsite shim name", file.path.display()));
                continue;
            };
            if prev_id.is_some_and(|p| id <= p) {
                check_failures.push(format!(
                    "{}: callsite shims are not sorted by id",
                    file.path.display()
                ));
            }
            prev_id = Some(id);
            if shims_by_id.insert(id, (fi, shim)).is_some() {
                check_failures.push(format!("duplicate callsite shim __yoake_cs_{id}"));
            }
            if file.shim_header_byte_start.is_none() {
                check_failures.push(format!(
                    "{}: missing call-site shim header comment",
                    file.path.display()
                ));
            }
        }
    }

    let shard = ledger_set.shard(crate_ident);
    let mut live_by_id: BTreeMap<u32, &yoake_hook_ledger::Entry> = BTreeMap::new();
    let mut summary = CallsiteSummary::default();
    if let Some(shard) = shard {
        for entry in shard.live() {
            if entry.kind == Kind::Callsite
                && caller_belongs_to_scan(
                    entry,
                    existing_sites.get(&entry.id),
                    &scanned_fn_ids,
                    &scanned_fn_keys,
                )
            {
                live_by_id.insert(entry.id, entry);
            }
        }
        for ex in shard.excluded() {
            if ex.kind == Kind::Callsite
                && let Some((caller_part, _)) = ex.key.split_once("@call:")
            {
                let in_scan = caller_part
                    .strip_prefix("fn:")
                    .and_then(|s| s.parse::<u32>().ok())
                    .is_some_and(|id| scanned_fn_ids.contains(&id))
                    || scanned_fn_keys.contains(caller_part);
                if in_scan {
                    summary.exclude(&ex.reason);
                }
            }
        }
    }

    verify_s2_refs(&config.crate_root, files, &shims_by_id)?;

    for (&id, file_idxs) in &shim_calls {
        if !live_by_id.contains_key(&id) {
            return Err(format!(
                "call to __yoake_cs_{id} in {} has no live callsite entry in ledger",
                files[file_idxs[0]].path.display()
            ));
        }
        if let Some(&(shim_fi, _)) = shims_by_id.get(&id) {
            for &call_fi in file_idxs {
                if call_fi != shim_fi {
                    return Err(format!(
                        "call to __yoake_cs_{id} in {} is in a different file than its shim",
                        files[call_fi].path.display()
                    ));
                }
            }
        } else {
            return Err(format!(
                "call to __yoake_cs_{id} in {} has no matching shim fn",
                files[file_idxs[0]].path.display()
            ));
        }
    }

    for (&id, &(fi, shim)) in &shims_by_id {
        let Some(entry) = live_by_id.get(&id) else {
            return Err(format!(
                "{}: shim __yoake_cs_{id} has no live callsite entry in ledger",
                files[fi].path.display()
            ));
        };
        if !shim_calls.contains_key(&id) {
            return Err(format!(
                "{}: shim __yoake_cs_{id} ({}) has no call in source; pass --tombstone-site {} to remove it",
                files[fi].path.display(),
                entry.key,
                entry.key
            ));
        }
        let expected_callee = existing_sites.get(&id).map(|s| s.callee_path.as_str());
        match verify_shim_shape(
            shim,
            id,
            &entry.key,
            crate_ident,
            expected_callee,
            &files[fi].style,
            &files[fi].path,
        ) {
            Ok(status) => {
                if status.body_old_method_form {
                    check_failures.push(format!(
                        "{}: shim __yoake_cs_{id}: shim body not fully qualified",
                        files[fi].path.display()
                    ));
                }
                if status.attr_needs_update {
                    check_failures.push(format!(
                        "{}: shim __yoake_cs_{id}: shim attribute missing yoake-callsite-baseline wrapper",
                        files[fi].path.display()
                    ));
                }
            }
            Err(msg) => check_failures.push(msg),
        }
    }

    for (&id, entry) in &live_by_id {
        if !shim_calls.contains_key(&id) && !shims_by_id.contains_key(&id) {
            return Err(format!(
                "callsite lost: {} (id={id}) is missing from source; pass --tombstone-site {} or --rename-site {}=<NEW_KEY> (or re-run with --thir)",
                entry.key, entry.key, entry.key
            ));
        }
    }

    summary.eligible = live_by_id.len();
    summary.rewritten = live_by_id.len();
    summary.print();

    let _ = config.mode;
    if check_failures.is_empty() {
        println!("check: clean (no changes)");
        Ok(true)
    } else {
        println!("check: changes needed:");
        for msg in check_failures {
            println!("  {msg}");
        }
        Ok(false)
    }
}

struct CandidateCall {
    file_idx: usize,
    caller_id: u32,
    callee_fn: Option<u32>,
    callee_path: String,
    /// `callee_path` with private-module segments dropped (what the shim body names).
    render_callee_path: String,
    base_key: String,
    orig: String,
    site: Site,
    shim_sig: ShimSignature,
    adj_prefix: String,
    turbofish_src: Option<String>,
    cfg_attrs: Vec<String>,
    detail: SynCallDetail,
    span: SpanRange,
}

#[derive(Clone)]
struct ExcludedCall {
    base_key: String,
    reason: String,
    manual: bool,
    from_hot_caller: bool,
    exact_manual_key: Option<String>,
}

struct RewrittenCallRef {
    file_idx: usize,
    shim_id: u32,
    caller_fn_id: Option<u32>,
    caller_fn_key: String,
    recv_ty: Option<String>,
    thir_args_valid: bool,
    thir_ret_valid: bool,
    detail: SynCallDetail,
}

#[allow(clippy::too_many_arguments)]
fn execute_with_thir(
    config: &Config,
    crate_ident: &str,
    ledger_set: &mut LedgerSet,
    manual_keys: &BTreeMap<String, String>,
    site_manual_keys: &BTreeMap<String, (String, SiteMeta)>,
    existing_sites: &BTreeMap<u32, SiteMeta>,
    fn_ledger: &FnLedgerIndex,
    static_index: &mut StaticParamIndex,
    files: &[CollectedFile],
    thir_dump: &ThirDump,
) -> Result<bool, String> {
    let allowlist = CallsiteAllowlist::load(&config.ledger)?;
    let track_caller_set = track_caller::load_track_caller_file(&config.ledger)?;
    let hot_callers = load_hot_callers_file(&config.ledger)?;

    let scanned_paths: Vec<String> = files
        .iter()
        .map(|f| norm_slash(&f.path.to_string_lossy()))
        .collect();
    let mut thir_by_file: BTreeMap<usize, Vec<&ThirCall>> = BTreeMap::new();
    for call in &thir_dump.calls {
        if call.ctxt != 0 || (call.kind != "method" && call.kind != "path") {
            continue;
        }
        if let Some(fi) = match_thir_file(&call.file, &scanned_paths) {
            thir_by_file.entry(fi).or_default().push(call);
        }
    }

    let mut summary = CallsiteSummary::default();
    let mut candidates: Vec<CandidateCall> = Vec::new();
    let mut excluded_calls: Vec<ExcludedCall> = Vec::new();
    let mut rewritten_refs: Vec<RewrittenCallRef> = Vec::new();
    let mut inside_shim_thir: BTreeMap<u32, &ThirCall> = BTreeMap::new();
    let mut scanned_fn_ids = BTreeSet::new();
    let mut scanned_fn_keys = BTreeSet::new();
    let mut new_snapshots: Vec<CallerSnapshot> = Vec::new();

    for (fi, file) in files.iter().enumerate() {
        let mut syn_by_span: BTreeMap<SpanRange, (usize, usize)> = BTreeMap::new();
        for (ci, caller) in file.callers.iter().enumerate() {
            scanned_fn_keys.insert(caller.fn_key.clone());
            if let Some(id) = caller.fn_id {
                scanned_fn_ids.insert(id);
            }
            new_snapshots.push(caller.snapshot.clone());
            for (ki, call) in caller.calls.iter().enumerate() {
                syn_by_span.insert(call.span, (ci, ki));
            }
        }

        let mut matched_syn: BTreeSet<(usize, usize)> = BTreeSet::new();
        if let Some(thir_calls) = thir_by_file.get(&fi) {
            for thir_call in thir_calls {
                if let Some(shim) = file
                    .existing_shims
                    .iter()
                    .find(|s| span_contains(s.span, thir_call.span))
                {
                    if let Some(shim_id) = shim.ident_id {
                        inside_shim_thir.entry(shim_id).or_insert(thir_call);
                    }
                    continue;
                }
                if file
                    .cfg_test_spans
                    .iter()
                    .any(|sp| span_contains(*sp, thir_call.span))
                {
                    continue;
                }
                if let Some(&(ci, ki)) = syn_by_span.get(&thir_call.span) {
                    matched_syn.insert((ci, ki));
                    summary.joined += 1;
                    let caller = &file.callers[ci];
                    let syn_call = &caller.calls[ki];
                    if let Some(shim_id) = syn_call.detail.existing_shim_id {
                        rewritten_refs.push(RewrittenCallRef {
                            file_idx: fi,
                            shim_id,
                            caller_fn_id: caller.fn_id,
                            caller_fn_key: caller.fn_key.clone(),
                            recv_ty: thir_call.args.first().and_then(|a| a.ty.clone()),
                            thir_args_valid: thir_call.args.iter().all(|a| a.ty.is_some()),
                            thir_ret_valid: thir_call.ret_ty.is_some(),
                            detail: syn_call.detail.clone(),
                        });
                        continue;
                    }
                    let is_path_call = !syn_call.detail.is_method;
                    let callee_path = if is_path_call
                        && thir_call.callee.starts_with("<Self as ")
                        && let Some((trait_part, fn_name)) =
                            thir_call.callee.strip_prefix("<Self as ").and_then(|r| r.rsplit_once(">::"))
                    {
                        format!("{trait_part}::{fn_name}")
                    } else {
                        thir_call.callee.clone()
                    };
                    let callee_fn = fn_ledger.lookup_callee(thir_call, crate_ident);
                    let caller_prefix = caller
                        .fn_id
                        .map(|id| format!("fn:{id}"))
                        .unwrap_or_else(|| caller.fn_key.clone());
                    let callee_part = callee_fn
                        .map(|id| format!("fn:{id}"))
                        .unwrap_or_else(|| callee_path.clone());
                    let base_key = format!("{caller_prefix}@call:{callee_part}");

                    if let Some(reason) = hot_callers.get(&caller.fn_key) {
                        excluded_calls.push(ExcludedCall {
                            base_key,
                            reason: reason.clone(),
                            manual: true,
                            from_hot_caller: true,
                            exact_manual_key: None,
                        });
                        continue;
                    }
                    if thir_call.kind != "method" {
                        excluded_calls.push(ExcludedCall {
                            base_key,
                            reason: "path call".to_string(),
                            manual: false,
                            from_hot_caller: false,
                            exact_manual_key: None,
                        });
                        continue;
                    }
                    let Some(caller_id) = caller.fn_id else {
                        excluded_calls.push(ExcludedCall {
                            base_key,
                            reason: "caller not in fn ledger".to_string(),
                            manual: false,
                            from_hot_caller: false,
                            exact_manual_key: None,
                        });
                        continue;
                    };
                    // A human-written (manual) exclusion always wins (SF3), e.g. a site whose
                    // argument type is only nameable through a private module.
                    if let Some(reason) = manual_keys.get(&base_key) {
                        excluded_calls.push(ExcludedCall {
                            base_key,
                            reason: reason.clone(),
                            manual: true,
                            from_hot_caller: false,
                            exact_manual_key: None,
                        });
                        continue;
                    }
                    let recv_ty_opt = thir_call.args.first().and_then(|a| a.ty.as_deref());
                    if let Err(reason) = check_callee_policy(
                        &callee_path,
                        recv_ty_opt,
                        crate_ident,
                        config.engine_crates.as_deref(),
                        &thir_dump.externs,
                        &allowlist,
                        &track_caller_set,
                    ) {
                        excluded_calls.push(ExcludedCall {
                            base_key,
                            reason: reason.to_string(),
                            manual: false,
                            from_hot_caller: false,
                            exact_manual_key: None,
                        });
                        continue;
                    }
                    if thir_call.resolution != "concrete" {
                        let reason = match thir_call.resolution.as_str() {
                            "dyn" => "dyn receiver".to_string(),
                            "generic" => "generic receiver".to_string(),
                            other => format!("non-concrete resolution ({other})"),
                        };
                        excluded_calls.push(ExcludedCall {
                            base_key,
                            reason,
                            manual: false,
                            from_hot_caller: false,
                            exact_manual_key: None,
                        });
                        continue;
                    }
                    static_index.ensure_crates_in_text(&callee_path);
                    for arg in &thir_call.args {
                        if let Some(ty) = arg.ty.as_deref() {
                            static_index.ensure_crates_in_text(ty);
                        }
                    }
                    if let Some(ty) = thir_call.ret_ty.as_deref() {
                        static_index.ensure_crates_in_text(ty);
                    }
                    let static_params = static_index.lookup_callee(thir_call, crate_ident, &callee_path);
                    let shim_sig = match validate_and_format_shim_sig(
                        thir_call,
                        static_params.as_deref(),
                        &static_index.aliases,
                        is_path_call,
                    ) {
                        Ok(sig) => sig,
                        Err(reason) => {
                            excluded_calls.push(ExcludedCall {
                                base_key,
                                reason: reason.to_string(),
                                manual: false,
                                from_hot_caller: false,
                                exact_manual_key: None,
                            });
                            continue;
                        }
                    };
                    let mut shim_sig = shim_sig;
                    let render_callee_path;
                    {
                        let pm = &static_index.private_mods;
                        for ty in shim_sig.arg_tys.iter_mut() {
                            *ty = publicize_paths(ty, &caller.fn_key, crate_ident, pm);
                        }
                        if let Some(ret) = shim_sig.ret_ty.as_mut() {
                            *ret = publicize_paths(ret, &caller.fn_key, crate_ident, pm);
                        }
                        render_callee_path = publicize_paths(&callee_path, &caller.fn_key, crate_ident, pm);
                    }
                    let adj_prefix = if is_path_call {
                        String::new()
                    } else {
                        recv_adjust_prefix(thir_call.recv_adjust.as_ref())?
                    };
                    let mut site = syn_call.site.clone();
                    site.callee = callee_part;
                    let orig =
                        file.source[syn_call.detail.recv_start..syn_call.detail.call_end].to_string();
                    candidates.push(CandidateCall {
                        file_idx: fi,
                        caller_id,
                        callee_fn,
                        callee_path,
                        render_callee_path,
                        base_key,
                        orig,
                        site,
                        shim_sig,
                        adj_prefix,
                        turbofish_src: syn_call.detail.turbofish_src.clone(),
                        cfg_attrs: caller.cfg_attrs.clone(),
                        detail: syn_call.detail.clone(),
                        span: thir_call.span,
                    });
                } else if let Some(caller) = file.callers.iter().find(|c| {
                    c.macro_spans
                        .iter()
                        .any(|ms| span_contains(*ms, thir_call.span))
                }) {
                    let callee_fn = fn_ledger.lookup_callee(thir_call, crate_ident);
                    let caller_prefix = caller
                        .fn_id
                        .map(|id| format!("fn:{id}"))
                        .unwrap_or_else(|| caller.fn_key.clone());
                    let callee_part = callee_fn
                        .map(|id| format!("fn:{id}"))
                        .unwrap_or_else(|| thir_call.callee.clone());
                    let (reason, manual, from_hot_caller) =
                        if let Some(reason) = hot_callers.get(&caller.fn_key) {
                            (reason.clone(), true, true)
                        } else {
                            ("inside macro invocation".to_string(), false, false)
                        };
                    excluded_calls.push(ExcludedCall {
                        base_key: format!("{caller_prefix}@call:{callee_part}"),
                        reason,
                        manual,
                        from_hot_caller,
                        exact_manual_key: None,
                    });
                } else if file
                    .top_macro_spans
                    .iter()
                    .any(|ms| span_contains(*ms, thir_call.span))
                {
                    summary.exclude("inside macro invocation");
                } else {
                    summary.unjoined_thir.push(format!(
                        "{}:{}:{}: {}",
                        file.path.display(),
                        thir_call.span[0],
                        thir_call.span[1],
                        thir_call.callee
                    ));
                }
            }
        }

        for (ci, caller) in file.callers.iter().enumerate() {
            for (ki, call) in caller.calls.iter().enumerate() {
                if !matched_syn.contains(&(ci, ki)) {
                    summary.unjoined_syn.push(format!(
                        "{}:{}:{}: {}",
                        file.path.display(),
                        call.span[0],
                        call.span[1],
                        call.site.callee
                    ));
                }
            }
        }
    }

    for hot_key in hot_callers.keys() {
        if let Some((crate_seg, _)) = hot_key.split_once("::")
            && key::normalize_crate_name(crate_seg) != crate_ident
        {
            continue;
        }
        if !scanned_fn_keys.contains(hot_key) {
            eprintln!(
                "warning: callsite-hot-callers.txt key '{hot_key}' matched no fn in scanned modules"
            );
        }
    }

    let mut candidate_sites: Vec<Site> = candidates.iter().map(|c| c.site.clone()).collect();
    assign_dup_ranks(&mut candidate_sites);
    for (cand, site) in candidates.iter_mut().zip(candidate_sites) {
        cand.site = site;
    }

    if !site_manual_keys.is_empty() {
        candidates = filter_site_manual_exclusions(
            candidates,
            site_manual_keys,
            existing_sites,
            &mut excluded_calls,
        );
    }

    reconcile_and_plan(
        config,
        crate_ident,
        ledger_set,
        manual_keys,
        &hot_callers,
        existing_sites,
        &allowlist,
        &track_caller_set,
        &thir_dump.externs,
        &inside_shim_thir,
        files,
        &scanned_fn_ids,
        &scanned_fn_keys,
        &new_snapshots,
        &rewritten_refs,
        &candidates,
        &excluded_calls,
        &mut summary,
    )
}

fn site_meta_matches_candidate_base(cand: &CandidateCall, meta: &SiteMeta) -> bool {
    cand.caller_id == meta.caller
        && cand.callee_fn == meta.callee_fn
        && cand.callee_path == meta.callee_path
        && format_hash(cand.site.anchor) == meta.anchor
}

/// Matches tombstoned manual-exclusion site metadata against candidate calls.
/// Matches by `dup_rank` first so identical zero-context duplicate siblings never steal a live sibling's slot.
fn filter_site_manual_exclusions(
    candidates: Vec<CandidateCall>,
    site_manual_keys: &BTreeMap<String, (String, SiteMeta)>,
    existing_sites: &BTreeMap<u32, SiteMeta>,
    excluded_calls: &mut Vec<ExcludedCall>,
) -> Vec<CandidateCall> {
    let mut matched_excl: Vec<Option<(String, String)>> = vec![None; candidates.len()];
    let mut consumed: BTreeSet<String> = BTreeSet::new();

    for (ci, cand) in candidates.iter().enumerate() {
        if let Some((excl_key, (reason, _))) = site_manual_keys.iter().find(|(ek, (_, meta))| {
            !consumed.contains(ek.as_str())
                && site_meta_matches_candidate_base(cand, meta)
                && cand.site.dup_rank == meta.dup_rank
        }) {
            consumed.insert(excl_key.clone());
            matched_excl[ci] = Some((excl_key.clone(), reason.clone()));
        }
    }

    for (ci, cand) in candidates.iter().enumerate() {
        if matched_excl[ci].is_some() {
            continue;
        }
        let ctx0_hex = format_hash(cand.site.context.0);
        let ctx1_hex = format_hash(cand.site.context.1);
        if ctx0_hex == "0000000000000000" && ctx1_hex == "0000000000000000" {
            continue;
        }
        if existing_sites.values().any(|meta| {
            site_meta_matches_candidate_base(cand, meta) && cand.site.dup_rank == meta.dup_rank
        }) {
            continue;
        }
        if let Some((excl_key, (reason, _))) = site_manual_keys.iter().find(|(ek, (_, meta))| {
            !consumed.contains(ek.as_str())
                && site_meta_matches_candidate_base(cand, meta)
                && meta.context == [ctx0_hex.clone(), ctx1_hex.clone()]
        }) {
            consumed.insert(excl_key.clone());
            matched_excl[ci] = Some((excl_key.clone(), reason.clone()));
        }
    }

    let mut kept = Vec::with_capacity(candidates.len());
    for (ci, cand) in candidates.into_iter().enumerate() {
        if let Some((excl_key, reason)) = matched_excl[ci].take() {
            excluded_calls.push(ExcludedCall {
                base_key: cand.base_key,
                reason,
                manual: true,
                from_hot_caller: false,
                exact_manual_key: Some(excl_key),
            });
        } else {
            kept.push(cand);
        }
    }
    kept
}

fn site_meta_from_candidate(id: u32, cand: &CandidateCall) -> SiteMeta {
    SiteMeta {
        caller: cand.caller_id,
        callee_fn: cand.callee_fn,
        callee_path: cand.callee_path.clone(),
        anchor: format_hash(cand.site.anchor),
        stmt_path: cand.site.stmt_path_hashes.iter().map(|&h| format_hash(h)).collect(),
        context: [
            format_hash(cand.site.context.0),
            format_hash(cand.site.context.1),
        ],
        dup_rank: cand.site.dup_rank,
        shim: format!("__yoake_cs_{id}"),
        orig: Some(cand.orig.clone()),
    }
}

fn record_from_meta(id: u32, meta: &SiteMeta) -> Result<Record, String> {
    let anchor = parse_hash(&meta.anchor)
        .ok_or_else(|| format!("invalid anchor hex {:?} for callsite id {id}", meta.anchor))?;
    let mut stmt_path_hashes = Vec::with_capacity(meta.stmt_path.len());
    for h in &meta.stmt_path {
        stmt_path_hashes.push(
            parse_hash(h)
                .ok_or_else(|| format!("invalid stmt_path hex {:?} for callsite id {id}", h))?,
        );
    }
    let prev = parse_hash(&meta.context[0])
        .ok_or_else(|| format!("invalid context[0] hex {:?} for callsite id {id}", meta.context[0]))?;
    let next = parse_hash(&meta.context[1])
        .ok_or_else(|| format!("invalid context[1] hex {:?} for callsite id {id}", meta.context[1]))?;
    let callee = meta
        .callee_fn
        .map(|cid| format!("fn:{cid}"))
        .unwrap_or_else(|| meta.callee_path.clone());
    Ok(Record {
        id,
        caller: format!("fn:{}", meta.caller),
        callee,
        anchor,
        stmt_path_hashes,
        context: (prev, next),
        dup_rank: meta.dup_rank,
    })
}

fn display_rel_path(crate_root: &Path, file_path: &Path) -> String {
    let rel = file_path.strip_prefix(crate_root).unwrap_or(file_path);
    norm_slash(&rel.to_string_lossy())
}

fn candidate_loc_and_text(
    crate_root: &Path,
    files: &[CollectedFile],
    cand: &CandidateCall,
) -> (String, String) {
    let file = &files[cand.file_idx];
    let rel = display_rel_path(crate_root, &file.path);
    let loc = format!("{rel}:{}:{}", cand.span[0], cand.span[1]);
    let text = &file.source[cand.detail.recv_start..cand.detail.call_end];
    let single_line = text.split_whitespace().collect::<Vec<_>>().join(" ");
    (loc, single_line)
}

fn strip_dup_suffix(key: &str) -> &str {
    match key.rsplit_once('#') {
        Some((prefix, num)) if !num.is_empty() && num.bytes().all(|b| b.is_ascii_digit()) => prefix,
        _ => key,
    }
}

fn candidate_matches_key(cand: &CandidateCall, target_key: &str) -> bool {
    let base = strip_dup_suffix(target_key);
    let alt_key = format!("{}@call:{}", cand.site.caller, cand.callee_path);
    cand.base_key == target_key || cand.base_key == base || alt_key == target_key || alt_key == base
}

fn update_site_meta_for_renamed_key(meta: &mut SiteMeta, new_key: &str) {
    let Some((caller_part, callee_part)) = new_key.split_once("@call:") else {
        return;
    };
    if let Some(id_str) = caller_part.strip_prefix("fn:")
        && let Ok(caller_id) = id_str.parse::<u32>()
    {
        meta.caller = caller_id;
    }
    let callee_base = strip_dup_suffix(callee_part);
    if let Some(id_str) = callee_base.strip_prefix("fn:")
        && let Ok(callee_id) = id_str.parse::<u32>()
    {
        meta.callee_fn = Some(callee_id);
    } else {
        meta.callee_fn = None;
        meta.callee_path = callee_base.to_string();
    }
}

fn find_candidates_by_location(
    crate_root: &Path,
    files: &[CollectedFile],
    candidates: &[CandidateCall],
    accept: &AcceptSite,
) -> Vec<usize> {
    let norm_target = norm_slash(&accept.file);
    let mut exact = Vec::new();
    let mut suffix = Vec::new();
    for (ci, cand) in candidates.iter().enumerate() {
        if cand.span[0] != accept.line || cand.span[1] != accept.col {
            continue;
        }
        let path = &files[cand.file_idx].path;
        let rel = display_rel_path(crate_root, path);
        let full = norm_slash(&path.to_string_lossy());
        if rel == norm_target || full == norm_target {
            exact.push(ci);
        } else if path_matches_suffix(&full, &norm_target) {
            suffix.push(ci);
        }
    }
    if !exact.is_empty() { exact } else { suffix }
}

struct ResolutionState<'a> {
    config: &'a Config,
    crate_ident: &'a str,
    ledger_set: &'a mut LedgerSet,
    existing_sites: &'a BTreeMap<u32, SiteMeta>,
    files: &'a [CollectedFile],
    candidates: &'a [CandidateCall],
    rewritten_by_id: &'a BTreeMap<u32, Vec<usize>>,
    kept_rewritten_ids: &'a mut BTreeSet<u32>,
    renamed_rewritten: &'a mut BTreeMap<u32, String>,
    old_records: &'a mut Vec<Record>,
    old_keys_by_id: &'a mut BTreeMap<u32, String>,
    used_keys: &'a mut BTreeSet<String>,
    updated_sites: &'a mut BTreeMap<u32, SiteMeta>,
    bound_candidates: &'a mut BTreeMap<usize, (u32, String)>,
    bound_old_ids: &'a mut BTreeSet<u32>,
}

fn resolve_rename_sites(state: &mut ResolutionState<'_>) -> Result<(), String> {
    let accept_keys: BTreeSet<&str> = state
        .config
        .accept_sites
        .iter()
        .map(|a| a.key.as_str())
        .collect();
    for (old_key, new_key) in &state.config.rename_sites {
        if old_key == new_key {
            return Err(format!(
                "--rename-site '{old_key}={new_key}': old and new keys are identical; use --accept-site KEY@FILE:LINE:COL for moved or changed sites"
            ));
        }
        let old_id = {
            let shard = state.ledger_set.shard(state.crate_ident).ok_or_else(|| {
                format!("--rename-site '{old_key}={new_key}': missing ledger shard")
            })?;
            shard
                .live()
                .find(|e| e.kind == Kind::Callsite && e.key == *old_key)
                .map(|e| e.id)
                .ok_or_else(|| {
                    format!(
                        "--rename-site '{old_key}={new_key}': '{old_key}' is not a live callsite in ledger"
                    )
                })?
        };
        if state.bound_old_ids.contains(&old_id) {
            return Err(format!("duplicate resolution flag for callsite '{old_key}'"));
        }

        if state.rewritten_by_id.contains_key(&old_id) {
            state
                .ledger_set
                .shard_mut(state.crate_ident)
                .rename(old_key, new_key)
                .map_err(|e| format!("--rename-site '{old_key}={new_key}' failed: {e}"))?;
            state.used_keys.remove(old_key);
            state.used_keys.insert(new_key.clone());
            state.kept_rewritten_ids.insert(old_id);
            state.renamed_rewritten.insert(old_id, new_key.clone());
            state.bound_old_ids.insert(old_id);
            if let Some(meta) = state.updated_sites.get_mut(&old_id) {
                update_site_meta_for_renamed_key(meta, new_key);
            }
            continue;
        }

        if !state.old_keys_by_id.contains_key(&old_id) {
            let meta = state.existing_sites.get(&old_id).ok_or_else(|| {
                format!("live callsite '{old_key}' (id={old_id}) is missing site metadata in ledger")
            })?;
            state.old_records.push(record_from_meta(old_id, meta)?);
        }

        state
            .ledger_set
            .shard_mut(state.crate_ident)
            .rename(old_key, new_key)
            .map_err(|e| format!("--rename-site '{old_key}={new_key}' failed: {e}"))?;
        state.used_keys.remove(old_key);
        state.used_keys.insert(new_key.clone());
        state.old_keys_by_id.insert(old_id, new_key.clone());

        if accept_keys.contains(new_key.as_str()) {
            continue;
        }

        let matches: Vec<usize> = state
            .candidates
            .iter()
            .enumerate()
            .filter(|(ci, cand)| {
                !state.bound_candidates.contains_key(ci) && candidate_matches_key(cand, new_key)
            })
            .map(|(ci, _)| ci)
            .collect();
        if matches.is_empty() {
            return Err(format!(
                "--rename-site '{old_key}={new_key}': no matching unrewritten candidate site in source for '{new_key}'"
            ));
        }
        if matches.len() > 1 {
            let desc: Vec<String> = matches
                .iter()
                .map(|&ci| {
                    let (loc, text) = candidate_loc_and_text(
                        &state.config.crate_root,
                        state.files,
                        &state.candidates[ci],
                    );
                    format!(
                        "  candidate {loc} `{text}` (pass --rename-site {old_key}={new_key} --accept-site {new_key}@{loc})"
                    )
                })
                .collect();
            return Err(format!(
                "--rename-site '{old_key}={new_key}' matches multiple candidates:\n{}",
                desc.join("\n")
            ));
        }
        let ci = matches[0];
        state.bound_old_ids.insert(old_id);
        state.bound_candidates.insert(ci, (old_id, new_key.clone()));
        state.ledger_set.assign(
            state.crate_ident,
            Kind::Callsite,
            new_key,
            &state.candidates[ci].shim_sig.sig_hash,
        );
    }
    Ok(())
}

fn resolve_accept_sites(state: &mut ResolutionState<'_>) -> Result<(), String> {
    for accept in &state.config.accept_sites {
        let Some((&old_id, _)) = state.old_keys_by_id.iter().find(|(_, k)| **k == accept.key)
        else {
            let is_rewritten = state
                .ledger_set
                .shard(state.crate_ident)
                .is_some_and(|shard| {
                    shard.live().any(|e| {
                        e.kind == Kind::Callsite
                            && e.key == accept.key
                            && state.rewritten_by_id.contains_key(&e.id)
                    })
                });
            if is_rewritten {
                return Err(format!(
                    "--accept-site '{}@{}:{}:{}': '{}' is already rewritten in source",
                    accept.key, accept.file, accept.line, accept.col, accept.key
                ));
            }
            return Err(format!(
                "--accept-site '{}@{}:{}:{}': '{}' is not an unrewritten live callsite in scanned modules",
                accept.key, accept.file, accept.line, accept.col, accept.key
            ));
        };
        if state.bound_old_ids.contains(&old_id) {
            return Err(format!(
                "duplicate resolution flag for callsite '{}'",
                accept.key
            ));
        }
        let matches = find_candidates_by_location(
            &state.config.crate_root,
            state.files,
            state.candidates,
            accept,
        );
        if matches.is_empty() {
            return Err(format!(
                "--accept-site '{}@{}:{}:{}': no unrewritten candidate site at {}:{}:{}",
                accept.key, accept.file, accept.line, accept.col, accept.file, accept.line, accept.col
            ));
        }
        if matches.len() > 1 {
            let desc: Vec<String> = matches
                .iter()
                .map(|&ci| {
                    let (loc, text) = candidate_loc_and_text(
                        &state.config.crate_root,
                        state.files,
                        &state.candidates[ci],
                    );
                    format!("  candidate {loc} `{text}`")
                })
                .collect();
            return Err(format!(
                "--accept-site '{}@{}:{}:{}' matches multiple candidates:\n{}",
                accept.key,
                accept.file,
                accept.line,
                accept.col,
                desc.join("\n")
            ));
        }
        let ci = matches[0];
        if state.bound_candidates.contains_key(&ci) {
            return Err(format!(
                "--accept-site '{}@{}:{}:{}': candidate at {}:{}:{} is already bound",
                accept.key, accept.file, accept.line, accept.col, accept.file, accept.line, accept.col
            ));
        }
        let cand = &state.candidates[ci];
        if !candidate_matches_key(cand, &accept.key) {
            return Err(format!(
                "--accept-site '{}@{}:{}:{}': candidate at {}:{}:{} has key '{}', which differs from '{}'; use --rename-site {}={}",
                accept.key,
                accept.file,
                accept.line,
                accept.col,
                accept.file,
                accept.line,
                accept.col,
                cand.base_key,
                accept.key,
                accept.key,
                cand.base_key
            ));
        }
        state.bound_old_ids.insert(old_id);
        state.bound_candidates.insert(ci, (old_id, accept.key.clone()));
        state.ledger_set.assign(
            state.crate_ident,
            Kind::Callsite,
            &accept.key,
            &cand.shim_sig.sig_hash,
        );
    }
    Ok(())
}

fn format_match_errors(
    crate_root: &Path,
    files: &[CollectedFile],
    candidates: &[CandidateCall],
    unmatched_cand_indices: &[usize],
    old_keys_by_id: &BTreeMap<u32, String>,
    outcome: &yoake_callsite_match::Outcome,
) -> Vec<String> {
    let mut errors = Vec::new();
    for (kind, id, ui) in outcome
        .moved
        .iter()
        .map(|&(id, ui)| ("moved", id, ui))
        .chain(outcome.changed.iter().map(|&(id, ui)| ("changed", id, ui)))
        .chain(outcome.fragile.iter().map(|&(id, ui)| ("fragile", id, ui)))
    {
        let ci = unmatched_cand_indices[ui];
        let (loc, text) = candidate_loc_and_text(crate_root, files, &candidates[ci]);
        let old_key = &old_keys_by_id[&id];
        errors.push(format!(
            "callsite {kind}: {old_key} -> candidate {loc} `{text}` (pass --accept-site {old_key}@{loc} or --tombstone-site {old_key})"
        ));
    }
    for (id, cands) in &outcome.ambiguous {
        let old_key = &old_keys_by_id[id];
        let mut lines = vec![format!(
            "callsite ambiguous: {old_key} (id={id}) matches multiple candidates:"
        )];
        for &ui in cands {
            let ci = unmatched_cand_indices[ui];
            let (loc, text) = candidate_loc_and_text(crate_root, files, &candidates[ci]);
            lines.push(format!(
                "  callsite ambiguous: {old_key} -> candidate {loc} `{text}` (pass --accept-site {old_key}@{loc} or --tombstone-site {old_key})"
            ));
        }
        errors.push(lines.join("\n"));
    }
    for id in &outcome.lost {
        let old_key = &old_keys_by_id[id];
        errors.push(format!(
            "callsite lost: {old_key} (id={id}) is no longer in source (pass --tombstone-site {old_key} or --rename-site {old_key}=<NEW_KEY>)"
        ));
    }
    errors
}

struct RetiredSite<'a> {
    id: u32,
    key: String,
    base_key: String,
    reason: String,
    manual: bool,
    from_hot_caller: bool,
    call_ref: &'a RewrittenCallRef,
    orig: Option<String>,
    method_name: String,
    is_path_call: bool,
    orig_func: Option<String>,
    turbofish_src: Option<String>,
}

#[allow(clippy::too_many_arguments)]
fn reconcile_and_plan(
    config: &Config,
    crate_ident: &str,
    ledger_set: &mut LedgerSet,
    manual_keys: &BTreeMap<String, String>,
    hot_callers: &BTreeMap<String, String>,
    existing_sites: &BTreeMap<u32, SiteMeta>,
    allowlist: &CallsiteAllowlist,
    track_caller_set: &BTreeSet<String>,
    thir_externs: &BTreeSet<String>,
    inside_shim_thir: &BTreeMap<u32, &ThirCall>,
    files: &[CollectedFile],
    scanned_fn_ids: &BTreeSet<u32>,
    scanned_fn_keys: &BTreeSet<String>,
    new_snapshots: &[CallerSnapshot],
    rewritten_refs: &[RewrittenCallRef],
    candidates: &[CandidateCall],
    excluded_calls: &[ExcludedCall],
    summary: &mut CallsiteSummary,
) -> Result<bool, String> {
    let mut rewritten_by_id: BTreeMap<u32, Vec<&RewrittenCallRef>> = BTreeMap::new();
    for r in rewritten_refs {
        rewritten_by_id.entry(r.shim_id).or_default().push(r);
    }
    let mut shims_by_id: BTreeMap<u32, (usize, &ExistingShim)> = BTreeMap::new();
    for (fi, file) in files.iter().enumerate() {
        for shim in &file.existing_shims {
            if let Some(id) = shim.ident_id
                && shims_by_id.insert(id, (fi, shim)).is_some()
            {
                return Err(format!("duplicate callsite shim __yoake_cs_{id}"));
            }
        }
    }

    verify_s2_refs(&config.crate_root, files, &shims_by_id)?;

    let mut upgrade_shim_ids: BTreeSet<u32> = BTreeSet::new();
    let mut upgrade_attr_shim_ids: BTreeSet<u32> = BTreeSet::new();
    let mut retired_sites: Vec<RetiredSite<'_>> = Vec::new();
    let mut retired_ids: BTreeSet<u32> = BTreeSet::new();

    for (&id, refs) in &rewritten_by_id {
        let Some(shard) = ledger_set.shard(crate_ident) else {
            return Err(format!("call to __yoake_cs_{id} has no ledger shard"));
        };
        let Some(entry) = shard.live().find(|e| e.id == id && e.kind == Kind::Callsite) else {
            return Err(format!(
                "call to __yoake_cs_{id} in {} has no live callsite entry in ledger",
                files[refs[0].file_idx].path.display()
            ));
        };
        let Some(&(shim_fi, shim)) = shims_by_id.get(&id) else {
            return Err(format!(
                "call to __yoake_cs_{id} in {} has no matching shim fn",
                files[refs[0].file_idx].path.display()
            ));
        };
        for r in refs {
            if r.file_idx != shim_fi {
                return Err(format!(
                    "call to __yoake_cs_{id} in {} is in a different file than its shim",
                    files[r.file_idx].path.display()
                ));
            }
        }
        let site_meta = existing_sites.get(&id);
        let expected_callee = site_meta.map(|s| s.callee_path.as_str());
        let shape_status = verify_shim_shape(
            shim,
            id,
            &entry.key,
            crate_ident,
            expected_callee,
            &files[shim_fi].style,
            &files[shim_fi].path,
        )?;
        if shape_status.body_old_method_form {
            upgrade_shim_ids.insert(id);
        }
        if shape_status.attr_needs_update {
            upgrade_attr_shim_ids.insert(id);
        }

        let r = refs[0];
        let callee_path = site_meta
            .map(|s| s.callee_path.clone())
            .or_else(|| inside_shim_thir.get(&id).map(|tc| tc.callee.clone()));
        let recv_ty_opt = inside_shim_thir
            .get(&id)
            .and_then(|tc| tc.args.first())
            .and_then(|a| a.ty.as_deref())
            .or(r.recv_ty.as_deref());

        let (inelig_reason, inelig_manual, from_hot_caller) =
            if let Some(reason) = hot_callers.get(&r.caller_fn_key) {
                (Some(reason.clone()), true, true)
            } else if r.caller_fn_id.is_none() {
                (Some("caller not in fn ledger".to_string()), false, false)
            } else if let Some(reason) = manual_keys
                .get(&entry.key)
                .or_else(|| manual_keys.get(strip_dup_suffix(&entry.key)))
            {
                (Some(reason.clone()), true, false)
            } else if let Some(cp) = callee_path.as_deref()
                && let Err(reason) = check_callee_policy(
                    cp,
                    recv_ty_opt,
                    crate_ident,
                    config.engine_crates.as_deref(),
                    thir_externs,
                    allowlist,
                    track_caller_set,
                )
            {
                (Some(reason.to_string()), false, false)
            } else if let Some(tc) = inside_shim_thir.get(&id)
                && tc.resolution != "concrete"
            {
                let reason = match tc.resolution.as_str() {
                    "dyn" => "dyn receiver".to_string(),
                    "generic" => "generic receiver".to_string(),
                    other => format!("non-concrete resolution ({other})"),
                };
                (Some(reason), false, false)
            } else if !r.thir_args_valid
                || inside_shim_thir
                    .get(&id)
                    .is_some_and(|tc| tc.args.iter().any(|a| a.ty.is_none()))
            {
                (Some("unwritable arg type".to_string()), false, false)
            } else if !r.thir_ret_valid
                || inside_shim_thir
                    .get(&id)
                    .is_some_and(|tc| tc.ret_ty.is_none())
            {
                (Some("unwritable return type".to_string()), false, false)
            } else {
                (None, false, false)
            };

        if let Some(reason) = inelig_reason {
            let is_path_call = shim.param_names.first().map(String::as_str) != Some("recv");
            let orig_func = match &shim.body {
                ShimBody::QualifiedCall { func_path, .. } => Some(quote!(#func_path).to_string()),
                _ => None,
            };
            let method_name = callee_path
                .as_deref()
                .and_then(|cp| cp.rsplit("::").next())
                .map(str::to_string)
                .or_else(|| match &shim.body {
                    ShimBody::Method { method, .. } => Some(method.clone()),
                    ShimBody::QualifiedCall { func_path, .. } => {
                        func_path.path.segments.last().map(|s| s.ident.to_string())
                    }
                    ShimBody::Other => None,
                })
                .ok_or_else(|| format!("cannot determine method name for shim __yoake_cs_{id}"))?;
            retired_ids.insert(id);
            retired_sites.push(RetiredSite {
                id,
                key: entry.key.clone(),
                base_key: strip_dup_suffix(&entry.key).to_string(),
                reason,
                manual: inelig_manual,
                from_hot_caller,
                call_ref: r,
                orig: site_meta.and_then(|s| s.orig.clone()),
                method_name,
                is_path_call,
                orig_func,
                turbofish_src: shim.turbofish_src.clone(),
            });
        }
    }

    if !retired_sites.is_empty() && !config.retire_ineligible {
        let lines: Vec<String> = retired_sites
            .iter()
            .map(|rs| format!("  {} (id={}, __yoake_cs_{}): {}", rs.key, rs.id, rs.id, rs.reason))
            .collect();
        return Err(format!(
            "already-rewritten callsite(s) are now ineligible (pass --retire-ineligible to un-rewrite and tombstone):\n{}",
            lines.join("\n")
        ));
    }

    for id in &retired_ids {
        upgrade_shim_ids.remove(id);
        upgrade_attr_shim_ids.remove(id);
    }

    let rewritten_file_map: BTreeMap<u32, Vec<usize>> = rewritten_by_id
        .iter()
        .map(|(&id, refs)| (id, refs.iter().map(|r| r.file_idx).collect()))
        .collect();

    let mut tombstones: BTreeSet<String> = config.tombstone_sites.iter().cloned().collect();
    let mut kept_rewritten_ids = BTreeSet::new();
    let mut renamed_rewritten: BTreeMap<u32, String> = BTreeMap::new();
    let mut old_records = Vec::new();
    let mut old_keys_by_id: BTreeMap<u32, String> = BTreeMap::new();
    let mut used_keys: BTreeSet<String> = BTreeSet::new();
    let mut updated_sites = existing_sites.clone();
    let mut all_excluded: Vec<ExcludedCall> = excluded_calls.to_vec();

    let fn_key_by_id: BTreeMap<u32, String> = files
        .iter()
        .flat_map(|f| f.callers.iter())
        .filter_map(|c| c.fn_id.map(|id| (id, c.fn_key.clone())))
        .collect();

    {
        let shard = ledger_set.shard_mut(crate_ident);
        for entry in shard.live() {
            used_keys.insert(entry.key.clone());
        }
        for ex in shard.excluded() {
            if ex.manual {
                used_keys.insert(ex.key.clone());
            }
        }
        let scanned_live: Vec<(u32, String)> = shard
            .live()
            .filter(|e| {
                e.kind == Kind::Callsite
                    && (rewritten_by_id.contains_key(&e.id)
                        || caller_belongs_to_scan(
                            e,
                            existing_sites.get(&e.id),
                            scanned_fn_ids,
                            scanned_fn_keys,
                        ))
            })
            .map(|e| (e.id, e.key.clone()))
            .collect();

        for (id, key) in scanned_live {
            if retired_ids.contains(&id) {
                tombstones.remove(&key);
                shard
                    .tombstone(&key)
                    .map_err(|e| format!("failed to tombstone retired site '{key}': {e}"))?;
            } else if rewritten_by_id.contains_key(&id) {
                if tombstones.contains(&key) {
                    return Err(format!(
                        "cannot tombstone '{key}': call-site shim __yoake_cs_{id} is still present in source"
                    ));
                }
                kept_rewritten_ids.insert(id);
            } else if tombstones.remove(&key) {
                shard
                    .tombstone(&key)
                    .map_err(|e| format!("failed to tombstone '{key}': {e}"))?;
            } else if config.retire_ineligible
                && existing_sites
                    .get(&id)
                    .and_then(|meta| fn_key_by_id.get(&meta.caller))
                    .is_some_and(|ck| hot_callers.contains_key(ck))
            {
                tombstones.remove(&key);
                shard
                    .tombstone(&key)
                    .map_err(|e| format!("failed to tombstone hot-caller site '{key}': {e}"))?;
            } else {
                let meta = existing_sites.get(&id).ok_or_else(|| {
                    format!("live callsite '{key}' (id={id}) is missing site metadata in ledger")
                })?;
                old_records.push(record_from_meta(id, meta)?);
                old_keys_by_id.insert(id, key);
            }
        }
        for rem in tombstones {
            shard
                .tombstone(&rem)
                .map_err(|e| format!("failed to tombstone '{rem}': {e}"))?;
        }
    }

    for rs in &retired_sites {
        all_excluded.push(ExcludedCall {
            base_key: rs.base_key.clone(),
            reason: rs.reason.clone(),
            manual: rs.manual,
            from_hot_caller: rs.from_hot_caller,
            exact_manual_key: None,
        });
    }

    let mut bound_candidates: BTreeMap<usize, (u32, String)> = BTreeMap::new();
    let mut bound_old_ids: BTreeSet<u32> = BTreeSet::new();
    {
        let mut res = ResolutionState {
            config,
            crate_ident,
            ledger_set,
            existing_sites,
            files,
            candidates,
            rewritten_by_id: &rewritten_file_map,
            kept_rewritten_ids: &mut kept_rewritten_ids,
            renamed_rewritten: &mut renamed_rewritten,
            old_records: &mut old_records,
            old_keys_by_id: &mut old_keys_by_id,
            used_keys: &mut used_keys,
            updated_sites: &mut updated_sites,
            bound_candidates: &mut bound_candidates,
            bound_old_ids: &mut bound_old_ids,
        };
        resolve_rename_sites(&mut res)?;
        resolve_accept_sites(&mut res)?;
    }

    let unmatched_old: Vec<Record> = old_records
        .iter()
        .filter(|r| !bound_old_ids.contains(&r.id))
        .cloned()
        .collect();
    let unmatched_cand_indices: Vec<usize> = (0..candidates.len())
        .filter(|ci| !bound_candidates.contains_key(ci))
        .collect();
    let unmatched_sites: Vec<Site> = unmatched_cand_indices
        .iter()
        .map(|&ci| candidates[ci].site.clone())
        .collect();

    let mut dummy_next_id = ledger_set.next_id().max(1);
    let mut outcome = reidentify_with_snapshots(
        &unmatched_old,
        &[],
        &unmatched_sites,
        new_snapshots,
        &mut dummy_next_id,
    );
    if config.patch_reidentify {
        let is_exact_unchanged = |id: u32, ui: usize| {
            let cand = &candidates[unmatched_cand_indices[ui]];
            existing_sites.get(&id).is_some_and(|meta| {
                cand.caller_id == meta.caller
                    && cand.callee_fn == meta.callee_fn
                    && cand.callee_path == meta.callee_path
                    && format_hash(cand.site.anchor) == meta.anchor
                    && cand.site.dup_rank == meta.dup_rank
                    && meta.context
                        == [
                            format_hash(cand.site.context.0),
                            format_hash(cand.site.context.1),
                        ]
            })
        };
        let mut promote = |vec: &mut Vec<(u32, usize)>| {
            let mut rest = Vec::new();
            for (id, ui) in vec.drain(..) {
                if is_exact_unchanged(id, ui) {
                    outcome.confirmed.push((id, ui));
                } else {
                    rest.push((id, ui));
                }
            }
            *vec = rest;
        };
        promote(&mut outcome.fragile);
        promote(&mut outcome.moved);
        promote(&mut outcome.changed);
    }

    let match_errors = format_match_errors(
        &config.crate_root,
        files,
        candidates,
        &unmatched_cand_indices,
        &old_keys_by_id,
        &outcome,
    );
    if !match_errors.is_empty() {
        return Err(match_errors.join("\n"));
    }

    let mut assigned_by_cand: BTreeMap<usize, (u32, String)> = bound_candidates;
    for &(id, ui) in &outcome.confirmed {
        let ci = unmatched_cand_indices[ui];
        let key = old_keys_by_id[&id].clone();
        let cand = &candidates[ci];
        ledger_set.assign(crate_ident, Kind::Callsite, &key, &cand.shim_sig.sig_hash);
        assigned_by_cand.insert(ci, (id, key));
    }
    for &(_, ui) in &outcome.new {
        let ci = unmatched_cand_indices[ui];
        let cand = &candidates[ci];
        let key = allocate_unique_key(&cand.base_key, &mut used_keys);
        let assigned = ledger_set.assign(crate_ident, Kind::Callsite, &key, &cand.shim_sig.sig_hash);
        assigned_by_cand.insert(ci, (assigned.id, key));
    }

    for (&ci, (id, _)) in &assigned_by_cand {
        updated_sites.insert(*id, site_meta_from_candidate(*id, &candidates[ci]));
    }

    let mut emitted_excluded_keys = BTreeSet::new();
    let mut emitted_manual_keys = BTreeSet::new();
    let mut excl_used_keys: BTreeSet<String> = BTreeSet::new();
    for entry in ledger_set.shard_mut(crate_ident).live() {
        excl_used_keys.insert(entry.key.clone());
    }
    for ex in &all_excluded {
        if let Some(exact) = &ex.exact_manual_key {
            excl_used_keys.insert(exact.clone());
        }
    }
    for ex in &all_excluded {
        let ex_key = if let Some(exact) = &ex.exact_manual_key {
            exact.clone()
        } else if !ex.from_hot_caller && manual_keys.contains_key(&ex.base_key) {
            ex.base_key.clone()
        } else {
            allocate_unique_key(&ex.base_key, &mut excl_used_keys)
        };
        emitted_excluded_keys.insert(ex_key.clone());
        if ex.manual {
            ledger_set
                .shard_mut(crate_ident)
                .exclude_manual(Kind::Callsite, &ex_key, &ex.reason)
                .map_err(|e| format!("failed to exclude callsite '{ex_key}': {e}"))?;
            emitted_manual_keys.insert(ex_key);
        } else {
            ledger_set
                .shard_mut(crate_ident)
                .exclude_kind(Kind::Callsite, &ex_key, &ex.reason)
                .map_err(|e| format!("failed to exclude callsite '{ex_key}': {e}"))?;
        }
        summary.exclude(&ex.reason);
    }

    {
        let shard = ledger_set.shard_mut(crate_ident);
        let stale_excluded: Vec<String> = shard
            .excluded()
            .iter()
            .filter(|ex| {
                ex.kind == Kind::Callsite
                    && !ex.manual
                    && !emitted_excluded_keys.contains(&ex.key)
                    && ex.key.split_once("@call:").is_some_and(|(cp, _)| {
                        cp.strip_prefix("fn:")
                            .and_then(|s| s.parse::<u32>().ok())
                            .is_some_and(|id| scanned_fn_ids.contains(&id))
                            || scanned_fn_keys.contains(cp)
                    })
            })
            .map(|ex| ex.key.clone())
            .collect();
        for stale in stale_excluded {
            shard.unexclude(&stale);
        }
    }

    let mut desired_by_file: BTreeMap<usize, Vec<DesiredShim>> = BTreeMap::new();
    for (ci, cand) in candidates.iter().enumerate() {
        let (id, key) = assigned_by_cand[&ci].clone();
        desired_by_file.entry(cand.file_idx).or_default().push(DesiredShim {
            id,
            key,
            cfg_attrs: cand.cfg_attrs.clone(),
            arg_tys: cand.shim_sig.arg_tys.clone(),
            ret_ty: cand.shim_sig.ret_ty.clone(),
            callee_path: cand.render_callee_path.clone(),
            turbofish_src: cand.turbofish_src.clone(),
            is_path_call: !cand.detail.is_method,
        });
    }

    let mut edits_by_file: BTreeMap<usize, Vec<TextEdit>> = BTreeMap::new();
    let mut active_call_spans: Vec<(usize, usize, usize)> = candidates
        .iter()
        .map(|c| (c.file_idx, c.detail.recv_start, c.detail.call_end))
        .collect();
    for r in rewritten_refs {
        active_call_spans.push((r.file_idx, r.detail.recv_start, r.detail.call_end));
    }
    for rs in &retired_sites {
        let call_start = rs.call_ref.detail.recv_start;
        let call_end = rs.call_ref.detail.call_end;
        let fi = rs.call_ref.file_idx;
        let has_nested = active_call_spans
            .iter()
            .any(|&(ofi, s, e)| ofi == fi && call_start <= s && e <= call_end && (call_start, call_end) != (s, e));
        if !has_nested && let Some(orig) = &rs.orig {
            edits_by_file.entry(fi).or_default().push(TextEdit {
                start: call_start,
                end: call_end,
                replacement: orig.clone(),
            });
        } else if rs.is_path_call
            && let Some(orig_func) = &rs.orig_func
        {
            edits_by_file.entry(fi).or_default().push(TextEdit {
                start: rs.call_ref.detail.func_start,
                end: rs.call_ref.detail.func_end,
                replacement: orig_func.clone(),
            });
        } else {
            let Some((arg0_start, arg0_end)) = rs.call_ref.detail.arg0_span else {
                return Err(format!("cannot un-rewrite __yoake_cs_{}: missing receiver arg", rs.id));
            };
            let arg0_src = &files[fi].source[arg0_start..arg0_end];
            let adj_len = strip_adjust_prefix_len(arg0_src);
            edits_by_file.entry(fi).or_default().push(TextEdit {
                start: call_start,
                end: arg0_start + adj_len,
                replacement: String::new(),
            });
            let tf = rs.turbofish_src.as_deref().unwrap_or("");
            if let Some(arg1_start) = rs.call_ref.detail.arg1_start {
                edits_by_file.entry(fi).or_default().push(TextEdit {
                    start: arg0_end,
                    end: arg1_start,
                    replacement: format!(".{}{tf}(", rs.method_name),
                });
            } else {
                edits_by_file.entry(fi).or_default().push(TextEdit {
                    start: arg0_end,
                    end: call_end,
                    replacement: format!(".{}{tf}()", rs.method_name),
                });
            }
        }
    }

    let mut prefix_groups: BTreeMap<(usize, usize), Vec<(usize, String)>> = BTreeMap::new();
    for (ci, cand) in candidates.iter().enumerate() {
        let (id, _) = assigned_by_cand[&ci];
        if !cand.detail.is_method {
            edits_by_file.entry(cand.file_idx).or_default().push(TextEdit {
                start: cand.detail.func_start,
                end: cand.detail.func_end,
                replacement: format!("__yoake_cs_{id}"),
            });
            continue;
        }
        let mut prefix = format!("__yoake_cs_{id}({}", cand.adj_prefix);
        if cand.detail.recv_needs_parens {
            prefix.push('(');
        }
        prefix_groups
            .entry((cand.file_idx, cand.detail.recv_start))
            .or_default()
            .push((cand.detail.call_end, prefix));

        let recv_close = if cand.detail.recv_needs_parens { ")" } else { "" };
        if let Some(first_arg_start) = cand.detail.first_arg_start {
            let after_open = &files[cand.file_idx].source[cand.detail.paren_open_end..first_arg_start];
            let sep = if after_open.starts_with(|c: char| c.is_whitespace()) {
                format!("{recv_close},")
            } else {
                format!("{recv_close}, ")
            };
            edits_by_file.entry(cand.file_idx).or_default().push(TextEdit {
                start: cand.detail.recv_end,
                end: cand.detail.paren_open_end,
                replacement: sep,
            });
        } else {
            edits_by_file.entry(cand.file_idx).or_default().push(TextEdit {
                start: cand.detail.recv_end,
                end: cand.detail.call_end,
                replacement: format!("{recv_close})"),
            });
        }
    }
    for ((fi, recv_start), mut entries) in prefix_groups {
        entries.sort_by(|a, b| b.0.cmp(&a.0));
        let combined: String = entries.into_iter().map(|(_, p)| p).collect();
        edits_by_file.entry(fi).or_default().push(TextEdit {
            start: recv_start,
            end: recv_start,
            replacement: combined,
        });
    }

    let mut file_updates: Vec<FileUpdate> = Vec::new();
    for (fi, file) in files.iter().enumerate() {
        let mut edits = edits_by_file.remove(&fi).unwrap_or_default();
        let new_shims = desired_by_file.remove(&fi).unwrap_or_default();
        let kept_existing: Vec<&ExistingShim> = file
            .existing_shims
            .iter()
            .filter(|s| s.ident_id.is_some_and(|id| kept_rewritten_ids.contains(&id)))
            .collect();

        let nl = edit::line_ending(&file.source);
        let has_renamed_kept = kept_existing
            .iter()
            .any(|ex| ex.ident_id.is_some_and(|id| renamed_rewritten.contains_key(&id)));
        let has_upgraded_kept = kept_existing
            .iter()
            .any(|ex| ex.ident_id.is_some_and(|id| upgrade_shim_ids.contains(&id)));
        let has_attr_upgraded_kept = kept_existing
            .iter()
            .any(|ex| ex.ident_id.is_some_and(|id| upgrade_attr_shim_ids.contains(&id)));
        let need_shim_edit = if new_shims.is_empty()
            && kept_existing.len() == file.existing_shims.len()
            && !has_renamed_kept
            && !has_upgraded_kept
            && !has_attr_upgraded_kept
        {
            !kept_existing.is_empty() && file.shim_header_byte_start.is_none()
        } else {
            true
        };

        if need_shim_edit {
            let mut rendered_parts: Vec<(u32, String)> = Vec::new();
            for ex in &kept_existing {
                let id = ex.ident_id.expect("kept shim has id");
                let mut shim_src = file.source[ex.byte_span.0..ex.byte_span.1].to_string();
                if upgrade_shim_ids.contains(&id)
                    && let Some((bs, be)) = ex.body_byte_span
                {
                    let callee_path = updated_sites
                        .get(&id)
                        .map(|s| s.callee_path.as_str())
                        .or_else(|| inside_shim_thir.get(&id).map(|tc| tc.callee.as_str()))
                        .ok_or_else(|| format!("missing callee_path for shim __yoake_cs_{id}"))?;
                    let recv_ty_str = ex
                        .recv_ty_src
                        .as_deref()
                        .ok_or_else(|| format!("missing recv type for shim __yoake_cs_{id}"))?;
                    let qualified_fn = format_qualified_callee(
                        crate_ident,
                        callee_path,
                        recv_ty_str,
                        ex.turbofish_src.as_deref(),
                    )?;
                    let call_args: Vec<String> = std::iter::once("recv".to_string())
                        .chain((1..ex.param_names.len()).map(|i| format!("a{}", i - 1)))
                        .collect();
                    let rel_bs = bs - ex.byte_span.0;
                    let rel_be = be - ex.byte_span.0;
                    shim_src.replace_range(
                        rel_bs..rel_be,
                        &format!("{qualified_fn}({})", call_args.join(", ")),
                    );
                }
                let new_key = renamed_rewritten.get(&id).map(String::as_str);
                if (new_key.is_some() || upgrade_attr_shim_ids.contains(&id))
                    && let Some((as_, ae)) = ex.attr_byte_span
                    && let Some(key_to_use) = new_key.or(ex.attr_key.as_deref())
                {
                    let rel_s = as_ - ex.byte_span.0;
                    let rel_e = ae - ex.byte_span.0;
                    let new_attr = attr::format_hook_attr(
                        &ExpectedHookAttr {
                            method: false,
                            self_ty_src: None,
                            self_ty_norm: None,
                            id,
                            key: key_to_use,
                            kind: Some("callsite"),
                        },
                        None,
                        ex.attr_path.as_deref(),
                        &file.style,
                    );
                    shim_src.replace_range(rel_s..rel_e, &new_attr);
                }
                rendered_parts.push((id, shim_src));
            }
            for des in &new_shims {
                rendered_parts.push((des.id, des.render(crate_ident, &file.style, nl)?));
            }
            rendered_parts.sort_by_key(|(id, _)| *id);

            let (block_start, block_end) = existing_shim_block_range(file);
            let mut trim_start = block_start;
            while trim_start > 0
                && matches!(file.source.as_bytes()[trim_start - 1], b'\n' | b'\r')
            {
                trim_start -= 1;
            }
            let replacement = if rendered_parts.is_empty() {
                if trim_start == 0 {
                    String::new()
                } else {
                    nl.to_string()
                }
            } else {
                let joined: Vec<String> = rendered_parts.into_iter().map(|(_, s)| s).collect();
                let prefix_nl = if trim_start == 0 {
                    String::new()
                } else {
                    format!("{nl}{nl}")
                };
                format!("{prefix_nl}{SHIM_HEADER}{nl}{}{nl}", joined.join(nl))
            };
            edits.push(TextEdit {
                start: trim_start,
                end: block_end,
                replacement,
            });
        }

        let new_source = edit::apply_edits(&file.source, edits)?;
        if new_source != file.source {
            file_updates.push(FileUpdate {
                path: file.path.clone(),
                original: file.source.clone(),
                updated: new_source,
            });
        }
    }

    summary.eligible = kept_rewritten_ids.len() + candidates.len();
    summary.rewritten = match config.mode {
        Mode::Apply => kept_rewritten_ids.len() + candidates.len(),
        Mode::Check => kept_rewritten_ids.len(),
    };

    let mut manual_set: BTreeSet<String> = manual_keys.keys().cloned().collect();
    manual_set.extend(emitted_manual_keys);
    let staging =
        ledger_io::stage_ledger_set_with_sites(ledger_set, crate_ident, &manual_set, &updated_sites)?;
    let ledger_changed = ledger_io::diff_ledger_dirs(staging.path(), &config.ledger)?;

    summary.print();

    match config.mode {
        Mode::Check => {
            if file_updates.is_empty() && ledger_changed.is_empty() {
                println!("check: clean (no changes)");
                Ok(true)
            } else {
                println!("check: changes needed:");
                for &id in &upgrade_shim_ids {
                    if let Some(&(fi, _)) = shims_by_id.get(&id) {
                        println!(
                            "  {}: shim __yoake_cs_{id}: shim body not fully qualified",
                            files[fi].path.display()
                        );
                    }
                }
                for &id in &upgrade_attr_shim_ids {
                    if let Some(&(fi, _)) = shims_by_id.get(&id) {
                        println!(
                            "  {}: shim __yoake_cs_{id}: shim attribute missing yoake-callsite-baseline wrapper",
                            files[fi].path.display()
                        );
                    }
                }
                for update in &file_updates {
                    println!("  file: {}", update.path.display());
                }
                for path in &ledger_changed {
                    println!("  ledger: {}", path.display());
                }
                Ok(false)
            }
        }
        Mode::Apply => {
            if !file_updates.is_empty() || !ledger_changed.is_empty() {
                let rustfmt_edition = config
                    .rustfmt
                    .then(|| modules::detect_crate_edition(&config.crate_root));
                ledger_io::atomic_apply(
                    &file_updates,
                    staging.path(),
                    &ledger_changed,
                    &config.ledger,
                    rustfmt_edition.as_deref(),
                )?;
            }
            Ok(true)
        }
    }
}

fn existing_shim_block_range(file: &CollectedFile) -> (usize, usize) {
    let mut start = file.source.len();
    if let Some(hdr) = file.shim_header_byte_start {
        start = start.min(hdr);
    }
    for shim in &file.existing_shims {
        start = start.min(shim.byte_span.0);
    }
    (start, file.source.len())
}

pub fn verify_callsites(crate_name: &str, ledger: &Path, thir: &Path) -> Result<bool, String> {
    let crate_ident = key::normalize_crate_name(crate_name);
    let ledger_set = ledger_io::load_ledger_set(ledger)?;
    let sites = ledger_io::read_callsite_sites(ledger, &crate_ident)?;

    let thir_text = std::fs::read_to_string(thir)
        .map_err(|e| format!("failed to read {}: {e}", thir.display()))?;
    let thir_dump: ThirDump = serde_json::from_str(&thir_text)
        .map_err(|e| format!("invalid THIR JSON in {}: {e}", thir.display()))?;
    if let Some(dump_crate) = thir_dump.crate_name.as_deref()
        && key::normalize_crate_name(dump_crate) != crate_ident
    {
        return Err(format!(
            "THIR dump crate '{dump_crate}' does not match --crate-name '{crate_name}'"
        ));
    }

    let mut calls_by_shim: BTreeMap<u32, Vec<&ThirCall>> = BTreeMap::new();
    for call in &thir_dump.calls {
        if call.ctxt != 0 || (call.kind != "path" && call.kind != "method") {
            continue;
        }
        // `#[yoake_hook]` moves the shim's body into `__yoake_orig___yoake_cs_<id>`, so the
        // original call is found there (or directly in `__yoake_cs_<id>` without the macro).
        if let Some(last) = call.caller_def.rsplit("::").next()
            && let Some(id) = parse_shim_ident(last.strip_prefix("__yoake_orig_").unwrap_or(last))
        {
            calls_by_shim.entry(id).or_default().push(call);
        }
    }

    let mut live_entries: Vec<&yoake_hook_ledger::Entry> = ledger_set
        .shard(&crate_ident)
        .map(|shard| shard.live().filter(|e| e.kind == Kind::Callsite).collect())
        .unwrap_or_default();
    live_entries.sort_by_key(|e| e.id);

    let mut patched_ids = BTreeSet::new();
    let patch_file = ledger.join(format!("{crate_ident}.callsites.patch"));
    if let Ok(patch_text) = std::fs::read_to_string(&patch_file) {
        for line in patch_text.lines() {
            if let Some(rest) = line.strip_prefix('+')
                && !rest.starts_with("++")
                && let Some(pos) = rest.find("fn __yoake_cs_")
            {
                let after = &rest[pos + "fn __yoake_cs_".len()..];
                let digits: String = after.chars().take_while(|c| c.is_ascii_digit()).collect();
                if let Ok(id) = digits.parse::<u32>() {
                    patched_ids.insert(id);
                }
            }
        }
    }

    let mut checked = 0usize;
    let mut verified = 0usize;
    let mut issues = Vec::new();

    for entry in live_entries {
        let id = entry.id;
        let Some(meta) = sites.get(&id) else {
            issues.push(format!("missing: id={id} (__yoake_cs_{id}): missing site metadata in ledger"));
            continue;
        };
        let expected = &meta.callee_path;
        match calls_by_shim.get(&id) {
            None => {
                if patched_ids.contains(&id) {
                    continue;
                }
                checked += 1;
                issues.push(format!("missing: id={id} (__yoake_cs_{id}): expected {expected}"));
            }
            Some(calls) if calls.len() != 1 => {
                checked += 1;
                let got: Vec<&str> = calls.iter().map(|c| c.callee.as_str()).collect();
                issues.push(format!(
                    "mismatch: id={id} (__yoake_cs_{id}): expected 1 call to {expected}, found {} ({})",
                    calls.len(),
                    got.join(", ")
                ));
            }
            Some(calls) => {
                checked += 1;
                // The ledger records a trait method from the original method call as
                // `<Self as path::Trait>::m`; the fully qualified shim body is a path call, which THIR
                // names `path::Trait::m`. Both name the same trait item.
                let same_trait_item = |a: &str, b: &str| {
                    let strip = |s: &str| {
                        s.strip_prefix("<Self as ")
                            .and_then(|rest| rest.split_once(">::"))
                            .map(|(tr, m)| format!("{tr}::{m}"))
                            .unwrap_or_else(|| s.to_owned())
                    };
                    strip(a) == strip(b)
                };
                if calls[0].callee == *expected || same_trait_item(&calls[0].callee, expected) {
                    verified += 1;
                } else {
                    issues.push(format!(
                        "mismatch: id={id} (__yoake_cs_{id}): expected {expected}, got {}",
                        calls[0].callee
                    ));
                }
            }
        }
    }

    if issues.is_empty() {
        println!("verified {verified} of {checked}");
        Ok(true)
    } else {
        for issue in &issues {
            eprintln!("{issue}");
        }
        eprintln!("verified {verified} of {checked}");
        Ok(false)
    }
}

