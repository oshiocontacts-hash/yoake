//! Coverage numbers and the unbound lists.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde::Serialize;

use crate::analyze::{Cat, FieldReport, FnReport, ModuleScan};

#[derive(Serialize, Clone, Debug, Default)]
pub struct Counts {
    /// Functions counted (derived trait impls are left out; see `derived`).
    pub total: usize,
    pub bound_a: usize,
    pub bound_mech: usize,
    pub handle_required: usize,
    pub excluded: usize,
    pub derived: usize,
    /// Derived trait methods (`clone`, `eq`, ...) that are bound anyway; not in the percentages.
    pub derived_bound: usize,
    pub fields_total: usize,
    pub fields_bound: usize,
    pub handle_types: usize,
}

impl Counts {
    pub fn bound(&self) -> usize {
        self.bound_a + self.bound_mech
    }
}

pub fn count(scan: &ModuleScan) -> Counts {
    let mut c = Counts::default();
    for f in &scan.fns {
        if f.derived {
            c.derived += 1;
            if matches!(f.cat, Cat::BoundA | Cat::BoundMech) {
                c.derived_bound += 1;
            }
            continue;
        }
        c.total += 1;
        match f.cat {
            Cat::BoundA => c.bound_a += 1,
            Cat::BoundMech => c.bound_mech += 1,
            Cat::HandleRequired => c.handle_required += 1,
            Cat::Excluded => c.excluded += 1,
        }
    }
    c.fields_total = scan.fields.len();
    c.fields_bound = scan.fields.iter().filter(|f| f.shape.is_some()).count();
    c.handle_types = scan.handle_types.len();
    c
}

fn pct(part: usize, total: usize) -> String {
    if total == 0 { "-".to_string() } else { format!("{:.1}%", part as f64 * 100.0 / total as f64) }
}

fn histogram(fns: &[&FnReport], cat: Cat) -> BTreeMap<String, usize> {
    let mut map = BTreeMap::new();
    for f in fns.iter().filter(|f| f.cat == cat) {
        for reason in &f.reasons {
            *map.entry(reason.clone()).or_insert(0) += 1;
        }
    }
    map
}

pub struct ModuleReport<'a> {
    pub label: &'a str,
    pub source: &'a str,
    pub scan: &'a ModuleScan,
    /// The shortest field path from the `Game` root that mentions a handle type.
    pub game_paths: &'a std::collections::BTreeMap<crate::doc::ItemRef, String>,
}

pub fn coverage_md(modules: &[ModuleReport<'_>], unresolved: &[String], delta_note: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Binding coverage (generated by yoake-bindgen)\n");
    let _ = writeln!(out, "Functions counted: free functions, inherent methods, and non-derived trait-impl methods whose body is in the module's own file. Derived trait impls (`Clone`, `Debug`, ...) are listed separately and are not in the denominator.\n");
    let _ = writeln!(out, "| module | functions | a (basic) | b (mechanical) | **bound now** | handle-required | excluded | derived (bound / total) | fields bound / total | handle types |");
    let _ = writeln!(out, "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
    for m in modules {
        let c = count(m.scan);
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | **{} ({})** | {} ({}) | {} ({}) | {} / {} | {} / {} | {} |",
            m.label,
            c.total,
            c.bound_a,
            c.bound_mech,
            c.bound(),
            pct(c.bound(), c.total),
            c.handle_required,
            pct(c.handle_required, c.total),
            c.excluded,
            pct(c.excluded, c.total),
            c.derived_bound,
            c.derived,
            c.fields_bound,
            c.fields_total,
            c.handle_types
        );
    }
    let _ = writeln!(out);
    for m in modules {
        let c = count(m.scan);
        let counted: Vec<&FnReport> = m.scan.fns.iter().filter(|f| !f.derived).collect();
        let _ = writeln!(out, "## `{}` ({})\n", m.label, m.source);
        let _ = writeln!(out, "- bound now: **{} of {}** ({}): {} basic + {} mechanical", c.bound(), c.total, pct(c.bound(), c.total), c.bound_a, c.bound_mech);
        let _ = writeln!(out, "- handle-required, not yet bound: {} ({})", c.handle_required, pct(c.handle_required, c.total));
        let _ = writeln!(out, "- excluded: {} ({})", c.excluded, pct(c.excluded, c.total));
        let _ = writeln!(out, "- field accessors (get + set pairs): {} of {} fields", c.fields_bound, c.fields_total);
        let _ = writeln!(out, "- handle types (receivers of bound methods or owners of bound fields): {}\n", m.scan.handle_types.len());
        let _ = writeln!(out, "### Handle types and how a guest reaches them\n");
        let _ = writeln!(
            out,
            "A type is reachable as a hook argument (`Root::HookArg`) when one of its methods is hooked; every type below has bound methods or accessors. The last column is the shortest chain of `Game` fields that mentions the type (resolution from `Game` is not built; this is where it would start).\n"
        );
        let _ = writeln!(out, "| handle type | bound methods | bound field pairs | from `Game` by field path |\n|---|---:|---:|---|");
        for (item, path) in &m.scan.handle_refs {
            let methods = m.scan.fns.iter().filter(|f| f.recv_ref == Some(*item) && matches!(f.cat, Cat::BoundA | Cat::BoundMech)).count();
            let fields = m.scan.fields.iter().filter(|f| f.owner_ref == *item && f.shape.is_some()).count();
            let reach = m.game_paths.get(item).map(|p| format!("`{p}`")).unwrap_or_else(|| "-".to_string());
            let _ = writeln!(out, "| `{path}` | {methods} | {fields} | {reach} |");
        }
        let _ = writeln!(out);
        for (title, cat) in [("Handle-required: reasons", Cat::HandleRequired), ("Excluded: reasons", Cat::Excluded)] {
            let _ = writeln!(out, "### {title}\n");
            let histogram = histogram(&counted, cat);
            if histogram.is_empty() {
                let _ = writeln!(out, "(none)\n");
                continue;
            }
            let mut rows: Vec<(&String, &usize)> = histogram.iter().collect();
            rows.sort_by(|a, b| b.1.cmp(a.1).then(a.0.cmp(b.0)));
            let _ = writeln!(out, "| reason | occurrences |\n|---|---:|");
            for (reason, n) in rows {
                let _ = writeln!(out, "| {} | {} |", reason.replace('|', "\\|"), n);
            }
            let _ = writeln!(out);
        }
        let _ = writeln!(out, "### Writable fields (setters are opt-in; every other data field is read-only and its setter id is reserved as `ReadOnly`)\n");
        let mut writable: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
        for field in m.scan.fields.iter().filter(|f| f.shape.is_some() && f.writable) {
            writable.entry(field.owner_label.as_str()).or_default().push(field.field.as_str());
        }
        let read_only = m.scan.fields.iter().filter(|f| f.shape.is_some() && !f.writable).count();
        if writable.is_empty() {
            let _ = writeln!(out, "(none writable; {read_only} read-only field accessors)\n");
        } else {
            for (owner, fields) in &writable {
                let _ = writeln!(out, "- `{}`: {}", owner, fields.iter().map(|f| format!("`{f}`")).collect::<Vec<_>>().join(", "));
            }
            let _ = writeln!(out, "\n{} read-only field accessors (getter only).\n", read_only);
        }
        let excluded_fields: Vec<&FieldReport> = m.scan.fields.iter().filter(|f| f.shape.is_none()).collect();
        let _ = writeln!(out, "### Fields without accessors\n");
        if excluded_fields.is_empty() {
            let _ = writeln!(out, "(none)\n");
        } else {
            let mut by_reason: BTreeMap<String, usize> = BTreeMap::new();
            for field in excluded_fields {
                *by_reason.entry(field.reason.clone().unwrap_or_default()).or_insert(0) += 1;
            }
            let _ = writeln!(out, "| reason | fields |\n|---|---:|");
            for (reason, n) in by_reason {
                let _ = writeln!(out, "| {} | {} |", reason.replace('|', "\\|"), n);
            }
            let _ = writeln!(out);
        }
    }
    let _ = writeln!(out, "## External types whose crate JSON was not loaded\n");
    if unresolved.is_empty() {
        let _ = writeln!(out, "(none)\n");
    } else {
        for item in unresolved {
            let _ = writeln!(out, "- `{item}`");
        }
        let _ = writeln!(out);
    }
    if !delta_note.is_empty() {
        let _ = writeln!(out, "## Lock changes in this run\n\n{delta_note}");
    }
    out
}

/// Every function of one module with its category and reasons.
pub fn functions_md(m: &ModuleReport<'_>) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# `{}`: every function ({})\n", m.label, m.source);
    let _ = writeln!(out, "| function | line | receiver | category | reasons |\n|---|---:|---|---|---|");
    let mut fns: Vec<&FnReport> = m.scan.fns.iter().collect();
    fns.sort_by(|a, b| a.path.cmp(&b.path));
    for f in fns {
        let cat = if f.derived {
            "derived (not counted)"
        } else {
            match f.cat {
                Cat::BoundA => "bound (a)",
                Cat::BoundMech => "bound (b, mechanical)",
                Cat::HandleRequired => "handle-required",
                Cat::Excluded => "excluded",
            }
        };
        let reasons = if f.reasons.is_empty() { "-".to_string() } else { f.reasons.join("; ") };
        let _ = writeln!(
            out,
            "| `{}` | {} | {} | {} | {} |",
            f.path.replace('|', "\\|"),
            f.line,
            f.receiver,
            cat,
            reasons.replace('|', "\\|").replace('\n', " ")
        );
    }
    let _ = writeln!(out, "\n## Fields\n\n| field | status |\n|---|---|");
    for field in &m.scan.fields {
        let _ = writeln!(
            out,
            "| `{}.{}` | {} |",
            field.owner_label,
            field.field,
            field.reason.as_deref().map(|r| format!("no accessor: {r}")).unwrap_or_else(|| "get + set".to_string())
        );
    }
    out
}

#[derive(Serialize)]
pub struct SummaryModule {
    pub label: String,
    #[serde(flatten)]
    pub counts: Counts,
}

pub fn summary_json(modules: &[ModuleReport<'_>]) -> String {
    let rows: Vec<SummaryModule> = modules.iter().map(|m| SummaryModule { label: m.label.to_string(), counts: count(m.scan) }).collect();
    let mut text = serde_json::to_string_pretty(&rows).expect("summary serializes");
    text.push('\n');
    text
}
