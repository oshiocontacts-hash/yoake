#!/usr/bin/env python3
"""Index checked-in WIT declarations and native hook catalog coverage."""

import argparse
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
WIT_DIR = ROOT / "crates" / "yoake-wasm" / "wit"
OUTPUT = ROOT / "docs" / "yoake-api-index.md"
DECLARATION = re.compile(r"^(interface|world)\s+([a-z][a-z0-9-]*)\s*\{")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def render():
    catalog = read_json(ROOT / "native-hooks.json")
    fragments = sorted((ROOT / "tools" / "native-hook-fragments").glob("*.json"))
    fragment_catalogs = [read_json(path) for path in fragments]
    hooks = list(catalog["hooks"])
    helpers = list(catalog["helpers"])
    for fragment in fragment_catalogs:
        hooks.extend(fragment.get("hooks", []))
        helpers.extend(fragment.get("helpers", []))
    names = [hook["name"] for hook in hooks]
    if len(set(names)) != len(names):
        raise ValueError("duplicate hook names in catalog")
    coverage = read_json(WIT_DIR / "coverage.json")
    if coverage["hook_count"] != len(hooks):
        raise ValueError("WIT coverage and hook catalog disagree")

    lines = [
        "# Yoake WebAssembly API index",
        "",
        "Generated by `python tools/generate_yoake_api_index.py`; use `--check` to detect a stale index.",
        "This indexes declarations, not a promise that every host operation is implemented or permitted.",
        "See the [Wasm development guide](yoake-wasm-dev.md) for host status and permissions.",
        "",
        "## Component worlds and interfaces",
        "",
        "| WIT file | Kind | Declaration |",
        "| --- | --- | --- |",
    ]
    for filename in ("yoake-mod.wit", "yoake-full.wit"):
        path = WIT_DIR / filename
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = DECLARATION.match(line)
            if match:
                kind, name = match.groups()
                lines.append(
                    f"| `{filename}` | {kind} | [`{name}`]"
                    f"(../crates/yoake-wasm/wit/{filename}#L{number}) |"
                )
    lines.extend(
        [
            "",
            "## Catalog and coverage",
            "",
            "Counts include the [base catalog](../native-hooks.json) and all JSON [fragments](../tools/native-hook-fragments/). Helper counts are catalog entries, not WIT exports.",
            "The [coverage report](../crates/yoake-wasm/wit/coverage.json) describes generated types, not runtime availability.",
            "",
            "| Measure | Count |",
            "| --- | ---: |",
            f"| Base catalog hooks | {len(catalog['hooks'])} |",
            f"| Fragment files | {len(fragments)} |",
            f"| Fragment hooks | {len(hooks) - len(catalog['hooks'])} |",
            f"| Total catalog hooks | {len(hooks)} |",
            f"| Catalog helper entries | {len(helpers)} |",
            f"| Fully typed hooks | {coverage['fully_typed']} |",
            f"| Partially typed hooks | {coverage['partial']} |",
            f"| Hooks with handles | {coverage['with_handles']} |",
            f"| Client hooks | {coverage['client_hooks']} |",
            f"| Server hooks | {coverage['server_hooks']} |",
            f"| Named types | {coverage['named_types']} |",
            "",
            "Client and server hook counts can overlap. Search the catalog or WIT for individual names; use the [SDK](../crates/yoake-wasm-sdk/src/lib.rs) for the Rust-facing API.",
            "",
        ]
    )
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the index is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, f"{OUTPUT} is stale; regenerate it\n")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
